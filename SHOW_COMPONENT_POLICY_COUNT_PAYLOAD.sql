-- Run with the schema containing the OSCAL Component tables selected.
-- Archer field: NUMBER_OF_POLICIES_SOURCE_LEVEL
-- OSCAL path: component-definition.components[].props[]
SELECT p.SOURCE_RECORD_ID AS ARCHER_CONTENT_ID,
       c.OSCAL_UUID AS COMPONENT_UUID,
       c.METADATA_JSON AS COMPONENT_PAYLOAD,
       p.METADATA_JSON:name::VARCHAR AS PROPERTY_NAME,
       p.METADATA_JSON:value AS POLICY_COUNT,
       p.METADATA_JSON AS PROPERTY_PAYLOAD
FROM DIM_OSCAL_COMPONENT_ELEMENT p
JOIN FACT_OSCAL_COMPONENT_DEPENDENCY d
  ON d.FK_TARGET_ELEMENT_HASH = p.PK_DIM_OSCAL_COMPONENT_ELEMENT_HASH
 AND d.DEPENDENCY_TYPE = 'CONTAINS'
JOIN DIM_OSCAL_COMPONENT_ELEMENT c
  ON c.PK_DIM_OSCAL_COMPONENT_ELEMENT_HASH = d.FK_SOURCE_ELEMENT_HASH
 AND c.ELEMENT_TYPE = 'components'
WHERE p.SOURCE_SYSTEM_NAME = 'ARCHER'
  AND p.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
  AND p.ELEMENT_TYPE = 'props'
  AND p.METADATA_JSON:name::VARCHAR = 'policy-count'
ORDER BY p.SOURCE_RECORD_ID
LIMIT 20;
