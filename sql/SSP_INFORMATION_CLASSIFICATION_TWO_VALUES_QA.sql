-- Verify whether 2+ Archer INFORMATION_CLASSIFICATION selections for one
-- Authorization Package Content ID are all present in SSP System Characteristics.
-- Current mapping: APPROVED, archer-select -> system-characteristics.props[].
-- Expected warehouse property name: information-classification.
-- Count DISTINCT resolved labels: the mapper deduplicates identical value identities.
-- Source rows with duplicate Content IDs require the running notebook's
-- approved latest-snapshot selection; report them separately, do not guess.
--
-- 1) Source population summary (all RAW snapshots).
WITH raw AS (
  SELECT CONTENT_ID::STRING AS CID,
         CURATED_JSON:"INFORMATION_CLASSIFICATION" AS CLASSIFICATION,
         COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS SNAPSHOT_ROWS
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
)
SELECT
  COUNT(DISTINCT CID) AS ALL_CONTENT_IDS,
  COUNT(DISTINCT IFF(ARRAY_SIZE(CLASSIFICATION:"ResolvedValues") = 2, CID, NULL))
    AS CONTENT_IDS_WITH_TWO_RESOLVED_VALUES,
  COUNT(DISTINCT IFF(ARRAY_SIZE(CLASSIFICATION:"ResolvedValues") > 2, CID, NULL))
    AS CONTENT_IDS_WITH_MORE_THAN_TWO,
  COUNT(DISTINCT IFF(
      ARRAY_SIZE(CLASSIFICATION:"ResolvedValues") >= 2 AND SNAPSHOT_ROWS > 1,
      CID, NULL)) AS MULTIVALUE_IDS_WITH_DUPLICATE_RAW_SNAPSHOTS
FROM raw;

-- 2) Exact source labels versus persisted, correctly parent-linked DIM props.
-- Inspect QA_STATUS, MISSING_VALUES and EXTRA_VALUES. Private source values
-- remain in Snowflake; do not publish result rows or record IDs to GitHub.
WITH raw AS (
  SELECT CONTENT_ID::STRING AS CID,
         CURATED_JSON:"INFORMATION_CLASSIFICATION" AS CLASSIFICATION,
         COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS SNAPSHOT_ROWS
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
multi_source AS (
  SELECT CID, CLASSIFICATION,
         COALESCE(CLASSIFICATION:"ValuesListIds",
                  CLASSIFICATION:"ValueListIds") AS SELECT_IDS
  FROM raw
  WHERE SNAPSHOT_ROWS = 1
    AND IS_ARRAY(CLASSIFICATION:"ResolvedValues")
    AND ARRAY_SIZE(CLASSIFICATION:"ResolvedValues") >= 2
),
expected AS (
  SELECT s.CID,
         s.CLASSIFICATION,
         ARRAY_SIZE(s.CLASSIFICATION:"ResolvedValues") AS SOURCE_SELECTIONS,
         ARRAY_SIZE(s.SELECT_IDS) AS SOURCE_IDS_COUNT,
         f.INDEX AS SOURCE_POSITION,
         f.VALUE:"ValueName"::STRING AS LABEL,
         f.VALUE:"LookupStatus"::STRING AS LOOKUP_STATUS,
         f.VALUE:"ValueId"::STRING AS RESOLVED_ID,
         GET(s.SELECT_IDS, f.INDEX)::STRING AS SELECT_ID
  FROM multi_source s,
       LATERAL FLATTEN(INPUT => s.CLASSIFICATION:"ResolvedValues") f
),
source_summary AS (
  SELECT CID,
         MAX(SOURCE_SELECTIONS) AS SOURCE_SELECTIONS,
         MAX(SOURCE_IDS_COUNT) AS SOURCE_IDS_COUNT,
         COUNT(DISTINCT LABEL) AS SOURCE_DISTINCT_VALUES,
         LISTAGG(DISTINCT LABEL, ' | ') WITHIN GROUP (ORDER BY LABEL)
           AS SOURCE_VALUES,
         COUNT_IF(LOOKUP_STATUS IS NULL OR LOOKUP_STATUS <> 'MATCHED'
                  OR RESOLVED_ID IS NULL OR SELECT_ID IS NULL
                  OR RESOLVED_ID <> SELECT_ID
                  OR LABEL IS NULL OR LENGTH(TRIM(LABEL)) = 0)
           AS INVALID_RESOLVED_ROWS
  FROM expected
  GROUP BY CID
),
target_props AS (
  SELECT child.SOURCE_RECORD_ID AS CID,
         IFF(IS_NULL_VALUE(child.METADATA_JSON:"value"),
             NULL, child.METADATA_JSON:"value"::STRING) AS LABEL
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT parent
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY edge
    ON edge.FK_SOURCE_ELEMENT_HASH = parent.PK_OSCAL_SSP_ELEMENT_HASH
   AND edge.DEPENDENCY_TYPE = 'CONTAINS'
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT child
    ON child.PK_OSCAL_SSP_ELEMENT_HASH = edge.FK_TARGET_ELEMENT_HASH
  WHERE parent.ELEMENT_TYPE = 'system-characteristics'
    AND child.ELEMENT_TYPE = 'props'
    AND parent.SOURCE_SYSTEM_NAME = 'ARCHER'
    AND parent.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND child.SOURCE_SYSTEM_NAME = parent.SOURCE_SYSTEM_NAME
    AND child.SOURCE_TABLE_NAME = parent.SOURCE_TABLE_NAME
    AND child.SOURCE_RECORD_ID = parent.SOURCE_RECORD_ID
    AND child.METADATA_JSON:"name"::STRING = 'information-classification'
),
target_summary AS (
  SELECT CID,
         COUNT(*) AS TARGET_PROPERTY_ROWS,
         COUNT(DISTINCT LABEL) AS TARGET_DISTINCT_VALUES,
         LISTAGG(DISTINCT LABEL, ' | ') WITHIN GROUP (ORDER BY LABEL)
           AS TARGET_VALUES
  FROM target_props
  GROUP BY CID
),
missing AS (
  SELECT s.CID,
         COUNT(DISTINCT s.LABEL) AS MISSING_VALUE_COUNT,
         LISTAGG(DISTINCT s.LABEL, ' | ') WITHIN GROUP (ORDER BY s.LABEL)
           AS MISSING_VALUES
  FROM expected s
  LEFT JOIN target_props t ON t.CID = s.CID AND t.LABEL = s.LABEL
  WHERE t.CID IS NULL
  GROUP BY s.CID
),
extra AS (
  SELECT t.CID,
         COUNT(*) AS EXTRA_PROPERTY_ROWS,
         LISTAGG(DISTINCT t.LABEL, ' | ') WITHIN GROUP (ORDER BY t.LABEL)
           AS EXTRA_VALUES
  FROM target_props t
  JOIN source_summary ss ON ss.CID = t.CID
  LEFT JOIN expected s ON s.CID = t.CID AND s.LABEL = t.LABEL
  WHERE s.CID IS NULL
  GROUP BY t.CID
),
qa AS (
  SELECT ss.CID,
         ss.SOURCE_SELECTIONS,
         ss.SOURCE_IDS_COUNT,
         ss.SOURCE_DISTINCT_VALUES,
         ss.SOURCE_VALUES,
         COALESCE(t.TARGET_PROPERTY_ROWS, 0) AS TARGET_PROPERTY_ROWS,
         COALESCE(t.TARGET_DISTINCT_VALUES, 0) AS TARGET_DISTINCT_VALUES,
         t.TARGET_VALUES,
         COALESCE(m.MISSING_VALUE_COUNT, 0) AS MISSING_VALUE_COUNT,
         m.MISSING_VALUES,
         COALESCE(x.EXTRA_PROPERTY_ROWS, 0) AS EXTRA_PROPERTY_ROWS,
         x.EXTRA_VALUES,
         CASE
           WHEN ss.SOURCE_IDS_COUNT IS NULL OR
                ss.SOURCE_IDS_COUNT <> ss.SOURCE_SELECTIONS OR
                ss.INVALID_RESOLVED_ROWS > 0
             THEN 'SOURCE_RESOLUTION_INVALID'
           WHEN ss.SOURCE_DISTINCT_VALUES < ss.SOURCE_SELECTIONS
             THEN 'SOURCE_HAS_DUPLICATE_LABELS_REVIEW'
           WHEN COALESCE(t.TARGET_PROPERTY_ROWS, 0) = 0
             THEN 'TARGET_MISSING_ALL'
           WHEN COALESCE(m.MISSING_VALUE_COUNT, 0) > 0
             THEN 'TARGET_MISSING_ONE_OR_MORE_VALUES'
           WHEN COALESCE(x.EXTRA_PROPERTY_ROWS, 0) > 0
             THEN 'TARGET_HAS_UNEXPECTED_VALUES'
           WHEN t.TARGET_PROPERTY_ROWS <> t.TARGET_DISTINCT_VALUES
             THEN 'TARGET_HAS_DUPLICATE_PROPERTIES'
           ELSE 'ALL_VALUES_MATCH'
         END AS QA_STATUS
  FROM source_summary ss
  LEFT JOIN target_summary t ON t.CID = ss.CID
  LEFT JOIN missing m ON m.CID = ss.CID
  LEFT JOIN extra x ON x.CID = ss.CID
)
SELECT CID AS ARCHER_CONTENT_ID,
       SOURCE_SELECTIONS, SOURCE_DISTINCT_VALUES, SOURCE_VALUES,
       TARGET_PROPERTY_ROWS, TARGET_DISTINCT_VALUES, TARGET_VALUES,
       MISSING_VALUE_COUNT, MISSING_VALUES,
       EXTRA_PROPERTY_ROWS, EXTRA_VALUES, QA_STATUS,
       COUNT(*) OVER (PARTITION BY QA_STATUS) AS STATUS_RECORDS_ALL
FROM qa
ORDER BY CASE WHEN QA_STATUS = 'ALL_VALUES_MATCH' THEN 1 ELSE 0 END,
         ARCHER_CONTENT_ID
LIMIT 100;
