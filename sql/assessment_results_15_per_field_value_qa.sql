-- Assessment Results: 15 source records per approved field, VALUE QA (read-only).
-- 2026-10-12 | Source One | 45 approved CSV mappings | no placeholders.
-- Prioritize POPULATED values for each field; missing/null fields are NOT value-tested.
-- Results marked REVIEW must not be called mapping failures without inspection.
WITH mapped AS (
 SELECT column1 AS FIELD_NAME, column2 AS ELEMENT_TYPE, column3 AS TRANSFORM_ID
 FROM VALUES
  ('FINDINGS', 'props', 'direct'),
  ('RISK_ACCEPTANCE_RBDS', 'props', 'reference-ids'),
  ('VULNERABILITY_SCORE', 'observations', 'scalar-score'),
  ('ANTIVIRUS_SCORE', 'observations', 'scalar-score'),
  ('PATCH_SCORE', 'observations', 'scalar-score'),
  ('SECURITY_COMPLIANCE_SCORE', 'observations', 'scalar-score'),
  ('STANDARD_OPERATING_ENVIRONMENT_SCORE', 'observations', 'scalar-score'),
  ('COMPUTER_PASSWORD_AGE_SCORE', 'observations', 'scalar-score'),
  ('VULNERABILITY_REPORTING_SCORE', 'observations', 'scalar-score'),
  ('SECURITY_COMPLIANCE_REPORTING_SCORE', 'observations', 'scalar-score'),
  ('TOTAL_AUTHORIZATION_PACKAGE_RISK_SCORE', 'observations', 'scalar-score'),
  ('AVG_AUTHORIZATION_PACKAGE_RISK_SCORE', 'observations', 'scalar-score'),
  ('RISK_SCORE_GRADE', 'observations', 'scalar-score'),
  ('AVG_VULNERABILITY_SCORE', 'observations', 'scalar-score'),
  ('AVG_PATCH_SCORE', 'observations', 'scalar-score'),
  ('AVG_SECURITY_COMPLIANCE_REPORTING_SCORE', 'observations', 'scalar-score'),
  ('AVG_ANTIVIRUS_SCORE', 'observations', 'scalar-score'),
  ('AVG_STANDARD_OPERATING_ENVIRONMENT_SCORE', 'observations', 'scalar-score'),
  ('AVG_COMPUTER_PASSWORD_AGE_SCORE', 'observations', 'scalar-score'),
  ('AVG_VULNERABILITY_REPORTING_SCORE', 'observations', 'scalar-score'),
  ('AVG_SECURITY_COMPLIANCE_SCORE', 'observations', 'scalar-score'),
  ('TOTAL_PACKAGE_INHERENT_RISK', 'observations', 'scalar-score'),
  ('TOTAL_PACKAGE_RESIDUAL_RISK', 'observations', 'scalar-score'),
  ('ADJUSTED_TOTAL_RISK_SCORE', 'observations', 'scalar-score'),
  ('ADJUSTED_AVERAGE_RISK_SCORE', 'observations', 'scalar-score'),
  ('CURRENT_HIGHEST_DEVICE_RISK_SCORE', 'observations', 'scalar-score'),
  ('CURRENT_AVERAGE_DEVICE_RISK_SCORE', 'observations', 'scalar-score'),
  ('CURRENT_CONTROL_RISK_SCORE', 'observations', 'scalar-score'),
  ('PCT_CURRENT_HIGHEST_DEVICE_RISK_THRESHOLD', 'observations', 'scalar-score'),
  ('PCT_CURRENT_AVERAGE_DEVICE_RISK_THRESHOLD', 'observations', 'scalar-score'),
  ('BASELINE_HIGHEST_DEVICE_RISK_SCORE', 'observations', 'scalar-score'),
  ('BASELINE_AVERAGE_DEVICE_RISK_SCORE', 'observations', 'scalar-score'),
  ('BASELINE_CONTROL_RISK_SCORE', 'observations', 'scalar-score'),
  ('RISK_ASSESSMENT', 'observations', 'scalar-score'),
  ('_CURRENT_AVERAGE_DEVICE_RISK_THRESHOLD', 'observations', 'scalar-score'),
  ('_CURRENT_HIGHEST_DEVICE_RISK_THRESHOLD', 'observations', 'scalar-score'),
  ('INITIAL_RISK_ASSESSMENT', 'observations', 'scalar-score'),
  ('RISK_ASSESSMENT_REPORT', 'props', 'json-text'),
  ('WORKFLOW_CURRENT_NODE', 'props', 'direct'),
  ('WORKFLOW_PROCESS_VERSION', 'props', 'direct'),
  ('WORKFLOW_JOB_STATUS', 'props', 'archer-select'),
  ('WORKFLOW_STATUS', 'props', 'archer-select'),
  ('DUE_DATE', 'props', 'date'),
  ('WORKFLOW_CURRENT_NODE_HRTN', 'props', 'direct'),
  ('WORKFLOW_STATUS_CHANGED', 'props', 'date')
), source_fields AS (
 SELECT a.CONTENT_ID::STRING AS CONTENT_ID, m.FIELD_NAME, m.ELEMENT_TYPE, m.TRANSFORM_ID,
        GET(a.CURATED_JSON, m.FIELD_NAME) AS ARCHER_VALUE
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
 CROSS JOIN mapped m
 WHERE a.CONTENT_ID IS NOT NULL
), classified_source AS (
 SELECT *,
        CASE WHEN ARCHER_VALUE IS NULL THEN 'MISSING_KEY'
             WHEN IS_NULL_VALUE(ARCHER_VALUE) THEN 'JSON_NULL'
             WHEN TYPEOF(ARCHER_VALUE)='VARCHAR' AND TRIM(ARCHER_VALUE::STRING)='' THEN 'EMPTY'
             WHEN TYPEOF(ARCHER_VALUE)='ARRAY' AND ARRAY_SIZE(ARCHER_VALUE)=0 THEN 'EMPTY'
             ELSE 'POPULATED' END AS SOURCE_STATUS
 FROM source_fields
), sampled AS (
 SELECT *
 FROM classified_source
 QUALIFY ROW_NUMBER() OVER (
   PARTITION BY FIELD_NAME
   ORDER BY IFF(SOURCE_STATUS='POPULATED',0,1),CONTENT_ID
 )<=15
), target_props AS (
 SELECT d.SOURCE_RECORD_ID::STRING AS CONTENT_ID, d.ELEMENT_TYPE,
        IFF(d.ELEMENT_TYPE='observations',
            d.METADATA_JSON:props[0]:name::STRING,
            d.METADATA_JSON:name::STRING) AS PROPERTY_NAME,
        IFF(d.ELEMENT_TYPE='observations',
            d.METADATA_JSON:props[0]:value,
            d.METADATA_JSON:value) AS OSCAL_VALUE
 FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT d
 JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_RESULTS_DEPENDENCY f
   ON f.FK_TARGET_ELEMENT_HASH=d.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH
 JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT parent
   ON parent.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
  AND parent.SOURCE_RECORD_ID=d.SOURCE_RECORD_ID
  AND parent.ELEMENT_TYPE='results'
 WHERE d.ELEMENT_TYPE IN ('props','observations')
), paired AS (
 SELECT s.*, p.CONTENT_ID AS TARGET_CONTENT_ID, p.OSCAL_VALUE,
   CASE
     WHEN s.TRANSFORM_ID IN ('scalar-score','direct')
          AND TYPEOF(s.ARCHER_VALUE) IN ('VARCHAR','INTEGER','DECIMAL','DOUBLE','BOOLEAN')
       THEN TRIM(s.ARCHER_VALUE::STRING)
     WHEN s.TRANSFORM_ID='scalar-score'
          AND TYPEOF(s.ARCHER_VALUE)='ARRAY' AND ARRAY_SIZE(s.ARCHER_VALUE)=1
       THEN TRIM(s.ARCHER_VALUE[0]::STRING)
     WHEN s.TRANSFORM_ID IN ('scalar-score','archer-select')
          AND TYPEOF(s.ARCHER_VALUE)='OBJECT'
          AND ARRAY_SIZE(s.ARCHER_VALUE:ResolvedValues)=1
          AND s.ARCHER_VALUE:ResolvedValues[0]:LookupStatus::STRING='MATCHED'
       THEN TRIM(s.ARCHER_VALUE:ResolvedValues[0]:ValueName::STRING)
     WHEN s.TRANSFORM_ID='reference-ids'
          AND TYPEOF(s.ARCHER_VALUE)='OBJECT'
       THEN s.ARCHER_VALUE:ContentId::STRING
     WHEN s.TRANSFORM_ID='date' AND TYPEOF(s.ARCHER_VALUE)='VARCHAR'
       THEN LEFT(TRIM(s.ARCHER_VALUE::STRING),10)
     ELSE NULL
   END AS EXPECTED_TEXT
 FROM sampled s
 LEFT JOIN target_props p
   ON p.CONTENT_ID=s.CONTENT_ID AND p.ELEMENT_TYPE=s.ELEMENT_TYPE
  AND p.PROPERTY_NAME=TRIM(LOWER(REGEXP_REPLACE(s.FIELD_NAME,'[^A-Za-z0-9]+','-')),'-')
), checked AS (
 SELECT *,
   CASE WHEN SOURCE_STATUS<>'POPULATED' THEN 'NO_POPULATED_SOURCE_DATA'
        WHEN TARGET_CONTENT_ID IS NULL THEN 'MISSING_TARGET'
        WHEN OSCAL_VALUE IS NULL OR IS_NULL_VALUE(OSCAL_VALUE) THEN 'TARGET_NULL'
        WHEN TRANSFORM_ID='json-text'
             AND TRY_PARSE_JSON(OSCAL_VALUE::STRING) IS NOT NULL
             AND TO_JSON(TRY_PARSE_JSON(OSCAL_VALUE::STRING))=TO_JSON(ARCHER_VALUE)
           THEN 'MATCH'
        WHEN EXPECTED_TEXT IS NOT NULL AND EXPECTED_TEXT=OSCAL_VALUE::STRING
           THEN 'MATCH'
        WHEN EXPECTED_TEXT IS NULL THEN 'COMPLEX_TRANSFORM_REVIEW'
        ELSE 'VALUE_DIFFERENCE_REVIEW'
   END AS VALUE_STATUS
 FROM paired
)
SELECT FIELD_NAME, ELEMENT_TYPE, TRANSFORM_ID,
       COUNT(DISTINCT IFF(SOURCE_STATUS='POPULATED',CONTENT_ID,NULL)) AS POPULATED_SAMPLE_IDS,
       COUNT(DISTINCT IFF(VALUE_STATUS='MATCH',CONTENT_ID,NULL)) AS VALUE_MATCHES,
       COUNT(DISTINCT IFF(VALUE_STATUS='MISSING_TARGET',CONTENT_ID,NULL)) AS MISSING_TARGET,
       COUNT(DISTINCT IFF(VALUE_STATUS='TARGET_NULL',CONTENT_ID,NULL)) AS NULL_TARGET_FOR_POPULATED,
       COUNT(DISTINCT IFF(VALUE_STATUS IN ('COMPLEX_TRANSFORM_REVIEW','VALUE_DIFFERENCE_REVIEW'),
                          CONTENT_ID,NULL)) AS NEEDS_VALUE_REVIEW,
       MIN(IFF(VALUE_STATUS IN ('MISSING_TARGET','TARGET_NULL',
              'COMPLEX_TRANSFORM_REVIEW','VALUE_DIFFERENCE_REVIEW'),CONTENT_ID,NULL)) AS EXAMPLE_CONTENT_ID_TO_REVIEW,
       CASE
         WHEN COUNT(DISTINCT IFF(SOURCE_STATUS='POPULATED',CONTENT_ID,NULL))=0
           THEN 'NO_POPULATED_SOURCE_DATA'
         WHEN COUNT(DISTINCT IFF(VALUE_STATUS<>'MATCH' AND SOURCE_STATUS='POPULATED',
                                 CONTENT_ID,NULL))>0 THEN 'REVIEW'
         ELSE 'SAMPLE_VALUE_MATCH'
       END AS QA_STATUS
FROM checked
GROUP BY FIELD_NAME,ELEMENT_TYPE,TRANSFORM_ID
ORDER BY QA_STATUS,FIELD_NAME;
