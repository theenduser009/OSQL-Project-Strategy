-- INFORMATION_CLASSIFICATION (Source One)
-- APPROVED archer-select to system-security-plan.system-characteristics.props[]
-- Inspect persisted property values only; no database writes.
SELECT
    SOURCE_RECORD_ID AS ARCHER_CONTENT_ID,
    ELEMENT_TYPE,
    METADATA_JSON:"name"::STRING AS PROPERTY_NAME,
    METADATA_JSON:"value"::STRING AS RESOLVED_VALUE,
    METADATA_JSON AS FULL_OSCAL_JSON
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
WHERE ELEMENT_TYPE = 'props'
  AND SOURCE_SYSTEM_NAME = 'ARCHER'
  AND SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
  AND METADATA_JSON:"name"::STRING = 'information-classification'
ORDER BY SOURCE_RECORD_ID
LIMIT 100;
