-- OSCAL Source Two / DEV / 2026-10-20 / READ ONLY / ONE RESULT TABLE.
-- Purpose: compare two Archer relationship definitions by exact record pairs.
--   Relationship A: Control Standards CR 30705 -> Control Procedures RR 30704
--   Relationship B: Control Procedures CR 3088 -> Control Standards RR 2497
-- Metadata supplied in the owner's Archer CR/RR workbook screenshots.
-- Use the actual SQL_FIELD_NAME for each (LEVEL_ID, FIELD_ID), not a guessed
-- JSON key or a globally searched field name.
-- No DIM/FACT access, no mapper/cell reload, no DDL/DML, no raw business values.
-- Run once as SQL in Snowflake DEV; screenshot the 4 result rows horizontally.
-- Compares ALL rows present in the two RAW target tables, not only procedures
-- already referenced from the Source Two Authoritative Sources hierarchy.
-- Do not equate these counts to the earlier 2,627-procedure subset totals.
-- No change to native OSCAL control links or the 104-row mapping CSV.

WITH required_fields AS (
    SELECT column1::VARCHAR AS RELATIONSHIP_FAMILY,
           column2::VARCHAR AS SIDE,
           column3::VARCHAR AS OWNER_KIND,
           column4::NUMBER  AS OWNER_LEVEL_ID,
           column5::NUMBER  AS ARCHER_FIELD_ID,
           column6::NUMBER  AS EXPECTED_REFERENCED_LEVEL_ID
    FROM VALUES
      ('STANDARDS_CR_TO_PROCEDURES_RR', 'CR', 'STANDARD', 41, 30705, 39),
      ('STANDARDS_CR_TO_PROCEDURES_RR', 'RR', 'PROCEDURE', 39, 30704, 41),
      ('PROCEDURES_CR_TO_STANDARDS_RR', 'CR', 'PROCEDURE', 39, 3088, 41),
      ('PROCEDURES_CR_TO_STANDARDS_RR', 'RR', 'STANDARD', 41, 2497, 39)
),
field_metadata AS (
    SELECT r.RELATIONSHIP_FAMILY, r.SIDE, r.OWNER_KIND,
           r.OWNER_LEVEL_ID, r.ARCHER_FIELD_ID,
           r.EXPECTED_REFERENCED_LEVEL_ID,
           COUNT(m.FIELD_ID) AS MATCHING_META_ROWS,
           MAX(m.SQL_FIELD_NAME) AS ACTUAL_SQL_FIELD_NAME
    FROM required_fields r
    LEFT JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_META_FIELD m
      ON m.LEVEL_ID = r.OWNER_LEVEL_ID
     AND m.FIELD_ID = r.ARCHER_FIELD_ID
    GROUP BY r.RELATIONSHIP_FAMILY, r.SIDE, r.OWNER_KIND,
             r.OWNER_LEVEL_ID, r.ARCHER_FIELD_ID,
             r.EXPECTED_REFERENCED_LEVEL_ID
),
standard_index AS (
    SELECT CONTENT_ID AS ID, COUNT(*) AS RAW_ROWS,
           COUNT_IF(CURATED_JSON IS NOT NULL) AS POPULATED_JSON_ROWS
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_STANDARDS_RAW
    WHERE CONTENT_ID IS NOT NULL
    GROUP BY CONTENT_ID
),
procedure_index AS (
    SELECT CONTENT_ID AS ID, COUNT(*) AS RAW_ROWS,
           COUNT_IF(CURATED_JSON IS NOT NULL) AS POPULATED_JSON_ROWS
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_PROCEDURES_RAW
    WHERE CONTENT_ID IS NOT NULL
    GROUP BY CONTENT_ID
),
owner_field_values AS (
    SELECT m.RELATIONSHIP_FAMILY, m.SIDE, m.OWNER_KIND,
           m.EXPECTED_REFERENCED_LEVEL_ID, s.CONTENT_ID AS OWNER_ID,
           GET(s.CURATED_JSON, m.ACTUAL_SQL_FIELD_NAME) AS FIELD_VALUE
    FROM field_metadata m
    JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_STANDARDS_RAW s
      ON m.OWNER_KIND = 'STANDARD' AND m.MATCHING_META_ROWS = 1
    UNION ALL
    SELECT m.RELATIONSHIP_FAMILY, m.SIDE, m.OWNER_KIND,
           m.EXPECTED_REFERENCED_LEVEL_ID, p.CONTENT_ID AS OWNER_ID,
           GET(p.CURATED_JSON, m.ACTUAL_SQL_FIELD_NAME) AS FIELD_VALUE
    FROM field_metadata m
    JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_PROCEDURES_RAW p
      ON m.OWNER_KIND = 'PROCEDURE' AND m.MATCHING_META_ROWS = 1
),
field_shapes AS (
    SELECT RELATIONSHIP_FAMILY, SIDE,
           COUNT(*) AS OWNER_RAW_ROWS,
           COUNT(DISTINCT OWNER_ID) AS DISTINCT_OWNER_IDS,
           COUNT_IF(TYPEOF(FIELD_VALUE) = 'ARRAY') AS ARRAY_ROWS,
           COUNT_IF(FIELD_VALUE IS NULL OR IS_NULL_VALUE(FIELD_VALUE))
             AS NULL_OR_ABSENT_ROWS,
           COUNT_IF(FIELD_VALUE IS NOT NULL AND NOT IS_NULL_VALUE(FIELD_VALUE)
                    AND TYPEOF(FIELD_VALUE) <> 'ARRAY') AS NON_ARRAY_NON_NULL_ROWS
    FROM owner_field_values
    GROUP BY RELATIONSHIP_FAMILY, SIDE
),
reference_items AS (
    SELECT v.RELATIONSHIP_FAMILY, v.SIDE, v.OWNER_KIND,
           v.EXPECTED_REFERENCED_LEVEL_ID, v.OWNER_ID, f.VALUE AS ITEM
    FROM owner_field_values v,
         LATERAL FLATTEN(
           INPUT => IFF(TYPEOF(v.FIELD_VALUE) = 'ARRAY',
                        v.FIELD_VALUE, ARRAY_CONSTRUCT())
         ) f
),
item_classification AS (
    SELECT i.*,
           TYPEOF(i.ITEM) AS ITEM_TYPE,
           IFF(TYPEOF(i.ITEM) = 'OBJECT',
               GET(i.ITEM, 'ContentId')::VARCHAR,
               IFF(TYPEOF(i.ITEM) IN ('INTEGER', 'DECIMAL', 'VARCHAR'),
                   i.ITEM::VARCHAR, NULL)) AS REF_ID_TEXT,
           IFF(TYPEOF(i.ITEM) = 'OBJECT',
               GET(i.ITEM, 'LevelId')::VARCHAR, NULL) AS REF_LEVEL_TEXT
    FROM reference_items i
),
normalized AS (
    SELECT c.*,
           IFF(REGEXP_LIKE(c.REF_ID_TEXT, '^[1-9][0-9]*$'),
               TRY_TO_NUMBER(c.REF_ID_TEXT), NULL) AS REFERENCE_ID,
           IFF(c.ITEM_TYPE = 'OBJECT' AND c.REF_LEVEL_TEXT IS NULL,
               1, 0) AS MISSING_OBJECT_LEVEL_ID,
           IFF(c.ITEM_TYPE = 'OBJECT' AND c.REF_LEVEL_TEXT IS NOT NULL
                AND c.REF_LEVEL_TEXT <> c.EXPECTED_REFERENCED_LEVEL_ID::VARCHAR,
               1, 0) AS WRONG_OBJECT_LEVEL_ID
    FROM item_classification c
),
reference_matches AS (
    SELECT n.*,
           IFF(n.OWNER_KIND = 'STANDARD', n.OWNER_ID, n.REFERENCE_ID) AS STANDARD_ID,
           IFF(n.OWNER_KIND = 'PROCEDURE', n.OWNER_ID, n.REFERENCE_ID) AS PROCEDURE_ID,
           IFF(n.OWNER_KIND = 'STANDARD', p.ID, s.ID) AS MATCHED_TARGET_ID,
           IFF(n.OWNER_KIND = 'STANDARD', p.RAW_ROWS, s.RAW_ROWS) AS TARGET_RAW_ROWS,
           IFF(n.OWNER_KIND = 'STANDARD', p.POPULATED_JSON_ROWS, s.POPULATED_JSON_ROWS)
             AS TARGET_JSON_ROWS
    FROM normalized n
    LEFT JOIN standard_index s
      ON n.OWNER_KIND = 'PROCEDURE' AND n.REFERENCE_ID = s.ID
    LEFT JOIN procedure_index p
      ON n.OWNER_KIND = 'STANDARD' AND n.REFERENCE_ID = p.ID
),
item_counts AS (
    SELECT RELATIONSHIP_FAMILY, SIDE,
           COUNT(*) AS REFERENCE_ITEMS,
           COUNT_IF(ITEM_TYPE = 'OBJECT') AS OBJECT_ITEMS,
           COUNT_IF(ITEM_TYPE <> 'OBJECT') AS SCALAR_OR_OTHER_ITEMS,
           COUNT_IF(REFERENCE_ID IS NULL) AS INVALID_OR_MISSING_ID_ITEMS,
           COUNT_IF(MISSING_OBJECT_LEVEL_ID = 1) AS MISSING_OBJECT_LEVEL_ID_ITEMS,
           COUNT_IF(WRONG_OBJECT_LEVEL_ID = 1) AS WRONG_OBJECT_LEVEL_ID_ITEMS,
           COUNT_IF(REFERENCE_ID IS NOT NULL AND MATCHED_TARGET_ID IS NULL)
             AS NO_RAW_TARGET_ITEMS,
           COUNT_IF(MATCHED_TARGET_ID IS NOT NULL AND TARGET_RAW_ROWS > 1)
             AS DUPLICATE_TARGET_ID_ITEMS,
           COUNT_IF(MATCHED_TARGET_ID IS NOT NULL AND TARGET_JSON_ROWS = 0)
             AS NULL_TARGET_JSON_ITEMS,
           COUNT_IF(MATCHED_TARGET_ID IS NOT NULL) AS MATCHED_TARGET_ITEMS
    FROM reference_matches
    GROUP BY RELATIONSHIP_FAMILY, SIDE
),
valid_distinct_pairs AS (
    SELECT DISTINCT RELATIONSHIP_FAMILY, SIDE, STANDARD_ID, PROCEDURE_ID
    FROM reference_matches
    WHERE REFERENCE_ID IS NOT NULL
      AND MATCHED_TARGET_ID IS NOT NULL
      AND COALESCE(MISSING_OBJECT_LEVEL_ID, 0) = 0
      AND COALESCE(WRONG_OBJECT_LEVEL_ID, 0) = 0
      AND TARGET_RAW_ROWS = 1
      AND TARGET_JSON_ROWS >= 1
),
pair_membership AS (
    SELECT RELATIONSHIP_FAMILY, STANDARD_ID, PROCEDURE_ID,
           MAX(IFF(SIDE = 'CR', 1, 0)) AS IN_ORIGINATING_CR,
           MAX(IFF(SIDE = 'RR', 1, 0)) AS IN_RELATED_RECORD_RR
    FROM valid_distinct_pairs
    GROUP BY RELATIONSHIP_FAMILY, STANDARD_ID, PROCEDURE_ID
),
family_parity AS (
    SELECT RELATIONSHIP_FAMILY,
           COUNT_IF(IN_ORIGINATING_CR = 1 AND IN_RELATED_RECORD_RR = 1)
             AS PAIRS_IN_BOTH_SIDES,
           COUNT_IF(IN_ORIGINATING_CR = 1 AND IN_RELATED_RECORD_RR = 0)
             AS PAIRS_ONLY_IN_CR,
           COUNT_IF(IN_ORIGINATING_CR = 0 AND IN_RELATED_RECORD_RR = 1)
             AS PAIRS_ONLY_IN_RR
    FROM pair_membership
    GROUP BY RELATIONSHIP_FAMILY
),
distinct_pair_counts AS (
    SELECT RELATIONSHIP_FAMILY, SIDE, COUNT(*) AS VALID_DISTINCT_PAIRS
    FROM valid_distinct_pairs
    GROUP BY RELATIONSHIP_FAMILY, SIDE
),
across_families AS (
    SELECT STANDARD_ID, PROCEDURE_ID,
           MAX(IFF(RELATIONSHIP_FAMILY = 'STANDARDS_CR_TO_PROCEDURES_RR', 1, 0))
             AS IN_STANDARDS_FAMILY,
           MAX(IFF(RELATIONSHIP_FAMILY = 'PROCEDURES_CR_TO_STANDARDS_RR', 1, 0))
             AS IN_PROCEDURES_FAMILY
    FROM pair_membership
    GROUP BY STANDARD_ID, PROCEDURE_ID
),
family_overlap AS (
    SELECT COUNT_IF(IN_STANDARDS_FAMILY = 1 AND IN_PROCEDURES_FAMILY = 1)
             AS PAIRS_SHARED_ACROSS_FAMILIES,
           COUNT_IF(IN_STANDARDS_FAMILY = 1 AND IN_PROCEDURES_FAMILY = 0)
             AS PAIRS_ONLY_STANDARDS_FAMILY,
           COUNT_IF(IN_STANDARDS_FAMILY = 0 AND IN_PROCEDURES_FAMILY = 1)
             AS PAIRS_ONLY_PROCEDURES_FAMILY
    FROM across_families
)
SELECT
    m.RELATIONSHIP_FAMILY,
    m.SIDE,
    m.OWNER_KIND,
    m.OWNER_LEVEL_ID,
    m.ARCHER_FIELD_ID,
    m.ACTUAL_SQL_FIELD_NAME,
    m.MATCHING_META_ROWS,
    COALESCE(fs.OWNER_RAW_ROWS, 0) AS OWNER_RAW_ROWS,
    COALESCE(fs.DISTINCT_OWNER_IDS, 0) AS DISTINCT_OWNER_IDS,
    COALESCE(fs.ARRAY_ROWS, 0) AS ARRAY_ROWS,
    COALESCE(fs.NULL_OR_ABSENT_ROWS, 0) AS NULL_OR_ABSENT_ROWS,
    COALESCE(fs.NON_ARRAY_NON_NULL_ROWS, 0) AS NON_ARRAY_NON_NULL_ROWS,
    COALESCE(ic.REFERENCE_ITEMS, 0) AS REFERENCE_ITEMS,
    COALESCE(ic.OBJECT_ITEMS, 0) AS OBJECT_ITEMS,
    COALESCE(ic.SCALAR_OR_OTHER_ITEMS, 0) AS SCALAR_OR_OTHER_ITEMS,
    COALESCE(ic.INVALID_OR_MISSING_ID_ITEMS, 0) AS INVALID_OR_MISSING_ID_ITEMS,
    COALESCE(ic.MISSING_OBJECT_LEVEL_ID_ITEMS, 0) AS MISSING_OBJECT_LEVEL_ID_ITEMS,
    COALESCE(ic.WRONG_OBJECT_LEVEL_ID_ITEMS, 0) AS WRONG_OBJECT_LEVEL_ID_ITEMS,
    COALESCE(ic.NO_RAW_TARGET_ITEMS, 0) AS NO_RAW_TARGET_ITEMS,
    COALESCE(ic.DUPLICATE_TARGET_ID_ITEMS, 0) AS DUPLICATE_TARGET_ID_ITEMS,
    COALESCE(ic.NULL_TARGET_JSON_ITEMS, 0) AS NULL_TARGET_JSON_ITEMS,
    COALESCE(ic.MATCHED_TARGET_ITEMS, 0) AS MATCHED_TARGET_ITEMS,
    COALESCE(dp.VALID_DISTINCT_PAIRS, 0) AS VALID_DISTINCT_PAIRS,
    COALESCE(fp.PAIRS_IN_BOTH_SIDES, 0) AS PAIRS_IN_BOTH_SIDES,
    COALESCE(fp.PAIRS_ONLY_IN_CR, 0) AS PAIRS_ONLY_IN_CR,
    COALESCE(fp.PAIRS_ONLY_IN_RR, 0) AS PAIRS_ONLY_IN_RR,
    COALESCE(fo.PAIRS_SHARED_ACROSS_FAMILIES, 0) AS PAIRS_SHARED_ACROSS_FAMILIES,
    COALESCE(fo.PAIRS_ONLY_STANDARDS_FAMILY, 0) AS PAIRS_ONLY_STANDARDS_FAMILY,
    COALESCE(fo.PAIRS_ONLY_PROCEDURES_FAMILY, 0) AS PAIRS_ONLY_PROCEDURES_FAMILY
FROM field_metadata m
LEFT JOIN field_shapes fs
  ON m.RELATIONSHIP_FAMILY = fs.RELATIONSHIP_FAMILY AND m.SIDE = fs.SIDE
LEFT JOIN item_counts ic
  ON m.RELATIONSHIP_FAMILY = ic.RELATIONSHIP_FAMILY AND m.SIDE = ic.SIDE
LEFT JOIN distinct_pair_counts dp
  ON m.RELATIONSHIP_FAMILY = dp.RELATIONSHIP_FAMILY AND m.SIDE = dp.SIDE
LEFT JOIN family_parity fp ON m.RELATIONSHIP_FAMILY = fp.RELATIONSHIP_FAMILY
CROSS JOIN family_overlap fo
ORDER BY m.RELATIONSHIP_FAMILY, m.SIDE;

-- Acceptance gate:
-- * MATCHING_META_ROWS must equal 1 for all four fields; check ACTUAL_SQL_FIELD_NAME.
-- * MISSING/WRONG_LEVEL, INVALID_ID, NO_RAW_TARGET, DUPLICATE_TARGET_ID and
--   NULL_TARGET_JSON item counts must be zero before treating a pair as valid.
-- * Compare PAIRS_ONLY_IN_CR and PAIRS_ONLY_IN_RR separately for each family.
-- * An absent field/empty array is coverage evidence, not proof of bad identity.
-- * PAIRS_SHARED_ACROSS_FAMILIES is only a potential duplicate business pair;
--   never merge the separate configured Archer relationships automatically.
-- * No automatic merge/union of distinct CR families. No auto native OSCAL links.
