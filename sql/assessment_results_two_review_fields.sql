-- Assessment Results / Source One | read-only two-field comparison.
-- Paste and run the entire SELECT. 15 populated source records per field.
SELECT
    a.CONTENT_ID::STRING AS ARCHER_CONTENT_ID,
    f.ARCHER_FIELD,
    GET(a.CURATED_JSON, f.ARCHER_FIELD) AS ARCHER_PAYLOAD,
    d.METADATA_JSON:"value" AS OSCAL_VALUE,
    d.METADATA_JSON AS OSCAL_PROPERTY_PAYLOAD,
    IFF(d.SOURCE_RECORD_ID IS NULL, 'TARGET_MISSING', 'TARGET_FOUND') AS TARGET_STATUS
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
CROSS JOIN (
    SELECT column1 AS ARCHER_FIELD, column2 AS PROP_NAME
    FROM VALUES
       ('RISK_ACCEPTANCE_RBDS', 'risk-acceptance-rbds'),
       ('WORKFLOW_STATUS_CHANGED', 'workflow-status-changed')
) f
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT d
    ON d.SOURCE_RECORD_ID = a.CONTENT_ID::STRING
   AND d.ELEMENT_TYPE = 'props'
   AND d.METADATA_JSON:"name"::STRING = f.PROP_NAME
WHERE GET(a.CURATED_JSON, f.ARCHER_FIELD) IS NOT NULL
  AND NOT IS_NULL_VALUE(GET(a.CURATED_JSON, f.ARCHER_FIELD))
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY f.ARCHER_FIELD ORDER BY a.CONTENT_ID::STRING
) <= 15
ORDER BY f.ARCHER_FIELD, a.CONTENT_ID::STRING;
