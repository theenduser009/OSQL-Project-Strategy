-- 2026-10-12 | Assessment Results | READ ONLY
-- Inspect two review cases from the 15-per-field QA.
-- Shows original Archer payload and exact persisted result-level prop.
WITH fields AS (
    SELECT column1 AS ARCHER_FIELD, column2 AS PROP_NAME, column3 AS TRANSFORM_ID
    FROM VALUES
      ('RISK_ACCEPTANCE_RBDS', 'risk-acceptance-rbds', 'reference-ids'),
      ('WORKFLOW_STATUS_CHANGED', 'workflow-status-changed', 'date')
), source_rows AS (
    SELECT a.CONTENT_ID::STRING AS CONTENT_ID, f.ARCHER_FIELD, f.PROP_NAME,
           f.TRANSFORM_ID, GET(a.CURATED_JSON, f.ARCHER_FIELD) AS ARCHER_PAYLOAD
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
    CROSS JOIN fields f
    WHERE a.CONTENT_ID IS NOT NULL
), sample AS (
    SELECT * FROM source_rows
    WHERE ARCHER_PAYLOAD IS NOT NULL AND NOT IS_NULL_VALUE(ARCHER_PAYLOAD)
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY ARCHER_FIELD ORDER BY CONTENT_ID
    ) <= 15
), targets AS (
    SELECT d.SOURCE_RECORD_ID::STRING AS CONTENT_ID,
           d.METADATA_JSON:name::STRING AS PROP_NAME,
           d.METADATA_JSON:value AS OSCAL_VALUE,
           d.METADATA_JSON AS OSCAL_PAYLOAD
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT d
    WHERE d.ELEMENT_TYPE = 'props'
      AND d.METADATA_JSON:name::STRING IN
          ('risk-acceptance-rbds', 'workflow-status-changed')
)
SELECT s.CONTENT_ID, s.ARCHER_FIELD, s.TRANSFORM_ID,
       TYPEOF(s.ARCHER_PAYLOAD) AS ARCHER_TYPE,
       s.ARCHER_PAYLOAD,
       IFF(s.TRANSFORM_ID = 'date'
            AND TYPEOF(s.ARCHER_PAYLOAD) = 'VARCHAR',
           LEFT(TRIM(s.ARCHER_PAYLOAD::STRING), 10), NULL) AS QA_EXPECTED_DATE,
       t.OSCAL_VALUE, t.OSCAL_PAYLOAD,
       IFF(t.CONTENT_ID IS NULL, 'MISSING_TARGET', 'PERSISTED_TARGET_FOUND') AS TARGET_STATUS
FROM sample s
LEFT JOIN targets t
    ON t.CONTENT_ID = s.CONTENT_ID AND t.PROP_NAME = s.PROP_NAME
ORDER BY s.ARCHER_FIELD, s.CONTENT_ID;
