-- SSP / System Characteristics / FIPS 199
-- Read-only: show populated source, native OSCAL value, and Archer field lineage.
-- The RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY source is NULL in current DEV.
SELECT
    a.CONTENT_ID AS ARCHER_CONTENT_ID,
    'SSP - System Characteristics' AS OSCAL_MODEL,
    a.CURATED_JSON:RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY AS RECOMMENDED_PAYLOAD,
    a.CURATED_JSON:CONFIDENTIALITY_CONTROL_CATEGORY_OVERRIDE AS OVERRIDE_PAYLOAD,
    a.CURATED_JSON:CONFIDENTIALITY_CONTROL_CATEGORY_OVERRIDE:ResolvedValues[0]:ValueName::STRING AS ARCHER_LABEL,
    d.METADATA_JSON:"security-objective-confidentiality"::STRING AS OSCAL_VALUE,
    p.METADATA_JSON:"value"::STRING AS SOURCE_FIELD_LINEAGE,
    d.METADATA_JSON AS OSCAL_PAYLOAD
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT d
    ON d.SOURCE_RECORD_ID = a.CONTENT_ID::STRING
   AND d.ELEMENT_TYPE = 'security-impact-level'
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT p
    ON p.SOURCE_RECORD_ID = a.CONTENT_ID::STRING
   AND p.ELEMENT_TYPE = 'props'
   AND p.METADATA_JSON:"name"::STRING = 'source-field'
   AND p.METADATA_JSON:"value"::STRING = 'CONFIDENTIALITY_CONTROL_CATEGORY_OVERRIDE'
WHERE a.CURATED_JSON:CONFIDENTIALITY_CONTROL_CATEGORY_OVERRIDE IS NOT NULL
  AND NOT IS_NULL_VALUE(a.CURATED_JSON:CONFIDENTIALITY_CONTROL_CATEGORY_OVERRIDE)
ORDER BY a.CONTENT_ID
LIMIT 20;
