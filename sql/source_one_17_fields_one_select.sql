-- SOURCE ONE: CONSOLIDATED CLIENT SELECT — 17 mapped OSCAL values + CONTENT_ID
-- Dated 2026-10-15. Read-only. Run as ONE SELECT in Snowflake DEV.
-- Uses persisted OSCAL DIM/FACT, not a preview or Archer RAW.
-- Person columns return stored readable names (multiple: semicolon-delimited).
-- ENTITY / BUSINESS retain stored ContentId/LevelId JSON, pending lookup.
-- POAMS returns item OSCAL UUIDs, NOT original Archer ContentIds.
-- AUTHORIZATION_PACKAGE_METADATA_TITLE is the second destination of PACKAGE_NAME.
-- No CREATE VIEW, INSERT, MERGE, UPDATE or COMMIT.
WITH
sspd AS (
  SELECT SOURCE_RECORD_ID AS CID, PK_OSCAL_SSP_ELEMENT_HASH AS PK,
         ELEMENT_TYPE AS KIND, METADATA_JSON AS J
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
),
roots AS (SELECT DISTINCT CID FROM sspd WHERE KIND='system-security-plan'),
ssp_edges AS (
  SELECT FK_SOURCE_ELEMENT_HASH AS PARENT_PK, FK_TARGET_ELEMENT_HASH AS CHILD_PK
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY
  WHERE DEPENDENCY_TYPE='CONTAINS'
),
native AS (
  SELECT CID,
    MAX(IFF(KIND='system-characteristics',J:"system-name"::STRING,NULL)) AS PACKAGE_NAME,
    MAX(IFF(KIND='system-characteristics',J:"system-name-short"::STRING,NULL)) AS ACRONYM,
    MAX(IFF(KIND='system-characteristics',J:"date-authorized"::STRING,NULL)) AS ATO_DATE,
    MAX(IFF(KIND='metadata',J:"title"::STRING,NULL)) AS METADATA_TITLE
  FROM sspd WHERE KIND IN ('system-characteristics','metadata') GROUP BY CID
),
status AS (
  SELECT s.CID, MAX(s.J:"state"::STRING) AS OPERATIONAL_STATUS
  FROM sspd s JOIN ssp_edges e ON e.CHILD_PK=s.PK
              JOIN sspd parent ON parent.PK=e.PARENT_PK AND parent.CID=s.CID
  WHERE s.KIND='status' AND parent.KIND='system-characteristics' GROUP BY s.CID
),
ssp_props AS (
  SELECT p.CID, p.J:"name"::STRING AS PROP_NAME,
         p.J:"value"::STRING AS PROP_VALUE
  FROM sspd p JOIN ssp_edges e ON e.CHILD_PK=p.PK
              JOIN sspd parent ON parent.PK=e.PARENT_PK AND parent.CID=p.CID
  WHERE p.KIND='props' AND parent.KIND='system-characteristics'
),
prop_values AS (
  SELECT CID, PROP_NAME,
         LISTAGG(DISTINCT PROP_VALUE,' | ') WITHIN GROUP (ORDER BY PROP_VALUE) AS V
  FROM ssp_props GROUP BY CID,PROP_NAME
),
prop_pivot AS (
  SELECT CID,
    MAX(IFF(PROP_NAME='authorization-decision',V,NULL)) AS AUTHORIZATION_DECISION,
    MAX(IFF(PROP_NAME='authorization-package-submit-date',V,NULL)) AS SUBMIT_DATE,
    MAX(IFF(PROP_NAME='atoiato-expiration-date',V,NULL)) AS EXPIRY_DATE,
    MAX(IFF(PROP_NAME='legacy-sap-id',V,NULL)) AS LEGACY_SAP_ID,
    MAX(IFF(PROP_NAME='entity',V,NULL)) AS ENTITY,
    MAX(IFF(PROP_NAME='business',V,NULL)) AS BUSINESS
  FROM prop_values GROUP BY CID
),
admin_json AS (
  SELECT CID,PROP_NAME,TRY_PARSE_JSON(PROP_VALUE) AS J
  FROM ssp_props
  WHERE PROP_NAME IN ('system-administrator-sa','alternate-system-administrator-sa')
),
admin_people AS (
  SELECT a.CID,a.PROP_NAME,
    NULLIF(TRIM(ARRAY_TO_STRING(ARRAY_CONSTRUCT_COMPACT(
      NULLIF(TRIM(f.VALUE:"ResolvedUser":"FIRST_NAME"::STRING),''),
      NULLIF(TRIM(f.VALUE:"ResolvedUser":"MIDDLE_NAME"::STRING),''),
      NULLIF(TRIM(f.VALUE:"ResolvedUser":"LAST_NAME"::STRING),'')
    ),' ')),'') AS DISPLAY_NAME
  FROM admin_json a, LATERAL FLATTEN(INPUT=>a.J:"UserList") f
  WHERE f.VALUE:"ResolvedUser":"LookupStatus"::STRING IN ('MATCHED','MATCHED_MISSING_EEID')
),
admin_agg AS (
  SELECT CID,PROP_NAME,
    LISTAGG(DISTINCT DISPLAY_NAME,'; ') WITHIN GROUP (ORDER BY DISPLAY_NAME) AS NAMES
  FROM admin_people WHERE DISPLAY_NAME IS NOT NULL GROUP BY CID,PROP_NAME
),
admins AS (
  SELECT CID,
    MAX(IFF(PROP_NAME='system-administrator-sa',NAMES,NULL)) AS SYSTEM_ADMINISTRATOR_SA,
    MAX(IFF(PROP_NAME='alternate-system-administrator-sa',NAMES,NULL)) AS ALTERNATE_SYSTEM_ADMINISTRATOR_SA
  FROM admin_agg GROUP BY CID
),
role_members AS (
  SELECT a.CID,a.J:"role-id"::STRING AS ROLE_ID,f.VALUE::STRING AS PARTY_UUID
  FROM sspd a JOIN ssp_edges e ON e.CHILD_PK=a.PK
              JOIN sspd parent ON parent.PK=e.PARENT_PK AND parent.CID=a.CID,
       LATERAL FLATTEN(INPUT=>a.J:"party-uuids") f
  WHERE a.KIND='responsible-parties' AND parent.KIND='metadata'
    AND a.J:"role-id"::STRING IN ('information-owner','authorizing-official')
),
role_people AS (
  SELECT r.CID,r.ROLE_ID,NULLIF(TRIM(p.J:"name"::STRING),'') AS DISPLAY_NAME
  FROM role_members r JOIN sspd p
    ON p.CID=r.CID AND p.KIND='parties'
   AND REPLACE(p.J:"uuid"::STRING,'-','')=REPLACE(r.PARTY_UUID,'-','')
),
role_agg AS (
  SELECT CID,ROLE_ID,
    LISTAGG(DISTINCT DISPLAY_NAME,'; ') WITHIN GROUP (ORDER BY DISPLAY_NAME) AS NAMES
  FROM role_people WHERE DISPLAY_NAME IS NOT NULL GROUP BY CID,ROLE_ID
),
roles AS (
  SELECT CID,
    MAX(IFF(ROLE_ID='information-owner',NAMES,NULL)) AS INFORMATION_OWNER_IO,
    MAX(IFF(ROLE_ID='authorizing-official',NAMES,NULL)) AS AUTHORIZING_OFFICIAL_AO
  FROM role_agg GROUP BY CID
),
workflow AS (
  SELECT p.SOURCE_RECORD_ID AS CID,
    LISTAGG(DISTINCT p.METADATA_JSON:"value"::STRING,' | ')
      WITHIN GROUP (ORDER BY p.METADATA_JSON:"value"::STRING) AS WORKFLOW_STATUS
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT p
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_RESULTS_DEPENDENCY e
    ON e.FK_TARGET_ELEMENT_HASH=p.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH
   AND e.DEPENDENCY_TYPE='CONTAINS'
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT r
    ON r.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=e.FK_SOURCE_ELEMENT_HASH
   AND r.SOURCE_RECORD_ID=p.SOURCE_RECORD_ID AND r.ELEMENT_TYPE='results'
  WHERE p.ELEMENT_TYPE='props' AND p.SOURCE_SYSTEM_NAME='ARCHER'
    AND p.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND p.METADATA_JSON:"name"::STRING='workflow-status'
  GROUP BY p.SOURCE_RECORD_ID
),
poams AS (
  SELECT item.SOURCE_RECORD_ID AS CID,
    LISTAGG(DISTINCT item.OSCAL_UUID,'; ') WITHIN GROUP (ORDER BY item.OSCAL_UUID) AS POAMS
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT item
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_POAM_DEPENDENCY e
    ON e.FK_TARGET_ELEMENT_HASH=item.PK_DIM_OSCAL_POAM_ELEMENT_HASH
   AND e.DEPENDENCY_TYPE='CONTAINS'
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT r
    ON r.PK_DIM_OSCAL_POAM_ELEMENT_HASH=e.FK_SOURCE_ELEMENT_HASH
   AND r.SOURCE_RECORD_ID=item.SOURCE_RECORD_ID
   AND r.ELEMENT_TYPE='plan-of-action-and-milestones'
  WHERE item.ELEMENT_TYPE='poam-items' AND item.SOURCE_SYSTEM_NAME='ARCHER'
    AND item.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
  GROUP BY item.SOURCE_RECORD_ID
)
SELECT root.CID AS CONTENT_ID,
       poams.POAMS,
       native.PACKAGE_NAME AS AUTHORIZATION_PACKAGE_NAME,
       native.ACRONYM,
       status.OPERATIONAL_STATUS,
       pp.AUTHORIZATION_DECISION,
       native.ATO_DATE AS ATOIATO_DATE,
       pp.SUBMIT_DATE AS AUTHORIZATION_PACKAGE_SUBMIT_DATE,
       pp.EXPIRY_DATE AS ATOIATO_EXPIRATION_DATE,
       workflow.WORKFLOW_STATUS,
       roles.INFORMATION_OWNER_IO,
       roles.AUTHORIZING_OFFICIAL_AO,
       pp.LEGACY_SAP_ID,
       admins.ALTERNATE_SYSTEM_ADMINISTRATOR_SA,
       admins.SYSTEM_ADMINISTRATOR_SA,
       pp.ENTITY,
       pp.BUSINESS,
       native.METADATA_TITLE AS AUTHORIZATION_PACKAGE_METADATA_TITLE
FROM roots root
LEFT JOIN native ON native.CID=root.CID
LEFT JOIN status ON status.CID=root.CID
LEFT JOIN prop_pivot pp ON pp.CID=root.CID
LEFT JOIN workflow ON workflow.CID=root.CID
LEFT JOIN roles ON roles.CID=root.CID
LEFT JOIN admins ON admins.CID=root.CID
LEFT JOIN poams ON poams.CID=root.CID
ORDER BY CONTENT_ID;
