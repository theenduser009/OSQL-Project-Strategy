-- Verifies persisted per-field observation/prop identity, NOT source-target value equality.
WITH mapped AS (
 SELECT TRIM(VALUE) AS FIELD_NAME,
        IFF(TRIM(VALUE) IN ('FINDINGS','RISK_ACCEPTANCE_RBDS','RISK_ASSESSMENT_REPORT','WORKFLOW_CURRENT_NODE','WORKFLOW_PROCESS_VERSION','WORKFLOW_JOB_STATUS','WORKFLOW_STATUS','DUE_DATE','WORKFLOW_CURRENT_NODE_HRTN','WORKFLOW_STATUS_CHANGED'), 'props', 'observations') AS KIND,
        TRIM(LOWER(REGEXP_REPLACE(TRIM(VALUE), '[^A-Za-z0-9]+', '-')), '-') AS PROP_NAME
 FROM TABLE(SPLIT_TO_TABLE('FINDINGS,RISK_ACCEPTANCE_RBDS,VULNERABILITY_SCORE,ANTIVIRUS_SCORE,PATCH_SCORE,SECURITY_COMPLIANCE_SCORE,STANDARD_OPERATING_ENVIRONMENT_SCORE,COMPUTER_PASSWORD_AGE_SCORE,VULNERABILITY_REPORTING_SCORE,SECURITY_COMPLIANCE_REPORTING_SCORE,TOTAL_AUTHORIZATION_PACKAGE_RISK_SCORE,AVG_AUTHORIZATION_PACKAGE_RISK_SCORE,RISK_SCORE_GRADE,AVG_VULNERABILITY_SCORE,AVG_PATCH_SCORE,AVG_SECURITY_COMPLIANCE_REPORTING_SCORE,AVG_ANTIVIRUS_SCORE,AVG_STANDARD_OPERATING_ENVIRONMENT_SCORE,AVG_COMPUTER_PASSWORD_AGE_SCORE,AVG_VULNERABILITY_REPORTING_SCORE,AVG_SECURITY_COMPLIANCE_SCORE,TOTAL_PACKAGE_INHERENT_RISK,TOTAL_PACKAGE_RESIDUAL_RISK,ADJUSTED_TOTAL_RISK_SCORE,ADJUSTED_AVERAGE_RISK_SCORE,CURRENT_HIGHEST_DEVICE_RISK_SCORE,CURRENT_AVERAGE_DEVICE_RISK_SCORE,CURRENT_CONTROL_RISK_SCORE,PCT_CURRENT_HIGHEST_DEVICE_RISK_THRESHOLD,PCT_CURRENT_AVERAGE_DEVICE_RISK_THRESHOLD,BASELINE_HIGHEST_DEVICE_RISK_SCORE,BASELINE_AVERAGE_DEVICE_RISK_SCORE,BASELINE_CONTROL_RISK_SCORE,RISK_ASSESSMENT,_CURRENT_AVERAGE_DEVICE_RISK_THRESHOLD,_CURRENT_HIGHEST_DEVICE_RISK_THRESHOLD,INITIAL_RISK_ASSESSMENT,RISK_ASSESSMENT_REPORT,WORKFLOW_CURRENT_NODE,WORKFLOW_PROCESS_VERSION,WORKFLOW_JOB_STATUS,WORKFLOW_STATUS,DUE_DATE,WORKFLOW_CURRENT_NODE_HRTN,WORKFLOW_STATUS_CHANGED', ','))
),
source AS (
 SELECT a.CONTENT_ID::STRING AS CONTENT_ID, m.FIELD_NAME, m.KIND, m.PROP_NAME,
        GET(a.CURATED_JSON, m.FIELD_NAME) AS ARCHER_VALUE
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
 CROSS JOIN mapped m
 WHERE a.CONTENT_ID IS NOT NULL
),
persisted AS (
 SELECT DISTINCT d.SOURCE_RECORD_ID::STRING AS CONTENT_ID, d.ELEMENT_TYPE AS KIND,
        IFF(d.ELEMENT_TYPE='observations',
            d.METADATA_JSON:props[0]:name::STRING,
            d.METADATA_JSON:name::STRING) AS PROP_NAME
 FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT d
 JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_RESULTS_DEPENDENCY e
   ON e.FK_TARGET_ELEMENT_HASH=d.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH
 JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT parent
   ON parent.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=e.FK_SOURCE_ELEMENT_HASH
  AND parent.ELEMENT_TYPE='results'
  AND parent.SOURCE_RECORD_ID=d.SOURCE_RECORD_ID
 WHERE d.ELEMENT_TYPE IN ('props','observations')
)
SELECT s.FIELD_NAME, s.KIND AS TARGET_ELEMENT_TYPE,
       COUNT(DISTINCT s.CONTENT_ID) AS SOURCE_RECORDS,
       COUNT(DISTINCT IFF(s.ARCHER_VALUE IS NULL,s.CONTENT_ID,NULL)) AS MISSING_SOURCE_KEY,
       COUNT(DISTINCT IFF(IS_NULL_VALUE(s.ARCHER_VALUE),s.CONTENT_ID,NULL)) AS SOURCE_JSON_NULL,
       COUNT(DISTINCT IFF(s.ARCHER_VALUE IS NOT NULL AND NOT IS_NULL_VALUE(s.ARCHER_VALUE),s.CONTENT_ID,NULL)) AS POPULATED_SOURCE,
       COUNT(DISTINCT p.CONTENT_ID) AS RECORDS_WITH_EXACT_TARGET_PROPERTY,
       COUNT(DISTINCT IFF(s.ARCHER_VALUE IS NOT NULL AND NOT IS_NULL_VALUE(s.ARCHER_VALUE)
                          AND p.CONTENT_ID IS NULL,s.CONTENT_ID,NULL)) AS POPULATED_MISSING_TARGET,
       IFF(COUNT(DISTINCT IFF(s.ARCHER_VALUE IS NOT NULL AND NOT IS_NULL_VALUE(s.ARCHER_VALUE),s.CONTENT_ID,NULL))=0,
           'NO_POPULATED_SOURCE_DATA',
           IFF(COUNT(DISTINCT IFF(s.ARCHER_VALUE IS NOT NULL AND NOT IS_NULL_VALUE(s.ARCHER_VALUE)
                                 AND p.CONTENT_ID IS NULL,s.CONTENT_ID,NULL))>0,
               'POPULATED_SOURCE_TARGET_EMPTY','TARGET_FIELD_PRESENT_VALUE_QA_NEXT')) AS QA_STATUS
FROM source s
LEFT JOIN persisted p ON p.CONTENT_ID=s.CONTENT_ID AND p.KIND=s.KIND
 AND p.PROP_NAME=s.PROP_NAME
GROUP BY s.FIELD_NAME,s.KIND
ORDER BY QA_STATUS,s.FIELD_NAME;
