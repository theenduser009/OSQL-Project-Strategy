-- Test any Archer field. Replace the name inside GET() only.
-- RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY maps to
-- SSP > system-characteristics > security-impact-level > security-objective-confidentiality.
WITH field_check AS (
    SELECT GET(CURATED_JSON, 'RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY') AS FIELD_VALUE
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
)
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(IS_NULL_VALUE(FIELD_VALUE)) AS JSON_NULL,
    COUNT_IF(FIELD_VALUE IS NULL) AS FIELD_MISSING,
    COUNT_IF(FIELD_VALUE IS NOT NULL AND NOT IS_NULL_VALUE(FIELD_VALUE)) AS POPULATED
FROM field_check;
