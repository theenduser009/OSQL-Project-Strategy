-- Owner Snowflake 2026-10-29 verified ARCHER_META_LEVEL:
-- LevelId=5 -> POLICY - LEVEL 3, ModuleId=65, Module=POLICIES.
-- Query 3 finds only Archer Content Policies Level 1/2/3 _RAW.
-- Query 4 must use the verified Level 3 _RAW table, not Level 1/2.
-- The exact physical Level 3 name remains to be confirmed in DEV.
-- Critical distinction: Source/Topic/Section use descendant ROLLUP fields;
-- Sub-Section uses directly-owned POLICY_LEVEL_3. Deduplicate business links
-- only after defining direct vs inherited relationship semantics.
-- No writes, no COMMIT or mapper changes, no real policy names in public GitHub.

-- QUERY 01: Already owner-verified Archer policy level, quick recheck only.
SELECT LEVEL_ID,LEVEL_NAME,MODULE_ID,MODULE_NAME
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_META_LEVEL
WHERE LEVEL_ID=5;

-- QUERY 02: Metadata target-ID COVERAGE for Policy Level 3. This validates
-- the ContentId exists in ARCHER_META_CONTENT but does not independently
-- verify which physical policy RAW record is used or a matching name.
WITH source_fields AS (
  SELECT 'Source' AS SOURCE_LEVEL,
         'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW' AS SOURCE_TABLE_NAME,
         CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
         'POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS' AS ARCHER_FIELD_NAME,
         GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
                 TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
             'POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS') AS REFERENCE_ARRAY
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
  UNION ALL
  SELECT 'Topic','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',
         CONTENT_ID::VARCHAR,
         'POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS',
         GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
                 TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
             'POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS')
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
  UNION ALL
  SELECT 'Section','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW',
         CONTENT_ID::VARCHAR,
         'POLICY_LEVEL_3_FROM_SECTION_LEVEL_AND_BELOW',
         GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
                 TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
             'POLICY_LEVEL_3_FROM_SECTION_LEVEL_AND_BELOW')
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
  UNION ALL
  SELECT 'Sub-Section','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW',
         CONTENT_ID::VARCHAR,'POLICY_LEVEL_3',
         GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
                 TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),'POLICY_LEVEL_3')
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
refs AS (
  SELECT s.SOURCE_LEVEL,s.SOURCE_TABLE_NAME,s.OWNER_CONTENT_ID,
         s.ARCHER_FIELD_NAME,x.INDEX AS REFERENCE_INDEX,
         TYPEOF(x.VALUE) AS ITEM_TYPE,
         x.VALUE:ContentId::VARCHAR AS TARGET_CONTENT_ID,
         x.VALUE:LevelId::VARCHAR AS TARGET_LEVEL_ID
  FROM source_fields s,
       LATERAL FLATTEN(INPUT=>IFF(IS_ARRAY(s.REFERENCE_ARRAY),
                                  s.REFERENCE_ARRAY,ARRAY_CONSTRUCT())) x
),
classified AS (
  SELECT *,
    (ITEM_TYPE='OBJECT'
      AND REGEXP_LIKE(COALESCE(TARGET_CONTENT_ID,''),'^[1-9][0-9]*$')
      AND TARGET_LEVEL_ID='5') AS VALID_LEVEL5_REFERENCE
  FROM refs
),
meta_ids AS (
  SELECT CONTENT_ID::VARCHAR AS META_CONTENT_ID,COUNT(*) AS META_ROWS
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_META_CONTENT
  GROUP BY CONTENT_ID::VARCHAR
)
SELECT IFF(GROUPING(r.SOURCE_LEVEL)=1,'ALL',r.SOURCE_LEVEL) AS SOURCE_LEVEL,
       COUNT(*) AS REFERENCE_OCCURRENCES,
       SUM(IFF(r.VALID_LEVEL5_REFERENCE,1,0)) AS VALID_LEVEL5_REFERENCES,
       SUM(IFF(r.TARGET_LEVEL_ID IS DISTINCT FROM '5',1,0)) AS WRONG_OR_MISSING_LEVEL,
       SUM(IFF(NOT r.VALID_LEVEL5_REFERENCE,1,0)) AS INVALID_REFERENCE_SHAPE_OR_ID,
       SUM(IFF(r.VALID_LEVEL5_REFERENCE AND m.META_CONTENT_ID IS NOT NULL,1,0)) AS META_CONTENT_MATCHED,
       SUM(IFF(r.VALID_LEVEL5_REFERENCE AND m.META_CONTENT_ID IS NULL,1,0)) AS META_CONTENT_UNMATCHED,
       SUM(IFF(r.VALID_LEVEL5_REFERENCE AND m.META_ROWS>1,1,0)) AS DUPLICATE_META_CONTENT_OCCURRENCES,
       COUNT(DISTINCT IFF(r.VALID_LEVEL5_REFERENCE,r.TARGET_CONTENT_ID,NULL)) AS DISTINCT_VALID_REFERENCE_IDS
FROM classified r
LEFT JOIN meta_ids m ON r.VALID_LEVEL5_REFERENCE
                     AND r.TARGET_CONTENT_ID=m.META_CONTENT_ID
GROUP BY ROLLUP(r.SOURCE_LEVEL)
ORDER BY GROUPING(r.SOURCE_LEVEL),SOURCE_LEVEL;

-- QUERY 03: Only the Policy Level 1/2/3 production _RAW tables.
-- Anchored prefix and terminal _RAW exclude _STG, _STAGE, _TMP,
-- _BASE and unsuffixed copies. Do not broaden if zero results.
WITH columns_by_table AS (
 SELECT TABLE_CATALOG,TABLE_SCHEMA,TABLE_NAME,
        COUNT_IF(UPPER(COLUMN_NAME)='CONTENT_ID') AS HAS_CONTENT_ID,
        COUNT_IF(UPPER(COLUMN_NAME)='CURATED_JSON') AS HAS_CURATED_JSON
 FROM RTX_RAW_DEV.INFORMATION_SCHEMA.COLUMNS
 WHERE TABLE_SCHEMA='ES_ESC_GRC'
   AND REGEXP_LIKE(UPPER(TABLE_NAME),
       '^ARCHER_CONTENT_POLICIES_(POLICY_)?LEVEL_[123]_RAW$')
 GROUP BY 1,2,3
)
SELECT TABLE_CATALOG,TABLE_SCHEMA,TABLE_NAME
FROM columns_by_table
WHERE HAS_CONTENT_ID>0 AND HAS_CURATED_JSON>0
ORDER BY TABLE_NAME;

-- QUERY 04: Exact source -> REAL Policy Level 3 CURATED_JSON record.
-- REQUIRED: Replace the IDENTIFIER placeholder with the exact, verified
-- Only use the verified Level 3 _RAW table from Query 3.
-- Never use Level 1/2 or _STG/_STAGE/_TMP/unsuffixed tables.
-- Query 4 requires the verified physical identifier.
-- IMPORTANT: name fields are only CANDIDATES. Owner saw a previous record
-- whose POLICY_LEVEL_3_NAME was NULL; do not invent a fallback identity.
WITH source_fields AS (
  SELECT 'Source' AS SOURCE_LEVEL,
         'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW' AS SOURCE_TABLE_NAME,
         CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
         'POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS' AS ARCHER_FIELD_NAME,
         GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
                 TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
             'POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS') AS REFERENCE_ARRAY
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
  UNION ALL
  SELECT 'Topic','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',
         CONTENT_ID::VARCHAR,
         'POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS',
         GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
                 TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
             'POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS')
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
  UNION ALL
  SELECT 'Section','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW',
         CONTENT_ID::VARCHAR,
         'POLICY_LEVEL_3_FROM_SECTION_LEVEL_AND_BELOW',
         GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
                 TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
             'POLICY_LEVEL_3_FROM_SECTION_LEVEL_AND_BELOW')
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
  UNION ALL
  SELECT 'Sub-Section','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW',
         CONTENT_ID::VARCHAR,'POLICY_LEVEL_3',
         GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
                 TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),'POLICY_LEVEL_3')
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
refs AS (
  SELECT s.SOURCE_LEVEL,s.SOURCE_TABLE_NAME,s.OWNER_CONTENT_ID,
         s.ARCHER_FIELD_NAME,x.INDEX AS REFERENCE_INDEX,
         TYPEOF(x.VALUE) AS ITEM_TYPE,
         x.VALUE:ContentId::VARCHAR AS TARGET_CONTENT_ID,
         x.VALUE:LevelId::VARCHAR AS TARGET_LEVEL_ID
  FROM source_fields s,
       LATERAL FLATTEN(INPUT=>IFF(IS_ARRAY(s.REFERENCE_ARRAY),
                                  s.REFERENCE_ARRAY,ARRAY_CONSTRUCT())) x
),
classified AS (
  SELECT *,
    (ITEM_TYPE='OBJECT'
      AND REGEXP_LIKE(COALESCE(TARGET_CONTENT_ID,''),'^[1-9][0-9]*$')
      AND TARGET_LEVEL_ID='5') AS VALID_LEVEL5_REFERENCE
  FROM refs
),
policy_records AS (
 SELECT CONTENT_ID::VARCHAR AS POLICY_CONTENT_ID,
        IFF(TYPEOF(CURATED_JSON)='VARCHAR',
            TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON) AS J
 FROM IDENTIFIER('RTX_RAW_DEV.ES_ESC_GRC.REPLACE_WITH_VERIFIED_POLICY_LEVEL3_RAW_TABLE')
 WHERE CONTENT_ID IS NOT NULL
),
policy_by_id AS (
 SELECT POLICY_CONTENT_ID,COUNT(*) AS POLICY_ROWS,
        COUNT_IF(J IS NOT NULL) AS NONNULL_CURATED_ROWS,
        MAX(GET(J,'POLICY_LEVEL_3_NAME')::VARCHAR) AS POLICY_LEVEL_3_NAME,
        MAX(GET(J,'POLICY_TOPIC_NAME')::VARCHAR) AS POLICY_TOPIC_NAME_CANDIDATE,
        MAX(GET(J,'POLICY_NUMBER')::VARCHAR) AS POLICY_NUMBER_CANDIDATE,
        MAX(GET(J,'POLICY_PURPOSE')::VARCHAR) AS POLICY_PURPOSE_CANDIDATE
 FROM policy_records GROUP BY POLICY_CONTENT_ID
)
SELECT r.SOURCE_LEVEL,r.SOURCE_TABLE_NAME,r.OWNER_CONTENT_ID,
       r.ARCHER_FIELD_NAME,r.REFERENCE_INDEX,
       r.TARGET_CONTENT_ID AS REFERENCED_POLICY_CONTENT_ID,
       r.TARGET_LEVEL_ID,
       IFF(p.POLICY_ROWS=1,p.POLICY_LEVEL_3_NAME,NULL) AS POLICY_LEVEL_3_NAME,
       IFF(p.POLICY_ROWS=1,p.POLICY_TOPIC_NAME_CANDIDATE,NULL) AS POLICY_TOPIC_NAME_CANDIDATE,
       IFF(p.POLICY_ROWS=1,p.POLICY_NUMBER_CANDIDATE,NULL) AS POLICY_NUMBER_CANDIDATE,
       IFF(p.POLICY_ROWS=1,p.POLICY_PURPOSE_CANDIDATE,NULL) AS POLICY_PURPOSE_CANDIDATE,
       CASE WHEN NOT r.VALID_LEVEL5_REFERENCE THEN 'INVALID_LEVEL5_REFERENCE'
            WHEN p.POLICY_CONTENT_ID IS NULL THEN 'POLICY_RECORD_NOT_FOUND'
            WHEN p.POLICY_ROWS<>1 THEN 'AMBIGUOUS_DUPLICATE_POLICY_CONTENT_ID'
            WHEN p.NONNULL_CURATED_ROWS<>1 THEN 'POLICY_CURATED_JSON_MISSING'
            WHEN NULLIF(TRIM(p.POLICY_LEVEL_3_NAME),'') IS NULL
              THEN 'POLICY_NAME_NOT_IN_EXPECTED_MEMBER_CHECK_REAL_FIELD_NAME'
            ELSE 'POLICY_RECORD_RESOLVED_OSCAL_RELATIONSHIP_NOT_TESTED'
       END AS QA_STATUS
FROM classified r
LEFT JOIN policy_by_id p ON r.VALID_LEVEL5_REFERENCE
                        AND r.TARGET_CONTENT_ID=p.POLICY_CONTENT_ID
QUALIFY ROW_NUMBER() OVER (
 PARTITION BY r.SOURCE_LEVEL ORDER BY r.OWNER_CONTENT_ID,r.REFERENCE_INDEX
)<=25
ORDER BY r.SOURCE_LEVEL,r.OWNER_CONTENT_ID,r.REFERENCE_INDEX;
