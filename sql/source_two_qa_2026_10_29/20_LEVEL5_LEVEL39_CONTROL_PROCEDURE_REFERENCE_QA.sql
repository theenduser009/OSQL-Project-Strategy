-- 01: VERIFY THE LEVEL/MODULE NAMES (not an inferred hard-coded name)
SELECT LEVEL_ID, LEVEL_NAME, MODULE_ID, MODULE_NAME
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_META_LEVEL
WHERE LEVEL_ID IN (5, 39)
ORDER BY LEVEL_ID;

-- 02: COVERAGE FOR RELATED_CONTROL_PROCEDURES ACROSS ALL FOUR SOURCE TWO LEVELS.
-- This is an independent read-only check; it does not rerun prior successful
-- Control Standards checks. Input must be {ContentId, LevelId} objects.
WITH source_rows AS (
    SELECT 'Source' AS SOURCE_LEVEL, CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
           IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR), CURATED_JSON) AS J
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
    UNION ALL
    SELECT 'Topic', CONTENT_ID::VARCHAR,
           IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR), CURATED_JSON)
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
    UNION ALL
    SELECT 'Section', CONTENT_ID::VARCHAR,
           IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR), CURATED_JSON)
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
    UNION ALL
    SELECT 'Sub-Section', CONTENT_ID::VARCHAR,
           IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR), CURATED_JSON)
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
source_references AS (
    SELECT s.SOURCE_LEVEL, s.OWNER_CONTENT_ID, f.INDEX AS ARRAY_INDEX,
           f.VALUE AS REF_OBJ
    FROM source_rows s,
         LATERAL FLATTEN(INPUT=>GET(s.J,'RELATED_CONTROL_PROCEDURES')) f
),
reference_parts AS (
    SELECT SOURCE_LEVEL, OWNER_CONTENT_ID, ARRAY_INDEX,
           TYPEOF(REF_OBJ) AS REF_TYPE,
           REF_OBJ:ContentId::VARCHAR AS REF_CONTENT_ID,
           REF_OBJ:LevelId::VARCHAR AS REF_LEVEL_ID
    FROM source_references
),
classified AS (
    SELECT *,
           (REF_TYPE='OBJECT'
            AND REGEXP_LIKE(COALESCE(REF_CONTENT_ID,''),'^[1-9][0-9]*$')
            AND REF_LEVEL_ID='39') AS VALID_LEVEL39_REF
    FROM reference_parts
),
target_by_id AS (
    SELECT CONTENT_ID::VARCHAR AS TARGET_CONTENT_ID,
           COUNT(*) AS TARGET_ROW_COUNT,
           COUNT_IF(CURATED_JSON IS NOT NULL) AS TARGET_JSON_ROWS
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_PROCEDURES_RAW
    WHERE CONTENT_ID IS NOT NULL
    GROUP BY CONTENT_ID::VARCHAR
)
SELECT IFF(GROUPING(r.SOURCE_LEVEL)=1,'ALL',r.SOURCE_LEVEL) AS SOURCE_LEVEL,
       COUNT(*) AS REFERENCE_OCCURRENCES,
       SUM(IFF(r.REF_LEVEL_ID IS DISTINCT FROM '39',1,0))
         AS WRONG_OR_MISSING_LEVEL_ID,
       SUM(IFF(NOT r.VALID_LEVEL39_REF,1,0))
         AS INVALID_LEVEL39_REFS,
       SUM(IFF(r.VALID_LEVEL39_REF AND t.TARGET_CONTENT_ID IS NOT NULL,1,0))
         AS MATCHED_OCCURRENCES,
       SUM(IFF(r.VALID_LEVEL39_REF AND t.TARGET_CONTENT_ID IS NULL,1,0))
         AS UNMATCHED_OCCURRENCES,
       COUNT(DISTINCT IFF(r.VALID_LEVEL39_REF,r.REF_CONTENT_ID,NULL))
         AS DISTINCT_VALID_REFERENCED_IDS,
       COUNT(DISTINCT IFF(r.VALID_LEVEL39_REF
                          AND t.TARGET_CONTENT_ID IS NOT NULL,
                          r.REF_CONTENT_ID,NULL)) AS DISTINCT_MATCHED_IDS,
       SUM(IFF(r.VALID_LEVEL39_REF
               AND COALESCE(t.TARGET_ROW_COUNT,0)>1,1,0))
         AS OCCURRENCES_WITH_DUPLICATE_RAW_TARGET_IDS,
       SUM(IFF(r.VALID_LEVEL39_REF
               AND t.TARGET_CONTENT_ID IS NOT NULL
               AND t.TARGET_JSON_ROWS=0,1,0))
         AS OCCURRENCES_WITH_TARGET_JSON_MISSING
FROM classified r
LEFT JOIN target_by_id t
  ON r.VALID_LEVEL39_REF AND r.REF_CONTENT_ID=t.TARGET_CONTENT_ID
GROUP BY ROLLUP(r.SOURCE_LEVEL)
ORDER BY GROUPING(r.SOURCE_LEVEL),SOURCE_LEVEL;

-- 03: TRACE INDIVIDUAL OWNER CONTENT IDS TO REFERENCED PROCEDURE IDS.
-- Keep source ownership! The same ContentId under another Archer source table
-- or same property name is not interchangeable. This is a bounded sample.
WITH source_rows AS (
    SELECT 'Source' AS SOURCE_LEVEL,
           'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW' AS SOURCE_TABLE_NAME,
           CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
           IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON) AS J
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
    UNION ALL
    SELECT 'Topic','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',
           CONTENT_ID::VARCHAR,
           IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON)
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
    UNION ALL
    SELECT 'Section','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW',
           CONTENT_ID::VARCHAR,
           IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON)
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
    UNION ALL
    SELECT 'Sub-Section','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW',
           CONTENT_ID::VARCHAR,
           IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON)
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
refs AS (
    SELECT s.SOURCE_LEVEL,s.SOURCE_TABLE_NAME,s.OWNER_CONTENT_ID,
           f.INDEX AS ARRAY_INDEX,
           TYPEOF(f.VALUE) AS ITEM_TYPE,
           f.VALUE:ContentId::VARCHAR AS REF_CONTENT_ID,
           f.VALUE:LevelId::VARCHAR AS REF_LEVEL_ID
    FROM source_rows s,
         LATERAL FLATTEN(INPUT=>GET(s.J,'RELATED_CONTROL_PROCEDURES')) f
),
targets AS (
    SELECT CONTENT_ID::VARCHAR AS TARGET_CONTENT_ID,
           COUNT(*) AS TARGET_ROWS,
           COUNT_IF(CURATED_JSON IS NOT NULL) AS CURATED_ROWS
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_PROCEDURES_RAW
    WHERE CONTENT_ID IS NOT NULL
    GROUP BY CONTENT_ID::VARCHAR
)
SELECT r.SOURCE_LEVEL,r.SOURCE_TABLE_NAME,r.OWNER_CONTENT_ID,
       'RELATED_CONTROL_PROCEDURES' AS ARCHER_FIELD_NAME,
       r.ARRAY_INDEX,r.ITEM_TYPE,
       r.REF_CONTENT_ID AS REFERENCED_PROCEDURE_CONTENT_ID,
       r.REF_LEVEL_ID AS REFERENCED_LEVEL_ID,
       t.TARGET_ROWS,t.CURATED_ROWS,
       CASE WHEN r.ITEM_TYPE<>'OBJECT'
                 OR NOT REGEXP_LIKE(COALESCE(r.REF_CONTENT_ID,''),'^[1-9][0-9]*$')
            THEN 'INVALID_REFERENCE_SHAPE_OR_ID'
            WHEN r.REF_LEVEL_ID IS DISTINCT FROM '39'
            THEN 'LEVEL_NOT_39'
            WHEN t.TARGET_CONTENT_ID IS NULL THEN 'NO_TARGET_CONTENT_ID'
            WHEN t.TARGET_ROWS>1 THEN 'DUPLICATE_TARGET_CONTENT_ID'
            WHEN t.CURATED_ROWS=0 THEN 'TARGET_CURATED_JSON_MISSING'
            ELSE 'TARGET_CONTENT_ID_MATCHED_NAME_AND_OSCAL_LINK_NOT_TESTED'
       END AS REFERENCE_QA_STATUS
FROM refs r
LEFT JOIN targets t ON t.TARGET_CONTENT_ID=r.REF_CONTENT_ID
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY r.SOURCE_LEVEL
    ORDER BY r.OWNER_CONTENT_ID,r.ARRAY_INDEX
)<=25
ORDER BY r.SOURCE_LEVEL,r.OWNER_CONTENT_ID,r.ARRAY_INDEX;

-- 04: FIND ACTUAL POPULATED PROCEDURE NAME/TITLE CANDIDATES.
-- Do not infer the correct name from FIELD_NAME pattern alone; review
-- actual values and approved business meaning first.
WITH targets AS (
    SELECT CONTENT_ID::VARCHAR AS CONTENT_ID,
           IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON) AS J
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_PROCEDURES_RAW
),
fields AS (
    SELECT t.CONTENT_ID,f.KEY::VARCHAR AS FIELD_NAME,
           f.VALUE AS FIELD_VALUE,TYPEOF(f.VALUE) AS VALUE_TYPE
    FROM targets t,LATERAL FLATTEN(INPUT=>t.J) f
    WHERE f.KEY ILIKE '%NAME%'
       OR f.KEY ILIKE '%TITLE%'
       OR f.KEY ILIKE '%PROCEDURE%'
       OR f.KEY ILIKE '%DESCRIPTION%'
)
SELECT FIELD_NAME,VALUE_TYPE,
       COUNT(*) AS FIELD_OCCURRENCES,
       COUNT_IF(FIELD_VALUE IS NOT NULL
                AND NOT COALESCE(IS_NULL_VALUE(FIELD_VALUE),FALSE)
                AND FIELD_VALUE::VARCHAR<>'') AS NONEMPTY_OCCURRENCES
FROM fields
GROUP BY FIELD_NAME,VALUE_TYPE
ORDER BY NONEMPTY_OCCURRENCES DESC,FIELD_NAME
LIMIT 80;
