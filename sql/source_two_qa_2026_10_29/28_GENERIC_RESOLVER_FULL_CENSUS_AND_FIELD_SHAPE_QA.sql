-- Q1. All Source-level contracts: physical field shape for every record.
-- Missing and JSON null are DISTINCT from [] and from populated arrays.
WITH contracts AS (
 SELECT COLUMN1 AS FIELD_NAME FROM VALUES
   ('POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS'),
   ('RELATED_CONTROL_PROCEDURES')
),
rows AS (
 SELECT CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID, CURATED_JSON AS J
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
 WHERE CONTENT_ID IS NOT NULL AND TYPEOF(CURATED_JSON)='OBJECT'
),
scanned AS (
 SELECT r.OWNER_CONTENT_ID,c.FIELD_NAME,
        ARRAY_CONTAINS(TO_VARIANT(c.FIELD_NAME),
                       OBJECT_KEYS(AS_OBJECT(r.J))) AS KEY_PRESENT,
        GET(r.J,c.FIELD_NAME) AS FIELD_VALUE
 FROM rows r CROSS JOIN contracts c
)
SELECT FIELD_NAME,
       CASE WHEN NOT KEY_PRESENT THEN 'KEY_MISSING'
            WHEN IS_NULL_VALUE(FIELD_VALUE) THEN 'JSON_NULL'
            WHEN IS_ARRAY(FIELD_VALUE)
                  AND ARRAY_SIZE(FIELD_VALUE)=0 THEN 'EMPTY_ARRAY'
            WHEN IS_ARRAY(FIELD_VALUE) THEN 'NONEMPTY_ARRAY'
            ELSE COALESCE(TYPEOF(FIELD_VALUE),'SQL_NULL_OR_MISSING')
       END AS STORED_SHAPE,
       COUNT(*) AS SOURCE_RECORDS,
       COUNT(DISTINCT OWNER_CONTENT_ID) AS DISTINCT_OWNERS
FROM scanned
GROUP BY FIELD_NAME,STORED_SHAPE
ORDER BY FIELD_NAME,SOURCE_RECORDS DESC;


-- Q2. Inspect all contracted fields on Source owners where at least
-- one PRESENT field is non-array/empty. Full original JSON is not printed.
-- No hardcoded Content IDs in the public file.
WITH contracts AS (
 SELECT COLUMN1 AS FIELD_NAME FROM VALUES
   ('POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS'),
   ('RELATED_CONTROL_PROCEDURES')
),
rows AS (
 SELECT CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,CURATED_JSON AS J
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
 WHERE CONTENT_ID IS NOT NULL AND TYPEOF(CURATED_JSON)='OBJECT'
),
fields AS (
 SELECT r.OWNER_CONTENT_ID,c.FIELD_NAME,
        ARRAY_CONTAINS(TO_VARIANT(c.FIELD_NAME),
                       OBJECT_KEYS(AS_OBJECT(r.J))) AS KEY_PRESENT,
        GET(r.J,c.FIELD_NAME) AS V
 FROM rows r CROSS JOIN contracts c
),
classified AS (
 SELECT *,
        CASE WHEN NOT KEY_PRESENT THEN 'MISSING_SKIP'
             WHEN IS_NULL_VALUE(V) THEN 'JSON_NULL_BLOCKS_CURRENT_CANDIDATE'
             WHEN IS_ARRAY(V) AND ARRAY_SIZE(V)=0
                  THEN 'EMPTY_ARRAY_BLOCKS_CURRENT_CANDIDATE'
             WHEN IS_ARRAY(V) THEN 'ARRAY'
             ELSE 'NOT_ARRAY_BLOCKS_CURRENT_CANDIDATE' END AS SHAPE_STATUS
 FROM fields
),
blocked_owners AS (
 SELECT OWNER_CONTENT_ID
 FROM classified
 GROUP BY OWNER_CONTENT_ID
 HAVING COUNT_IF(SHAPE_STATUS IN
   ('JSON_NULL_BLOCKS_CURRENT_CANDIDATE',
    'EMPTY_ARRAY_BLOCKS_CURRENT_CANDIDATE',
    'NOT_ARRAY_BLOCKS_CURRENT_CANDIDATE'))>0
)
SELECT c.OWNER_CONTENT_ID,c.FIELD_NAME,c.KEY_PRESENT,
       TYPEOF(c.V) AS VALUE_TYPE,
       IFF(IS_ARRAY(c.V),ARRAY_SIZE(c.V),NULL) AS ARRAY_LENGTH,
       c.SHAPE_STATUS
FROM classified c
JOIN blocked_owners b ON b.OWNER_CONTENT_ID=c.OWNER_CONTENT_ID
ORDER BY c.OWNER_CONTENT_ID,c.FIELD_NAME
LIMIT 100;


WITH contracts (SOURCE_TABLE_NAME,FIELD_NAME,TARGET_LEVEL_ID,REFERENCE_KIND) AS (
   SELECT COLUMN1,COLUMN2,COLUMN3,COLUMN4 FROM VALUES
     ('ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW',
      'POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS','5','DESCENDANT_ROLLUP'),
     ('ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',
      'POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS','5','DESCENDANT_ROLLUP'),
     ('ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW',
      'POLICY_LEVEL_3_FROM_SECTION_LEVEL_AND_BELOW','5','DESCENDANT_ROLLUP'),
     ('ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW',
      'POLICY_LEVEL_3','5','DIRECT'),
     ('ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW',
      'RELATED_CONTROL_PROCEDURES','39','RELATED_RECORD'),
     ('ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',
      'SECTION_REFERENCES','8','CHILD_SECTION_REFERENCE'),
     ('ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',
      'RELATED_CONTROL_PROCEDURES','39','RELATED_RECORD'),
     ('ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW',
      'RELATED_CONTROL_PROCEDURES','39','RELATED_RECORD'),
     ('ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW',
      'RELATED_CONTROL_PROCEDURES','39','RELATED_RECORD')
 ),
 owners AS (
   SELECT REGEXP_SUBSTR(UPPER('RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'),'[^.]+$')
             AS SOURCE_TABLE_NAME,
          CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,CURATED_JSON AS J,
          COUNT(*) OVER (PARTITION BY CONTENT_ID::VARCHAR) AS OWNER_ID_ROWS
   FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
   WHERE CONTENT_ID IS NOT NULL AND TYPEOF(CURATED_JSON)='OBJECT'
 ),
 fields AS (
   SELECT s.OWNER_CONTENT_ID,s.J,c.FIELD_NAME,c.TARGET_LEVEL_ID,
          c.REFERENCE_KIND,f.VALUE AS REF_ARRAY
   FROM owners s,
        LATERAL FLATTEN(INPUT=>s.J) f,
        contracts c
   WHERE s.OWNER_ID_ROWS=1
     AND c.FIELD_NAME=f.KEY::VARCHAR
     AND c.SOURCE_TABLE_NAME=s.SOURCE_TABLE_NAME
 ),
 items AS (
   SELECT f.OWNER_CONTENT_ID,f.FIELD_NAME,f.TARGET_LEVEL_ID,
          f.REFERENCE_KIND,x.INDEX AS ITEM_INDEX,TYPEOF(x.VALUE) AS ITEM_TYPE,
          CASE WHEN TYPEOF(x.VALUE)='OBJECT' THEN x.VALUE:ContentId::VARCHAR
               WHEN TYPEOF(x.VALUE) IN ('INTEGER','DECIMAL','VARCHAR')
                    THEN x.VALUE::VARCHAR ELSE NULL END AS REF_CONTENT_ID,
          IFF(TYPEOF(x.VALUE)='OBJECT',x.VALUE:LevelId::VARCHAR,NULL)
            AS ORIGINAL_LEVEL_ID
   FROM fields f,LATERAL FLATTEN(
     INPUT=>IFF(IS_ARRAY(f.REF_ARRAY),f.REF_ARRAY,ARRAY_CONSTRUCT())) x
 ),
 needed_ids AS (
   SELECT DISTINCT TARGET_LEVEL_ID,REF_CONTENT_ID
   FROM items
   WHERE REGEXP_LIKE(COALESCE(REF_CONTENT_ID,''),'^[1-9][0-9]*$')
 ),
 target_rows AS (
   SELECT '5' AS LEVEL_ID,p.CONTENT_ID::VARCHAR AS REF_CONTENT_ID,
          p.CURATED_JSON:POLICY_LEVEL_3_NAME::VARCHAR AS BUSINESS_NAME,
          p.CURATED_JSON:POLICY_NUMBER::VARCHAR AS BUSINESS_ID,
          p.CURATED_JSON IS NOT NULL AS HAS_JSON
   FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW p
   WHERE p.CONTENT_ID::VARCHAR IN
      (SELECT REF_CONTENT_ID FROM needed_ids WHERE TARGET_LEVEL_ID='5')
   UNION ALL
   SELECT '39',p.CONTENT_ID::VARCHAR,
          p.CURATED_JSON:CONTROL_PROCEDURE_NAME::VARCHAR,
          p.CURATED_JSON:CONTROL_PROCEDURE_ID::VARCHAR,
          p.CURATED_JSON IS NOT NULL
   FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_PROCEDURES_RAW p
   WHERE p.CONTENT_ID::VARCHAR IN
      (SELECT REF_CONTENT_ID FROM needed_ids WHERE TARGET_LEVEL_ID='39')
   UNION ALL
   SELECT '8',p.CONTENT_ID::VARCHAR,
          p.CURATED_JSON:SECTION_NAME::VARCHAR,
          p.CURATED_JSON:SECTION_ID::VARCHAR,
          p.CURATED_JSON IS NOT NULL
   FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW p
   WHERE p.CONTENT_ID::VARCHAR IN
      (SELECT REF_CONTENT_ID FROM needed_ids WHERE TARGET_LEVEL_ID='8')
 ),
 targets AS (
   SELECT LEVEL_ID,REF_CONTENT_ID,COUNT(*) AS MATCH_COUNT,
          COUNT_IF(HAS_JSON) AS CURATED_ROWS,
          MAX(BUSINESS_NAME) AS BUSINESS_NAME,
          MAX(BUSINESS_ID) AS BUSINESS_ID
   FROM target_rows WHERE REF_CONTENT_ID IS NOT NULL
   GROUP BY LEVEL_ID,REF_CONTENT_ID
 ),
 matched AS (
   SELECT i.*,t.BUSINESS_NAME,t.BUSINESS_ID,
          CASE WHEN i.ITEM_TYPE NOT IN ('OBJECT','INTEGER','DECIMAL','VARCHAR')
                      OR NOT REGEXP_LIKE(COALESCE(i.REF_CONTENT_ID,''),'^[1-9][0-9]*$')
                 THEN 'INVALID_ID_OR_SHAPE'
               WHEN i.ITEM_TYPE='OBJECT'
                  AND i.ORIGINAL_LEVEL_ID IS DISTINCT FROM i.TARGET_LEVEL_ID
                 THEN 'LEVEL_MISMATCH'
               WHEN t.REF_CONTENT_ID IS NULL THEN 'TARGET_NOT_FOUND'
               WHEN t.MATCH_COUNT<>1 THEN 'DUPLICATE_TARGET'
               WHEN t.CURATED_ROWS<>1 THEN 'TARGET_JSON_MISSING'
               WHEN NULLIF(TRIM(t.BUSINESS_NAME),'') IS NULL
                 THEN 'NAME_MISSING'
               ELSE 'MATCHED' END AS LOOKUP_STATUS
   FROM items i LEFT JOIN targets t
     ON t.LEVEL_ID=i.TARGET_LEVEL_ID AND t.REF_CONTENT_ID=i.REF_CONTENT_ID
 ),
 field_resolutions AS (
   SELECT OWNER_CONTENT_ID,FIELD_NAME,
          COUNT_IF(LOOKUP_STATUS<>'MATCHED') AS BAD_ITEMS,
          ARRAY_AGG(OBJECT_CONSTRUCT_KEEP_NULL(
            'ContractVersion','archer-record-reference-v1',
            'ArrayIndex',ITEM_INDEX,
            'SourceItemType',ITEM_TYPE,
            'ContentId',REF_CONTENT_ID,
            'OriginalLevelId',ORIGINAL_LEVEL_ID,
            'ResolvedLevelId',TARGET_LEVEL_ID,
            'ReferenceKind',REFERENCE_KIND,
            'BusinessName',BUSINESS_NAME,
            'BusinessId',BUSINESS_ID,
            'LookupStatus',LOOKUP_STATUS
          )) WITHIN GROUP (ORDER BY ITEM_INDEX) AS MEMBERS
   FROM matched GROUP BY OWNER_CONTENT_ID,FIELD_NAME
 ),
 owner_resolutions AS (
   SELECT OWNER_CONTENT_ID,SUM(BAD_ITEMS) AS BAD_ITEMS,
          OBJECT_AGG(FIELD_NAME,TO_VARIANT(MEMBERS)) AS RESOLVED_FIELDS
   FROM field_resolutions GROUP BY OWNER_CONTENT_ID
 ),
 eligible AS (
   SELECT o.OWNER_CONTENT_ID,
      OBJECT_INSERT(AS_OBJECT(o.J),'_OSCAL_RESOLVED_RECORD_REFERENCES',
                    TO_VARIANT(r.RESOLVED_FIELDS),FALSE) AS ENRICHED_CURATED_JSON
   FROM owners o JOIN owner_resolutions r ON r.OWNER_CONTENT_ID=o.OWNER_CONTENT_ID
   WHERE o.OWNER_ID_ROWS=1 AND r.BAD_ITEMS=0
     AND NOT ARRAY_CONTAINS(TO_VARIANT('_OSCAL_RESOLVED_RECORD_REFERENCES'),
                            OBJECT_KEYS(AS_OBJECT(o.J)))
     AND NOT EXISTS (
       SELECT 1 FROM fields f
       WHERE f.OWNER_CONTENT_ID=o.OWNER_CONTENT_ID
         AND (NOT IS_ARRAY(f.REF_ARRAY) OR ARRAY_SIZE(f.REF_ARRAY)=0)
     )
 )

, qa AS (
 SELECT o.OWNER_CONTENT_ID,o.J AS ORIGINAL_JSON,
        r.BAD_ITEMS,e.OWNER_CONTENT_ID AS ENRICHED_OWNER_ID,
        e.ENRICHED_CURATED_JSON AS ENRICHED_JSON,
        CASE WHEN r.OWNER_CONTENT_ID IS NULL
                  THEN 'NO_VERIFIED_REFERENCE_FIELDS'
             WHEN r.BAD_ITEMS>0 THEN 'BLOCKED_LOOKUP_PRESERVE_JSON'
             WHEN ARRAY_CONTAINS(TO_VARIANT('_OSCAL_RESOLVED_RECORD_REFERENCES'),
                                  OBJECT_KEYS(AS_OBJECT(o.J)))
                  THEN 'EXISTING_SIDECAR_PRESERVED'
             WHEN EXISTS (SELECT 1 FROM fields f
                          WHERE f.OWNER_CONTENT_ID=o.OWNER_CONTENT_ID
                            AND (NOT IS_ARRAY(f.REF_ARRAY)
                              OR ARRAY_SIZE(f.REF_ARRAY)=0))
                  THEN 'INVALID_FIELD_ARRAY_PRESERVE_JSON'
             WHEN e.OWNER_CONTENT_ID IS NOT NULL THEN 'READY_ADDITIVE_ONLY'
             ELSE 'NOT_ELIGIBLE_NO_CHANGE' END AS PREVIEW_STATUS,
        IFF(e.OWNER_CONTENT_ID IS NULL,NULL,
          OBJECT_DELETE(AS_OBJECT(e.ENRICHED_CURATED_JSON),
                        '_OSCAL_RESOLVED_RECORD_REFERENCES')
                = AS_OBJECT(o.J)) AS ORIGINAL_JSON_PRESERVED
 FROM owners o
 LEFT JOIN owner_resolutions r ON r.OWNER_CONTENT_ID=o.OWNER_CONTENT_ID
 LEFT JOIN eligible e ON e.OWNER_CONTENT_ID=o.OWNER_CONTENT_ID
)
SELECT PREVIEW_STATUS,
       COUNT(*) AS SOURCE_ROWS,
       COUNT(DISTINCT OWNER_CONTENT_ID) AS DISTINCT_SOURCE_OWNERS,
       COUNT_IF(ENRICHED_OWNER_ID IS NOT NULL) AS SIDECAR_CANDIDATE_ROWS,
       COUNT_IF(ORIGINAL_JSON_PRESERVED=TRUE) AS ORIGINAL_JSON_EQUAL_ROWS,
       COUNT_IF(ORIGINAL_JSON_PRESERVED=FALSE) AS ORIGINAL_JSON_DIFFERENT_ROWS,
       COUNT_IF(BAD_ITEMS>0) AS OWNERS_WITH_LOOKUP_FAILURES
FROM qa
GROUP BY PREVIEW_STATUS
ORDER BY SOURCE_ROWS DESC,PREVIEW_STATUS;
