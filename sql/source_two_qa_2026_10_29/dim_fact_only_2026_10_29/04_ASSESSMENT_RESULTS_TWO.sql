-- 1: Assessment Results TOPIC COMPLIANCE_RATING; identity SOURCE_FIELD_NAME.
SELECT d.SOURCE_RECORD_ID AS CONTENT_ID, d.SOURCE_TABLE_NAME,
       'assessment-results.results[].props[compliance-rating].value' AS OSCAL_ELEMENT_PATH,
       d.ELEMENT_TYPE AS OSCAL_ELEMENT,
       'COMPLIANCE_RATING' AS ARCHER_FIELD_NAME,
       d.METADATA_JSON:value AS FIELD_VALUE
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT d
WHERE d.ELEMENT_TYPE='props'
  AND d.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW'
  AND d.METADATA_JSON:name::VARCHAR='compliance-rating'
  AND d.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=MD5_BINARY(
    'v1_registry_path_instance|ARCHER|'||d.SOURCE_TABLE_NAME||'|'||
    d.SOURCE_RECORD_ID||'|ASSESSMENT_RESULTS|'||
    'assessment-results.results[].props[]|COMPLIANCE_RATING'
  )
ORDER BY CONTENT_ID LIMIT 25;

