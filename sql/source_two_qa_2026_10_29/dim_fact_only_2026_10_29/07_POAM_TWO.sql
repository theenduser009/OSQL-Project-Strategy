-- POAM (SOURCE ONE) | 2026-10-29 | READ ONLY | NO ARCHER RAW TABLES
-- Output: CONTENT_ID, SOURCE_TABLE_NAME, OSCAL_ELEMENT_PATH,
--         OSCAL_ELEMENT, ARCHER_FIELD_NAME, FIELD_VALUE
-- Field names are reconstructed from approved mapping identity or unique native
-- mappings, not automatically read from a universal Archer column in DIM.
-- Sample only; test in DEV and verify deployed mapping/registry before QA PASS.

-- 1: POAMS item representation; target may preserve only UUID, not original Archer ref ID.
SELECT d.SOURCE_RECORD_ID AS CONTENT_ID,d.SOURCE_TABLE_NAME,
       'plan-of-action-and-milestones.poam-items[]' AS OSCAL_ELEMENT_PATH,
       d.ELEMENT_TYPE AS OSCAL_ELEMENT,
       'POAMS' AS ARCHER_FIELD_NAME,
       d.METADATA_JSON AS FIELD_VALUE
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT d
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_POAM_DEPENDENCY f
  ON f.FK_TARGET_ELEMENT_HASH=d.PK_DIM_OSCAL_POAM_ELEMENT_HASH
 AND f.DEPENDENCY_TYPE='CONTAINS'
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT parent
  ON parent.PK_DIM_OSCAL_POAM_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
WHERE d.ELEMENT_TYPE='poam-items'
  AND parent.ELEMENT_TYPE='plan-of-action-and-milestones'
  AND d.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
ORDER BY CONTENT_ID LIMIT 25;

-- 2: POAMS relationship target UUID from the FACT; this is OSCAL target value, not raw Archer ContentId.
SELECT child.SOURCE_RECORD_ID AS CONTENT_ID,child.SOURCE_TABLE_NAME,
       'plan-of-action-and-milestones.poam-items[].uuid' AS OSCAL_ELEMENT_PATH,
       child.ELEMENT_TYPE AS OSCAL_ELEMENT,
       'POAMS' AS ARCHER_FIELD_NAME,
       f.TARGET_OSCAL_UUID AS FIELD_VALUE
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_POAM_DEPENDENCY f
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT child
  ON child.PK_DIM_OSCAL_POAM_ELEMENT_HASH=f.FK_TARGET_ELEMENT_HASH
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT parent
  ON parent.PK_DIM_OSCAL_POAM_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
WHERE child.ELEMENT_TYPE='poam-items'
  AND parent.ELEMENT_TYPE='plan-of-action-and-milestones'
  AND child.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
ORDER BY CONTENT_ID LIMIT 25;
