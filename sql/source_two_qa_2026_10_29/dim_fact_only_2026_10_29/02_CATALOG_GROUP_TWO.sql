-- 1: NUMBER_OF_CONTROL_STANDARDS_TOPIC_LEVEL for TOPIC group (actual Archer child Content ID stored in archer-content-id)
-- Catalog DIM.SOURCE_RECORD_ID refers to the root Source; child record is embedded.
SELECT id.VALUE:value::VARCHAR AS CONTENT_ID,
       'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW' AS SOURCE_TABLE_NAME,
       'catalog.groups[].props[control-count].value' AS OSCAL_ELEMENT_PATH,
       d.ELEMENT_TYPE AS OSCAL_ELEMENT,
       'NUMBER_OF_CONTROL_STANDARDS_TOPIC_LEVEL' AS ARCHER_FIELD_NAME,
       p.VALUE:value AS FIELD_VALUE
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT d
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f
  ON f.FK_TARGET_ELEMENT_HASH=d.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
 AND f.DEPENDENCY_TYPE='CONTAINS'
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT parent
  ON parent.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH,
LATERAL FLATTEN(INPUT=>d.METADATA_JSON:props) id,
LATERAL FLATTEN(INPUT=>d.METADATA_JSON:props) p
WHERE d.ELEMENT_TYPE='groups'
  AND d.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
  AND id.VALUE:name::VARCHAR='archer-content-id'
  AND p.VALUE:name::VARCHAR='control-count'
  AND parent.ELEMENT_TYPE='catalog'
ORDER BY CONTENT_ID LIMIT 25;

-- 2: NUMBER_OF_CONTROL_STANDARDS_SECTION_LEVEL for SECTION group (actual Archer child Content ID stored in archer-content-id)
-- Catalog DIM.SOURCE_RECORD_ID refers to the root Source; child record is embedded.
SELECT id.VALUE:value::VARCHAR AS CONTENT_ID,
       'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW' AS SOURCE_TABLE_NAME,
       'catalog.groups[].groups[].props[control-count].value' AS OSCAL_ELEMENT_PATH,
       d.ELEMENT_TYPE AS OSCAL_ELEMENT,
       'NUMBER_OF_CONTROL_STANDARDS_SECTION_LEVEL' AS ARCHER_FIELD_NAME,
       p.VALUE:value AS FIELD_VALUE
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT d
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f
  ON f.FK_TARGET_ELEMENT_HASH=d.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
 AND f.DEPENDENCY_TYPE='CONTAINS'
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT parent
  ON parent.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f2
  ON f2.FK_TARGET_ELEMENT_HASH=parent.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
 AND f2.DEPENDENCY_TYPE='CONTAINS'
JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT grand
  ON grand.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH=f2.FK_SOURCE_ELEMENT_HASH,
LATERAL FLATTEN(INPUT=>d.METADATA_JSON:props) id,
LATERAL FLATTEN(INPUT=>d.METADATA_JSON:props) p
WHERE d.ELEMENT_TYPE='groups'
  AND d.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
  AND id.VALUE:name::VARCHAR='archer-content-id'
  AND p.VALUE:name::VARCHAR='control-count'
  AND parent.ELEMENT_TYPE='groups' AND grand.ELEMENT_TYPE='catalog'
ORDER BY CONTENT_ID LIMIT 25;
