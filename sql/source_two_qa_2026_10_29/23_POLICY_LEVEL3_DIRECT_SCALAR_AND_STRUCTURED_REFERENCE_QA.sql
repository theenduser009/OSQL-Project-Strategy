-- 01: Profile Sub-Section direct POLICY_LEVEL_3 ARRAY MEMBER SHAPES.
-- Does not assume each numeric is a valid record ID.
WITH subsection_rows AS (
 SELECT CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
        GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
                TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
            'POLICY_LEVEL_3') AS REFERENCE_ARRAY
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
items AS (
 SELECT s.OWNER_CONTENT_ID, f.INDEX AS ITEM_INDEX,
        TYPEOF(f.VALUE) AS ITEM_TYPE,
        CASE WHEN TYPEOF(f.VALUE)='OBJECT'
             THEN f.VALUE:ContentId::VARCHAR
             WHEN TYPEOF(f.VALUE) IN ('INTEGER','DECIMAL','VARCHAR')
             THEN f.VALUE::VARCHAR
        END AS CANDIDATE_CONTENT_ID,
        IFF(TYPEOF(f.VALUE)='OBJECT',
            f.VALUE:LevelId::VARCHAR,NULL) AS OBJECT_LEVEL_ID
 FROM subsection_rows s,
      LATERAL FLATTEN(INPUT=>IFF(IS_ARRAY(s.REFERENCE_ARRAY),
                       s.REFERENCE_ARRAY,ARRAY_CONSTRUCT())) f
),
target_by_id AS (
 SELECT CONTENT_ID::VARCHAR AS CONTENT_ID, COUNT(*) AS TARGET_ROWS,
        COUNT_IF(CURATED_JSON IS NOT NULL) AS CURATED_ROWS
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW
 GROUP BY CONTENT_ID::VARCHAR
)
SELECT i.ITEM_TYPE,
       COUNT(*) AS ARRAY_ITEM_OCCURRENCES,
       COUNT(DISTINCT i.OWNER_CONTENT_ID) AS OWNER_RECORDS,
       COUNT(DISTINCT i.CANDIDATE_CONTENT_ID) AS DISTINCT_CANDIDATE_IDS,
       COUNT_IF(REGEXP_LIKE(COALESCE(i.CANDIDATE_CONTENT_ID,''),'^[1-9][0-9]*$')) AS POSITIVE_NUMERIC_IDS,
       COUNT_IF(i.ITEM_TYPE='OBJECT' AND i.OBJECT_LEVEL_ID='5') AS OBJECT_LEVEL5_IDS,
       COUNT_IF(t.CONTENT_ID IS NOT NULL AND t.TARGET_ROWS=1) AS UNIQUE_POLICY_L3_RAW_MATCHES,
       COUNT_IF(t.CONTENT_ID IS NULL) AS UNMATCHED_POLICY_L3_RAW_ITEMS,
       COUNT_IF(t.TARGET_ROWS>1) AS DUPLICATE_TARGET_RAW_ID_ITEMS,
       COUNT_IF(t.TARGET_ROWS=1 AND t.CURATED_ROWS=0) AS TARGET_JSON_MISSING_ITEMS
FROM items i LEFT JOIN target_by_id t
  ON REGEXP_LIKE(COALESCE(i.CANDIDATE_CONTENT_ID,''),'^[1-9][0-9]*$')
 AND t.CONTENT_ID=i.CANDIDATE_CONTENT_ID
GROUP BY i.ITEM_TYPE
ORDER BY ARRAY_ITEM_OCCURRENCES DESC,ITEM_TYPE;

-- 02: FULL FOUR-LEVEL business-ID coverage with BOTH object and direct
-- scalar Sub-Section shapes. Scalar matches prove raw ID match, but are not
-- an encoded LevelId=5 because their original members had no LevelId.
WITH owner_fields AS (
SELECT 'Source' AS SOURCE_LEVEL,
       'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW' AS SOURCE_TABLE_NAME,
       CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
       'POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS' AS ARCHER_FIELD_NAME,
       GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
           'POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS') AS REFERENCE_ARRAY
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
UNION ALL
SELECT 'Topic' AS SOURCE_LEVEL,
       'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW' AS SOURCE_TABLE_NAME,
       CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
       'POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS' AS ARCHER_FIELD_NAME,
       GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
           'POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS') AS REFERENCE_ARRAY
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
UNION ALL
SELECT 'Section' AS SOURCE_LEVEL,
       'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW' AS SOURCE_TABLE_NAME,
       CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
       'POLICY_LEVEL_3_FROM_SECTION_LEVEL_AND_BELOW' AS ARCHER_FIELD_NAME,
       GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
           'POLICY_LEVEL_3_FROM_SECTION_LEVEL_AND_BELOW') AS REFERENCE_ARRAY
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
UNION ALL
SELECT 'Sub-Section' AS SOURCE_LEVEL,
       'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW' AS SOURCE_TABLE_NAME,
       CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
       'POLICY_LEVEL_3' AS ARCHER_FIELD_NAME,
       GET(IFF(TYPEOF(CURATED_JSON)='VARCHAR',
               TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON),
           'POLICY_LEVEL_3') AS REFERENCE_ARRAY
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
refs AS (
 SELECT o.SOURCE_LEVEL,o.SOURCE_TABLE_NAME,o.OWNER_CONTENT_ID,
        o.ARCHER_FIELD_NAME,f.INDEX AS REFERENCE_INDEX,
        TYPEOF(f.VALUE) AS ITEM_TYPE,
        CASE WHEN TYPEOF(f.VALUE)='OBJECT' THEN f.VALUE:ContentId::VARCHAR
             WHEN TYPEOF(f.VALUE) IN ('INTEGER','DECIMAL','VARCHAR')
                  THEN f.VALUE::VARCHAR
             ELSE NULL END AS CANDIDATE_CONTENT_ID,
        IFF(TYPEOF(f.VALUE)='OBJECT',
            f.VALUE:LevelId::VARCHAR,NULL) AS OBJECT_LEVEL_ID
 FROM owner_fields o,
      LATERAL FLATTEN(INPUT=>IFF(IS_ARRAY(o.REFERENCE_ARRAY),
                         o.REFERENCE_ARRAY,ARRAY_CONSTRUCT())) f
),
classified AS (
 SELECT *,
   CASE WHEN ITEM_TYPE='OBJECT' AND OBJECT_LEVEL_ID='5'
             AND REGEXP_LIKE(COALESCE(CANDIDATE_CONTENT_ID,''),'^[1-9][0-9]*$')
          THEN 'OBJECT_LEVEL5'
        WHEN SOURCE_LEVEL='Sub-Section'
             AND ITEM_TYPE IN ('INTEGER','DECIMAL','VARCHAR')
             AND REGEXP_LIKE(COALESCE(CANDIDATE_CONTENT_ID,''),'^[1-9][0-9]*$')
          THEN 'SUBSECTION_SCALAR_CANDIDATE'
        ELSE 'OTHER_OR_INVALID' END AS REFERENCE_FORM
 FROM refs
),
target_rows AS (
 SELECT CONTENT_ID::VARCHAR AS POLICY_CONTENT_ID,
        IFF(TYPEOF(CURATED_JSON)='VARCHAR',
            TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON) AS J
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW
 WHERE CONTENT_ID IS NOT NULL
),
target_by_id AS (
 SELECT POLICY_CONTENT_ID,
        COUNT(*) AS TARGET_ROWS,
        COUNT_IF(J IS NOT NULL) AS TARGET_CURATED_ROWS,
        MAX(GET(J,'POLICY_LEVEL_3_NAME')::VARCHAR) AS POLICY_NAME,
        MAX(GET(J,'POLICY_TOPIC_NAME')::VARCHAR) AS POLICY_TOPIC,
        MAX(GET(J,'POLICY_NUMBER')::VARCHAR) AS POLICY_NUMBER
 FROM target_rows GROUP BY POLICY_CONTENT_ID
)
SELECT IFF(GROUPING(c.SOURCE_LEVEL)=1,'ALL',c.SOURCE_LEVEL) AS SOURCE_LEVEL,
       COUNT(*) AS REFERENCE_OCCURRENCES,
       COUNT_IF(c.REFERENCE_FORM='OBJECT_LEVEL5') AS STRUCTURED_OBJECT_LEVEL5,
       COUNT_IF(c.REFERENCE_FORM='SUBSECTION_SCALAR_CANDIDATE') AS DIRECT_SCALAR_CANDIDATES,
       COUNT_IF(c.REFERENCE_FORM='OTHER_OR_INVALID') AS OTHER_OR_INVALID_ITEMS,
       COUNT_IF(c.REFERENCE_FORM<>'OTHER_OR_INVALID'
                AND t.TARGET_ROWS=1) AS UNIQUE_LEVEL3_RAW_MATCHES,
       COUNT_IF(c.REFERENCE_FORM<>'OTHER_OR_INVALID'
                AND t.POLICY_CONTENT_ID IS NULL) AS VALID_SHAPE_BUT_RAW_UNMATCHED,
       COUNT_IF(c.REFERENCE_FORM<>'OTHER_OR_INVALID'
                AND t.TARGET_ROWS>1) AS AMBIGUOUS_POLICY_CONTENT_IDS,
       COUNT_IF(c.REFERENCE_FORM<>'OTHER_OR_INVALID'
                AND t.TARGET_ROWS=1 AND t.TARGET_CURATED_ROWS=0) AS TARGET_JSON_MISSING,
       COUNT_IF(c.REFERENCE_FORM<>'OTHER_OR_INVALID'
                AND t.TARGET_ROWS=1 AND NULLIF(TRIM(t.POLICY_NAME),'') IS NOT NULL)
         AS RESOLVED_WITH_NONEMPTY_POLICY_NAME,
       COUNT(DISTINCT IFF(c.REFERENCE_FORM<>'OTHER_OR_INVALID',
                          c.CANDIDATE_CONTENT_ID,NULL)) AS DISTINCT_VALID_SHAPE_IDS
FROM classified c
LEFT JOIN target_by_id t
 ON c.REFERENCE_FORM<>'OTHER_OR_INVALID'
 AND c.CANDIDATE_CONTENT_ID=t.POLICY_CONTENT_ID
GROUP BY ROLLUP(c.SOURCE_LEVEL)
ORDER BY GROUPING(c.SOURCE_LEVEL),SOURCE_LEVEL;

