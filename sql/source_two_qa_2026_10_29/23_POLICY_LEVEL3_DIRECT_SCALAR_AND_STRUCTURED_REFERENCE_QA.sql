-- Snowflake DEV read-only SELECTs. Run three queries independently.
-- Owner-run screenshot evidence on October 29:
--   10,929 structured Policy Level3 object references matched ARCHER_META_CONTENT;
--   2,349 Sub-Section references were marked INVALID solely by SQL22's
--   object-and-LevelId=5 shape condition; unknown if these are numeric IDs.
--   Real Policy L3 table: RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW.
--   Example Policy L3 business fields populated: POLICY_LEVEL_3_NAME,
--   POLICY_TOPIC_NAME, POLICY_NUMBER; POLICY_PURPOSE can be null.
-- Difference in source grain is critical: direct Sub-Section POLICY_LEVEL_3
-- vs Source/Topic/Section descendant inherited rollup arrays.
-- Treat scalar refs as candidate IDs, NOT validated LevelIds until target
-- record match to actual Level3 RAW; no invented {ContentId,LevelId} object.
-- No DML, changes to mapper/registry, or native OSCAL relationship claim.
