-- Source Two QA 21 | 2026-10-29 | SELECT ONLY | DEV
-- Owner Snowflake SQL20 readback: LevelId 39 = CONTROL PROCEDURES (Module 153).
-- 303983 reference occurrences matched 2627 distinct procedure Content IDs.
-- Owner target field profiler: CONTROL_PROCEDURE_ID, CONTROL_PROCEDURE_NAME,
-- DESCRIPTION, PROCEDURE_TRACKING_ID have 3112 nonempty occurrences each.
-- Return each source owner and the procedure's business values.
-- Original names come from ACTUAL target CURATED_JSON, not guessed from REF_ID.
-- This is Archer-to-Archer resolution, NOT proof of a native OSCAL link.
-- To filter to a specific owner ContentId, edit the refs CTE WHERE after
-- confirming the source level; do not commit private IDs to public GitHub.

WITH source_rows AS (
 SELECT 'Source' AS SOURCE_LEVEL,
        'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW' AS SOURCE_TABLE_NAME,
        CONTENT_ID::VARCHAR AS OWNER_CONTENT_ID,
        IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON) AS J
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
 UNION ALL
 SELECT 'Topic','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',
        CONTENT_ID::VARCHAR,
        IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON)
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
 UNION ALL
 SELECT 'Section','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW',
        CONTENT_ID::VARCHAR,
        IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON)
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
 UNION ALL
 SELECT 'Sub-Section','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW',
        CONTENT_ID::VARCHAR,
        IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON)
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
refs AS (
 SELECT s.SOURCE_LEVEL,s.SOURCE_TABLE_NAME,s.OWNER_CONTENT_ID,
        f.INDEX AS REFERENCE_INDEX,TYPEOF(f.VALUE) AS ITEM_TYPE,
        f.VALUE:ContentId::VARCHAR AS TARGET_CONTENT_ID,
        f.VALUE:LevelId::VARCHAR AS TARGET_LEVEL_ID
 FROM source_rows s,
      LATERAL FLATTEN(INPUT=>GET(s.J,'RELATED_CONTROL_PROCEDURES')) f
),
target_rows AS (
 SELECT CONTENT_ID::VARCHAR AS CONTENT_ID,
        IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON) AS J
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_PROCEDURES_RAW
 WHERE CONTENT_ID IS NOT NULL
),
target_by_id AS (
 SELECT CONTENT_ID,COUNT(*) AS TARGET_ROW_COUNT,
        COUNT_IF(J IS NOT NULL) AS CURATED_ROW_COUNT,
        MAX(GET(J,'CONTROL_PROCEDURE_ID')::VARCHAR) AS PROCEDURE_ID,
        MAX(GET(J,'CONTROL_PROCEDURE_NAME')::VARCHAR) AS PROCEDURE_NAME,
        MAX(GET(J,'DESCRIPTION')::VARCHAR) AS PROCEDURE_DESCRIPTION,
        MAX(GET(J,'PROCEDURE_TRACKING_ID')::VARCHAR) AS PROCEDURE_TRACKING_ID
 FROM target_rows GROUP BY CONTENT_ID
)
SELECT r.SOURCE_LEVEL,r.SOURCE_TABLE_NAME,
       r.OWNER_CONTENT_ID,
       'RELATED_CONTROL_PROCEDURES' AS ARCHER_FIELD_NAME,
       r.REFERENCE_INDEX,
       r.TARGET_CONTENT_ID AS PROCEDURE_CONTENT_ID,r.TARGET_LEVEL_ID,
       IFF(t.TARGET_ROW_COUNT=1,t.PROCEDURE_ID,NULL) AS CONTROL_PROCEDURE_ID,
       IFF(t.TARGET_ROW_COUNT=1,t.PROCEDURE_NAME,NULL) AS CONTROL_PROCEDURE_NAME,
       IFF(t.TARGET_ROW_COUNT=1,t.PROCEDURE_DESCRIPTION,NULL) AS DESCRIPTION,
       IFF(t.TARGET_ROW_COUNT=1,t.PROCEDURE_TRACKING_ID,NULL) AS PROCEDURE_TRACKING_ID,
       CASE WHEN r.ITEM_TYPE<>'OBJECT' OR
                 NOT REGEXP_LIKE(COALESCE(r.TARGET_CONTENT_ID,''),'^[1-9][0-9]*$')
              THEN 'INVALID_REFERENCE'
            WHEN r.TARGET_LEVEL_ID IS DISTINCT FROM '39'
              THEN 'WRONG_ARCHER_LEVEL'
            WHEN t.CONTENT_ID IS NULL THEN 'TARGET_NOT_FOUND'
            WHEN t.TARGET_ROW_COUNT<>1 THEN 'AMBIGUOUS_TARGET_CONTENT_ID'
            WHEN t.CURATED_ROW_COUNT<>1 THEN 'TARGET_CURATED_JSON_MISSING'
            WHEN NULLIF(TRIM(t.PROCEDURE_NAME),'') IS NULL THEN 'PROCEDURE_NAME_MISSING'
            WHEN NULLIF(TRIM(t.PROCEDURE_ID),'') IS NULL THEN 'PROCEDURE_BUSINESS_ID_MISSING'
            ELSE 'ARCHER_RECORD_AND_NAME_RESOLVED_OSCAL_NOT_TESTED'
       END AS QA_STATUS
FROM refs r LEFT JOIN target_by_id t ON t.CONTENT_ID=r.TARGET_CONTENT_ID
QUALIFY ROW_NUMBER() OVER
  (PARTITION BY r.SOURCE_LEVEL ORDER BY r.OWNER_CONTENT_ID,r.REFERENCE_INDEX)<=25
ORDER BY r.SOURCE_LEVEL,r.OWNER_CONTENT_ID,r.REFERENCE_INDEX
LIMIT 100;