-- Source Two QA 12: COMPLIANCE_RATING, identical field name across levels.
-- Read-only Snowflake DEV; one SELECT, exactly seven output columns.
-- Distinguish a property by Source Table + Content ID + field-derived DIM hash,
-- NOT by the common OSCAL property name alone.
-- Runtime identity contract to verify: assessment-results.results[].props[]
-- uses SOURCE_FIELD_NAME (not SOURCE_FIELD_NAME+VALUE).
-- Oct 27 accepted AR routes: Topic, Section, Sub-Section. Source AR is
-- included to show the source context but its route is NOT accepted in that receipt.
WITH raw AS (
  SELECT 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW' AS RAW_TABLE,
         CONTENT_ID::VARCHAR AS CID,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON) AS J
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
  UNION ALL
  SELECT 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
  UNION ALL
  SELECT 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
  UNION ALL
  SELECT 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
)
SELECT
  r.RAW_TABLE AS ARCHER_TABLE_NAME,
  r.CID AS CONTENT_ID,
  'COMPLIANCE_RATING' AS ARCHER_FIELD_NAME,
  GET(r.J,'COMPLIANCE_RATING') AS ARCHER_VALUE,
  d.METADATA_JSON:name::VARCHAR AS OSCAL_PROPERTY_NAME,
  d.ELEMENT_TYPE AS OSCAL_ELEMENT_TYPE,
  d.METADATA_JSON:value AS OSCAL_VALUE
FROM raw r
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT d
  ON d.SOURCE_TABLE_NAME=r.RAW_TABLE
 AND d.SOURCE_RECORD_ID=r.CID
 AND d.ELEMENT_TYPE='props'
 AND d.METADATA_JSON:name::VARCHAR='compliance-rating'
 AND d.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=MD5_BINARY(
      'v1_registry_path_instance|ARCHER|'||r.RAW_TABLE||'|'||r.CID||
      '|ASSESSMENT_RESULTS|assessment-results.results[].props[]|COMPLIANCE_RATING'
    )
QUALIFY ROW_NUMBER() OVER (PARTITION BY r.RAW_TABLE ORDER BY r.CID) <= 8
ORDER BY ARCHER_TABLE_NAME,CONTENT_ID;
