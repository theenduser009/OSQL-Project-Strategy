-- Source Two QA 13: SAME field RELATED_TO_KEY_CONTROLS in Topic/Section/Sub-Section.
-- Read-only Snowflake DEV; one SELECT with seven output columns.
-- Catalog hierarchy is stored under Source-owned DIM.SOURCE_RECORD_ID, so do NOT
-- join Topic/Section/Sub-Section RAW.CONTENT_ID directly to DIM.SOURCE_RECORD_ID.
-- Resolve each child by its 'archer-content-id' embedded prop and FACT depth.
-- Property name only gives a candidate attribution; compare transforms and
-- check active compiled mapping for another field owning this same prop name.
-- Source-to-target parity for this field was photographed 2026-10-22 for all
-- 31,982 Topic/Section/Sub-Section records, not independently rerun here.
WITH raw AS (
  SELECT 'TOPIC' AS LVL, 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW' AS RAW_TABLE,
         CONTENT_ID::VARCHAR AS CID,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON) AS J
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
  UNION ALL
  SELECT 'SECTION','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
  UNION ALL
  SELECT 'SUB_SECTION','ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
), catalog_groups AS (
  SELECT
    CASE WHEN parent.ELEMENT_TYPE='catalog' THEN 'TOPIC'
         WHEN grand.ELEMENT_TYPE='catalog' THEN 'SECTION'
         WHEN great.ELEMENT_TYPE='catalog' THEN 'SUB_SECTION'
    END AS LVL,
    marker.VALUE:value::VARCHAR AS CHILD_CONTENT_ID,
    d.ELEMENT_TYPE,
    d.METADATA_JSON
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT d
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY edge1
    ON edge1.FK_TARGET_ELEMENT_HASH=d.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
   AND edge1.DEPENDENCY_TYPE='CONTAINS'
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT parent
    ON parent.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH=edge1.FK_SOURCE_ELEMENT_HASH
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY edge2
    ON edge2.FK_TARGET_ELEMENT_HASH=parent.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
   AND edge2.DEPENDENCY_TYPE='CONTAINS'
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT grand
    ON grand.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH=edge2.FK_SOURCE_ELEMENT_HASH
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY edge3
    ON edge3.FK_TARGET_ELEMENT_HASH=grand.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
   AND edge3.DEPENDENCY_TYPE='CONTAINS'
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT great
    ON great.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH=edge3.FK_SOURCE_ELEMENT_HASH,
  LATERAL FLATTEN(INPUT=>d.METADATA_JSON:props) marker
  WHERE d.ELEMENT_TYPE='groups'
    AND d.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
    AND marker.VALUE:name::VARCHAR='archer-content-id'
), field_props AS (
  SELECT g.LVL,g.CHILD_CONTENT_ID,g.ELEMENT_TYPE,
         p.VALUE:value AS PROP_VALUE
  FROM catalog_groups g,
       LATERAL FLATTEN(INPUT=>g.METADATA_JSON:props) p
  WHERE p.VALUE:name::VARCHAR='related-to-key-controls'
)
SELECT
  r.RAW_TABLE AS ARCHER_TABLE_NAME,
  r.CID AS CONTENT_ID,
  'RELATED_TO_KEY_CONTROLS' AS ARCHER_FIELD_NAME,
  GET(r.J,'RELATED_TO_KEY_CONTROLS') AS ARCHER_VALUE,
  IFF(p.ELEMENT_TYPE IS NULL,NULL,'related-to-key-controls') AS OSCAL_PROPERTY_NAME,
  p.ELEMENT_TYPE AS OSCAL_ELEMENT_TYPE,
  p.PROP_VALUE AS OSCAL_VALUE
FROM raw r
LEFT JOIN field_props p
  ON p.LVL=r.LVL AND p.CHILD_CONTENT_ID=r.CID
QUALIFY ROW_NUMBER() OVER (PARTITION BY r.RAW_TABLE ORDER BY r.CID) <= 8
ORDER BY ARCHER_TABLE_NAME,CONTENT_ID;
