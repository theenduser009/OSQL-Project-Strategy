-- Source Two policy reference diagnostic | 2026-10-29 | DIM-only, READ-ONLY
-- DO NOT treat ContentId/LevelId extraction as a resolved OSCAL relationship.
-- This SELECT only parses persisted property text in the query result.
-- Replacing the source Content IDs below selects other root Source records.
-- For nested Catalog groups, DIM SOURCE_RECORD_ID identifies the owning
-- Source root, NOT necessarily the embedded Topic/Section/Sub-Section child.
-- No raw Archer tables, no database writes, no source identifiers fabricated.

-- QUERY 1: Catalog (embedded plus individually stored property values)
WITH stored_props AS (
  SELECT d.SOURCE_TABLE_NAME, d.SOURCE_RECORD_ID AS ROOT_SOURCE_CONTENT_ID,
         d.ELEMENT_TYPE, d.METADATA_JSON:name::VARCHAR AS PROPERTY_NAME,
         d.METADATA_JSON:value AS STORED_VALUE
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT d
  WHERE d.SOURCE_RECORD_ID IN ('185810','185837','207242')
    AND d.METADATA_JSON:name::VARCHAR ILIKE '%polic%'
  UNION ALL
  SELECT d.SOURCE_TABLE_NAME, d.SOURCE_RECORD_ID,
         d.ELEMENT_TYPE, p.VALUE:name::VARCHAR, p.VALUE:value
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT d,
       LATERAL FLATTEN(INPUT=>d.METADATA_JSON:props) p
  WHERE d.SOURCE_RECORD_ID IN ('185810','185837','207242')
    AND p.VALUE:name::VARCHAR ILIKE '%polic%'
),
decoded AS (
  SELECT *, TYPEOF(STORED_VALUE) AS STORED_TYPE,
         COALESCE(TRY_PARSE_JSON(STORED_VALUE::VARCHAR),STORED_VALUE) AS PARSED_VALUE
  FROM stored_props
)
SELECT SOURCE_TABLE_NAME, ROOT_SOURCE_CONTENT_ID, ELEMENT_TYPE, PROPERTY_NAME,
       STORED_TYPE, TYPEOF(PARSED_VALUE) AS PARSED_TYPE,
       r.VALUE:ContentId::VARCHAR AS REFERENCED_ARCHER_CONTENT_ID,
       r.VALUE:LevelId::VARCHAR AS REFERENCED_ARCHER_LEVEL_ID,
       CASE WHEN r.VALUE:ContentId IS NOT NULL THEN 'REFERENCE_EXTRACTED_NOT_RESOLVED'
            WHEN IS_ARRAY(PARSED_VALUE) THEN 'ARRAY_ITEM_NO_CONTENT_ID'
            ELSE 'NON_REFERENCE_OR_UNPARSEABLE' END AS DIAGNOSTIC
FROM decoded d,
     LATERAL FLATTEN(INPUT=>IFF(IS_ARRAY(d.PARSED_VALUE),
                                 d.PARSED_VALUE,ARRAY_CONSTRUCT()),
                     OUTER=>TRUE) r
ORDER BY ROOT_SOURCE_CONTENT_ID,PROPERTY_NAME,REFERENCED_ARCHER_CONTENT_ID
LIMIT 100;

-- QUERY 2: Component Definition (separately stored policy props)
WITH stored_props AS (
  SELECT d.SOURCE_TABLE_NAME, d.SOURCE_RECORD_ID AS CONTENT_ID,
         d.ELEMENT_TYPE, d.METADATA_JSON:name::VARCHAR AS PROPERTY_NAME,
         d.METADATA_JSON:value AS STORED_VALUE
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_COMPONENT_ELEMENT d
  WHERE d.SOURCE_RECORD_ID IN ('185810','185837','207242')
    AND d.ELEMENT_TYPE='props'
    AND d.METADATA_JSON:name::VARCHAR ILIKE '%polic%'
),
decoded AS (
  SELECT *, TYPEOF(STORED_VALUE) AS STORED_TYPE,
         COALESCE(TRY_PARSE_JSON(STORED_VALUE::VARCHAR),STORED_VALUE) AS PARSED_VALUE
  FROM stored_props
)
SELECT SOURCE_TABLE_NAME, CONTENT_ID, ELEMENT_TYPE, PROPERTY_NAME,
       STORED_TYPE, TYPEOF(PARSED_VALUE) AS PARSED_TYPE,
       r.VALUE:ContentId::VARCHAR AS REFERENCED_ARCHER_CONTENT_ID,
       r.VALUE:LevelId::VARCHAR AS REFERENCED_ARCHER_LEVEL_ID,
       CASE WHEN r.VALUE:ContentId IS NOT NULL THEN 'REFERENCE_EXTRACTED_NOT_RESOLVED'
            WHEN IS_ARRAY(PARSED_VALUE) THEN 'ARRAY_ITEM_NO_CONTENT_ID'
            ELSE 'NON_REFERENCE_OR_UNPARSEABLE' END AS DIAGNOSTIC
FROM decoded d,
     LATERAL FLATTEN(INPUT=>IFF(IS_ARRAY(d.PARSED_VALUE),
                                 d.PARSED_VALUE,ARRAY_CONSTRUCT()),
                     OUTER=>TRUE) r
ORDER BY CONTENT_ID,PROPERTY_NAME,REFERENCED_ARCHER_CONTENT_ID
LIMIT 100;
