-- 2026-10-30 | SOURCE TWO TOPIC: SECTION_REFERENCES enrichment diagnostic
-- READ ONLY. Run Query 1 first, then Query 2, in Snowflake DEV.
-- The original CURATED_JSON preserves its {ContentId,LevelId} references by design.
-- The optional extra enrichment adds sidecar metadata, NEVER replaces them.
-- Draft generic resolver PR19 does NOT yet whitelist SECTION_REFERENCES.
-- Queries help separate "additive step not run" from "field not in contract".
-- No Matillion writes, OSCAL writes, or changing source data.
--
-- Query 1: See original Topic field and enrichment sidecar, if any.
WITH topic AS (
 SELECT CONTENT_ID::VARCHAR AS TOPIC_CONTENT_ID,
        IFF(TYPEOF(CURATED_JSON)='VARCHAR',
            TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON) AS J
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
)
SELECT TOPIC_CONTENT_ID,
       GET(J,'SECTION_REFERENCES') AS ORIGINAL_SECTION_REFERENCES,
       IFF(GET(J,'_OSCAL_RESOLVED_RECORD_REFERENCES') IS NOT NULL,
           'SIDECAR_PRESENT','SIDECAR_NOT_PRESENT') AS SIDECAR_STATUS,
       GET(GET(J,'_OSCAL_RESOLVED_RECORD_REFERENCES'),
           'SECTION_REFERENCES') AS RESOLVED_SECTION_REFERENCES,
       CASE
         WHEN GET(J,'_OSCAL_RESOLVED_RECORD_REFERENCES') IS NULL
           THEN 'NEW_ENRICHMENT_NOT_VISIBLE_ON_THIS_RECORD'
         WHEN GET(GET(J,'_OSCAL_RESOLVED_RECORD_REFERENCES'),
                  'SECTION_REFERENCES') IS NULL
           THEN 'ENRICHMENT_PRESENT_BUT_SECTION_FIELD_NOT_INCLUDED'
         ELSE 'RESOLVED_SECTION_SIDECAR_PRESENT'
       END AS DIAGNOSTIC
FROM topic
WHERE IS_ARRAY(GET(J,'SECTION_REFERENCES'))
  AND ARRAY_SIZE(GET(J,'SECTION_REFERENCES'))>0
ORDER BY TOPIC_CONTENT_ID
LIMIT 20;

-- Query 2: Validate referenced Topic -> Section Content IDs and Level IDs
-- against the actual SECTION_RAW table; no assumed LevelId or name.
WITH topic AS (
 SELECT CONTENT_ID::VARCHAR AS TOPIC_CONTENT_ID,
        IFF(TYPEOF(CURATED_JSON)='VARCHAR',
            TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON) AS J
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
),
refs AS (
 SELECT t.TOPIC_CONTENT_ID, f.INDEX AS REF_INDEX,
        TYPEOF(f.VALUE) AS ITEM_TYPE,
        f.VALUE:ContentId::VARCHAR AS SECTION_CONTENT_ID,
        f.VALUE:LevelId::VARCHAR AS REF_LEVEL_ID
 FROM topic t,
      LATERAL FLATTEN(
        INPUT=>IFF(IS_ARRAY(GET(t.J,'SECTION_REFERENCES')),
                   GET(t.J,'SECTION_REFERENCES'),ARRAY_CONSTRUCT())) f
),
target AS (
 SELECT CONTENT_ID::VARCHAR AS SECTION_CONTENT_ID,
        COUNT(*) AS TARGET_ROWS,
        COUNT_IF(CURATED_JSON IS NOT NULL) AS TARGET_CURATED_ROWS,
        MAX(GET(CURATED_JSON,'SECTION_NAME')::VARCHAR) AS SECTION_NAME,
        MAX(GET(CURATED_JSON,'SECTION_ID')::VARCHAR) AS SECTION_BUSINESS_ID
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
 WHERE CONTENT_ID IS NOT NULL
 GROUP BY CONTENT_ID::VARCHAR
)
SELECT r.ITEM_TYPE,r.REF_LEVEL_ID,
       m.LEVEL_NAME,m.MODULE_NAME,
       COUNT(*) AS REFERENCE_OCCURRENCES,
       COUNT(DISTINCT r.TOPIC_CONTENT_ID) AS TOPIC_OWNERS,
       COUNT(DISTINCT r.SECTION_CONTENT_ID) AS DISTINCT_REFERENCED_SECTIONS,
       COUNT_IF(t.SECTION_CONTENT_ID IS NOT NULL AND t.TARGET_ROWS=1)
           AS UNIQUE_SECTION_RAW_ID_MATCHES,
       COUNT_IF(t.SECTION_CONTENT_ID IS NULL) AS UNMATCHED_SECTION_IDS,
       COUNT_IF(t.TARGET_ROWS>1) AS AMBIGUOUS_TARGET_ID_OCCURRENCES,
       COUNT_IF(t.TARGET_ROWS=1 AND t.TARGET_CURATED_ROWS=0)
           AS MISSING_TARGET_CURATED_JSON,
       COUNT_IF(t.TARGET_ROWS=1
                AND NULLIF(TRIM(t.SECTION_NAME),'') IS NOT NULL)
           AS REFERENCES_WITH_SECTION_NAME,
       COUNT_IF(t.TARGET_ROWS=1
                AND NULLIF(TRIM(t.SECTION_BUSINESS_ID),'') IS NOT NULL)
           AS REFERENCES_WITH_SECTION_BUSINESS_ID
FROM refs r
LEFT JOIN target t ON t.SECTION_CONTENT_ID=r.SECTION_CONTENT_ID
LEFT JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_META_LEVEL m
 ON m.LEVEL_ID::VARCHAR=r.REF_LEVEL_ID
GROUP BY 1,2,3,4
ORDER BY REFERENCE_OCCURRENCES DESC,REF_LEVEL_ID;
