-- ================================================================
-- 01 COMPONENT DEFINITION POLICY-LEVEL: exact FIELD-ID via DIM HASH
-- ================================================================
-- For component-definition.components[].props[], mapper Cell 4 uses
--   INSTANCE_KEY = ARCHER_FIELD || ':' ||
--     MD5('source-field-value-v1|' || ARCHER_FIELD || '|' || emitted value)
-- Cell 5 uses
--   NODE_KEY = MD5_BINARY(identity_version || '|ARCHER|' || source_table ||
--             '|' || source_content_id || '|COMPONENT_DEFINITION|' ||
--             'component-definition.components[].props[]|' || INSTANCE_KEY).
-- The stored key identifies which field generated a same-named property,
-- independent of whether two fields happen to have identical values.
-- This reconstruction is ONLY valid when deployed runtime uses those
-- exact registry identity and mapper versions; a hash miss is NOT proof
-- of a broken mapping until those are checked. JSON null is handled
-- separately (Python's original value identity is not assumed here).
WITH raw AS (
  SELECT 'SOURCE' AS SOURCE_LEVEL,
         'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW' AS ARCHER_TABLE,
         CONTENT_ID::VARCHAR AS CONTENT_ID,
         IFF(TYPEOF(CURATED_JSON) = 'VARCHAR',
             TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)), CURATED_JSON) AS PAYLOAD
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
  UNION ALL
  SELECT 'TOPIC', 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',
         CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON) = 'VARCHAR',
             TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)), CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
),
fields AS (
  SELECT COLUMN1 AS SOURCE_LEVEL, COLUMN2 AS ARCHER_FIELD
  FROM VALUES
    ('SOURCE', 'POLICY_LEVEL_3'),
    ('SOURCE', 'POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS'),
    ('SOURCE', 'POLICY_LEVEL_3__FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS'),
    ('TOPIC',  'POLICY_LEVEL_3'),
    ('TOPIC',  'POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS'),
    ('TOPIC',  'POLICY_LEVEL_3__FROM_SECTION_AND_SUBSECTION_LEVELS')
),
source_fields AS (
  SELECT r.SOURCE_LEVEL, r.ARCHER_TABLE, r.CONTENT_ID, f.ARCHER_FIELD,
         GET(r.PAYLOAD, f.ARCHER_FIELD) AS ARCHER_VALUE,
         TYPEOF(GET(r.PAYLOAD, f.ARCHER_FIELD)) AS ARCHER_VALUE_TYPE,
         COUNT(*) OVER (PARTITION BY r.ARCHER_TABLE, r.CONTENT_ID) AS SOURCE_SNAPSHOT_ROWS
  FROM raw r JOIN fields f ON f.SOURCE_LEVEL = r.SOURCE_LEVEL
),
props AS (
  SELECT d.PK_DIM_OSCAL_COMPONENT_ELEMENT_HASH AS NODE_HASH,
         d.OSCAL_UUID AS PROP_UUID,
         d.SOURCE_TABLE_NAME AS ARCHER_TABLE,
         d.SOURCE_RECORD_ID AS CONTENT_ID,
         d.METADATA_JSON:name::VARCHAR AS PROP_NAME,
         d.METADATA_JSON:value::VARCHAR AS PROP_VALUE,
         d.METADATA_JSON AS PROP_PAYLOAD
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_COMPONENT_ELEMENT d
  WHERE d.ELEMENT_TYPE = 'props'
    AND d.METADATA_JSON:name::VARCHAR = 'policy-level'
),
candidates AS (
  SELECT s.*, p.NODE_HASH, p.PROP_UUID, p.PROP_NAME, p.PROP_VALUE,
         p.PROP_PAYLOAD,
         CASE WHEN p.PROP_VALUE IS NOT NULL THEN MD5_BINARY(
           'v1_registry_path_instance|ARCHER|' || s.ARCHER_TABLE || '|' ||
           s.CONTENT_ID || '|COMPONENT_DEFINITION|' ||
           'component-definition.components[].props[]|' || s.ARCHER_FIELD || ':' ||
           MD5('source-field-value-v1|' || s.ARCHER_FIELD || '|' || p.PROP_VALUE)
         ) ELSE NULL END AS EXPECTED_FIELD_NODE_HASH
  FROM source_fields s
  LEFT JOIN props p
    ON p.ARCHER_TABLE = s.ARCHER_TABLE
   AND p.CONTENT_ID = s.CONTENT_ID
   -- CRITICAL: exact field-derived node identity, not just shared prop name.
   AND p.NODE_HASH = MD5_BINARY(
     'v1_registry_path_instance|ARCHER|' || s.ARCHER_TABLE || '|' ||
     s.CONTENT_ID || '|COMPONENT_DEFINITION|' ||
     'component-definition.components[].props[]|' || s.ARCHER_FIELD || ':' ||
     MD5('source-field-value-v1|' || s.ARCHER_FIELD || '|' ||
         IFF(COALESCE(IS_NULL_VALUE(p.PROP_PAYLOAD:value), FALSE),
             'None', p.PROP_VALUE))
   )
)
SELECT c.SOURCE_LEVEL, c.ARCHER_TABLE, c.CONTENT_ID,
       c.ARCHER_FIELD, c.ARCHER_VALUE, c.ARCHER_VALUE_TYPE,
       c.PROP_NAME AS OSCAL_PROP_NAME, c.PROP_VALUE AS OSCAL_VALUE,
       c.PROP_UUID AS OSCAL_UUID,
       TO_VARCHAR(c.NODE_HASH, 'HEX') AS STORED_NODE_HASH,
       TO_VARCHAR(c.EXPECTED_FIELD_NODE_HASH, 'HEX') AS EXPECTED_NODE_HASH,
       par.ELEMENT_TYPE AS FACT_PARENT_TYPE,
       par.OSCAL_UUID AS FACT_PARENT_UUID,
       CASE
         WHEN c.SOURCE_SNAPSHOT_ROWS > (SELECT COUNT(*) FROM fields f
                                       WHERE f.SOURCE_LEVEL = c.SOURCE_LEVEL)
           THEN 'DUPLICATE_RAW_CONTENT_ID_REVIEW'
         WHEN c.NODE_HASH IS NULL AND (c.ARCHER_VALUE IS NULL OR COALESCE(IS_NULL_VALUE(c.ARCHER_VALUE),FALSE))
           THEN 'SOURCE_NULL_NO_FIELD_OWNED_PROPERTY'
         WHEN c.NODE_HASH IS NULL THEN 'SOURCE_POPULATED_NO_PROVEN_FIELD_OWNED_PROPERTY'
         WHEN c.PROP_VALUE IS NULL THEN 'NULL_PROPERTY_NEEDS_SPECIAL_IDENTITY_REVIEW'
         WHEN c.NODE_HASH = c.EXPECTED_FIELD_NODE_HASH
           AND (c.ARCHER_VALUE IS NULL OR COALESCE(IS_NULL_VALUE(c.ARCHER_VALUE),FALSE))
           THEN 'FIELD_HASH_MATCH_BUT_CURRENT_SOURCE_EMPTY_REVIEW'
         WHEN c.NODE_HASH = c.EXPECTED_FIELD_NODE_HASH
           THEN 'FIELD_IDENTITY_HASH_MATCH_CHECK_VALUE_TRANSFORM'
         ELSE 'NOT_THIS_ARCHER_FIELD_OR_DEPLOYED_IDENTITY_DIFFERS'
       END AS ATTRIBUTION_STATUS
FROM candidates c
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_COMPONENT_DEPENDENCY e
  ON e.FK_TARGET_ELEMENT_HASH = c.NODE_HASH AND e.DEPENDENCY_TYPE = 'CONTAINS'
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_COMPONENT_ELEMENT par
  ON par.PK_DIM_OSCAL_COMPONENT_ELEMENT_HASH = e.FK_SOURCE_ELEMENT_HASH
-- Keep source-null rows visible; no unrelated target is attached to them.
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY c.SOURCE_LEVEL, c.ARCHER_FIELD,
    IFF(c.NODE_HASH=c.EXPECTED_FIELD_NODE_HASH,'HASH_MATCH','OTHER')
  ORDER BY c.CONTENT_ID, c.PROP_UUID
) <= 12
ORDER BY c.SOURCE_LEVEL, c.ARCHER_FIELD, c.CONTENT_ID
LIMIT 300;

-- ================================================================
-- 02 CATALOG JOINED TOPIC / SECTION / SUB-SECTION FIELD OWNERSHIP
-- ================================================================
-- Catalog contains hierarchy groups nested inside the Source-owned document.
-- SOURCE_RECORD_ID on an embedded group can therefore be the SOURCE Content ID.
-- The child's true Archer Content ID is retained by prop name
-- 'archer-content-id' inside the group payload. Join it to Topic/Section/SubSection
-- RAW.CONTENT_ID -- not just catalog DIM.SOURCE_RECORD_ID.
-- This example inspects a known repeatedly populated field and its property.
-- A matching source/prop value still needs transform and no-collision checks
-- before a field-by-field PASS is awarded.
WITH raw AS (
  SELECT 'TOPIC' AS SOURCE_LEVEL, CONTENT_ID::VARCHAR AS CONTENT_ID,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON) AS PAYLOAD
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
  UNION ALL
  SELECT 'SECTION', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
  UNION ALL
  SELECT 'SUB_SECTION', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
-- Add rows to this VALUES matrix for other confirmed, executable mappings.
field_matrix AS (
  SELECT COLUMN1 AS LEVEL_NAME, COLUMN2 AS ARCHER_FIELD, COLUMN3 AS PROP_NAME
  FROM VALUES
    ('TOPIC', 'RELATED_TO_KEY_CONTROLS', 'related-to-key-controls'),
    ('SECTION', 'RELATED_TO_KEY_CONTROLS', 'related-to-key-controls'),
    ('SUB_SECTION', 'RELATED_TO_KEY_CONTROLS', 'related-to-key-controls')
),
catalog_groups AS (
  SELECT d.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS GROUP_HASH,
         d.OSCAL_UUID AS GROUP_UUID,
         d.SOURCE_RECORD_ID AS CATALOG_SOURCE_CONTENT_ID,
         d.ELEMENT_TYPE, d.METADATA_JSON,
         marker.VALUE:value::VARCHAR AS CHILD_ARCHER_CONTENT_ID
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT d,
       LATERAL FLATTEN(INPUT => d.METADATA_JSON:props) marker
  WHERE marker.VALUE:name::VARCHAR = 'archer-content-id'
    AND d.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
),
matched_groups AS (
  SELECT r.SOURCE_LEVEL, r.CONTENT_ID, r.PAYLOAD, f.ARCHER_FIELD,
         f.PROP_NAME, g.GROUP_HASH, g.GROUP_UUID,
         g.CATALOG_SOURCE_CONTENT_ID, g.ELEMENT_TYPE, g.METADATA_JSON,
         parent.ELEMENT_TYPE AS PARENT_ELEMENT_TYPE,
         parent.OSCAL_UUID AS PARENT_UUID
  FROM raw r
  JOIN field_matrix f ON f.LEVEL_NAME=r.SOURCE_LEVEL
  LEFT JOIN catalog_groups g ON g.CHILD_ARCHER_CONTENT_ID=r.CONTENT_ID
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY edge
    ON edge.FK_TARGET_ELEMENT_HASH=g.GROUP_HASH AND edge.DEPENDENCY_TYPE='CONTAINS'
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT parent
    ON parent.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH=edge.FK_SOURCE_ELEMENT_HASH
),
property_rows AS (
  SELECT m.*, p.VALUE:value::VARCHAR AS OSCAL_VALUE,
         p.VALUE:name::VARCHAR AS ACTUAL_PROP_NAME
  FROM matched_groups m,
       LATERAL FLATTEN(INPUT => m.METADATA_JSON:props, OUTER => TRUE) p
)
SELECT SOURCE_LEVEL, CONTENT_ID AS CHILD_ARCHER_CONTENT_ID,
       CATALOG_SOURCE_CONTENT_ID AS PARENT_SOURCE_CONTENT_ID,
       ARCHER_FIELD, GET(PAYLOAD,ARCHER_FIELD) AS ARCHER_VALUE,
       PROP_NAME AS EXPECTED_PROP_NAME, ACTUAL_PROP_NAME, OSCAL_VALUE,
       ELEMENT_TYPE AS OSCAL_GROUP_ELEMENT,
       PARENT_ELEMENT_TYPE AS FACT_PARENT_ELEMENT, PARENT_UUID AS FACT_PARENT_UUID,
       GROUP_UUID AS OSCAL_GROUP_UUID,
       TO_VARCHAR(GROUP_HASH,'HEX') AS GROUP_DIM_HASH,
       CASE
         WHEN GROUP_HASH IS NULL THEN 'NO_JOINED_GROUP_FOUND'
         WHEN ACTUAL_PROP_NAME = PROP_NAME THEN 'PROPERTY_FOUND_CHECK_VALUE_AND_MAPPING'
         ELSE 'NO_REQUESTED_PROPERTY_IN_THIS_GROUP'
       END AS QA_STATUS
FROM property_rows
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY SOURCE_LEVEL, CONTENT_ID, ARCHER_FIELD, GROUP_HASH
  ORDER BY IFF(ACTUAL_PROP_NAME=PROP_NAME,0,1)
) = 1
ORDER BY SOURCE_LEVEL, CONTENT_ID, ARCHER_FIELD
LIMIT 200;

-- ================================================================
-- 03 ASSESSMENT RESULTS + ASSESSMENT PLAN: MULTI-LEVEL FIELD AUDIT
-- ================================================================
-- Results and SAP use their OWN model DIM tables. The same Archer field name
-- at different source levels is NOT interchangeable: source table is mandatory.
-- This is exact per-record/property inspection, not a claim of field attribution
-- for an inline property with multiple possible field owners.
-- Add source/model/field/prop to the field_matrix as fields are approved.
WITH raw AS (
  SELECT 'SOURCE' AS LVL, 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW' AS RAW_TABLE,
         CONTENT_ID::VARCHAR AS CID,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON) AS P
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
  UNION ALL
  SELECT 'TOPIC', 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
  UNION ALL
  SELECT 'SECTION', 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW',CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
  UNION ALL
  SELECT 'SUB_SECTION', 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW',CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
field_matrix AS (
  SELECT COLUMN1 AS LVL, COLUMN2 AS MODEL, COLUMN3 AS ARCHER_FIELD,
         COLUMN4 AS EXPECTED_PROP
  FROM VALUES
    ('TOPIC','ASSESSMENT_RESULTS','COMPLIANCE_RATING','compliance-rating'),
    ('SECTION','ASSESSMENT_RESULTS','COMPLIANCE_RATING','compliance-rating'),
    ('SUB_SECTION','ASSESSMENT_RESULTS','COMPLIANCE_RATING','compliance-rating'),
    ('SOURCE','SECURITY_ASSESSMENT_PLAN',
       'COMPLIANCE_ENGAGEMENTS_SCOPE_PROCEDURES_FROM_SELECTED_AUTHORITATIVE_SOURCES',NULL),
    ('SECTION','SECURITY_ASSESSMENT_PLAN',
       'COMPLIANCE_ENGAGEMENTS_SCOPE_PROCEDURES_FROM_SELECTED_AUTHORITATIVE_SOURCES',NULL)
),
dim AS (
  SELECT 'ASSESSMENT_RESULTS' AS MODEL, SOURCE_TABLE_NAME AS RAW_TABLE,
         SOURCE_RECORD_ID AS CID, ELEMENT_TYPE, OSCAL_UUID, METADATA_JSON
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT
  UNION ALL
  SELECT 'SECURITY_ASSESSMENT_PLAN', SOURCE_TABLE_NAME,
         SOURCE_RECORD_ID, ELEMENT_TYPE, OSCAL_UUID, METADATA_JSON
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT
),
properties AS (
  SELECT d.MODEL,d.RAW_TABLE,d.CID,d.ELEMENT_TYPE,d.OSCAL_UUID,d.METADATA_JSON,
         COALESCE(d.METADATA_JSON:name::VARCHAR, p.VALUE:name::VARCHAR) AS PROP_NAME,
         COALESCE(d.METADATA_JSON:value::VARCHAR, p.VALUE:value::VARCHAR) AS PROP_VALUE
  FROM dim d, LATERAL FLATTEN(INPUT => d.METADATA_JSON:props, OUTER => TRUE) p
  WHERE d.ELEMENT_TYPE IN ('props','results','observations','findings','tasks')
)
SELECT r.LVL AS SOURCE_LEVEL, f.MODEL, r.RAW_TABLE AS ARCHER_TABLE,
       r.CID AS ARCHER_CONTENT_ID, f.ARCHER_FIELD,
       GET(r.P,f.ARCHER_FIELD) AS ARCHER_VALUE,
       f.EXPECTED_PROP, t.PROP_NAME AS ACTUAL_PROP, t.PROP_VALUE AS OSCAL_VALUE,
       t.ELEMENT_TYPE AS OSCAL_ELEMENT_TYPE, t.OSCAL_UUID,
       t.METADATA_JSON AS FULL_OSCAL_PAYLOAD,
       CASE WHEN t.OSCAL_UUID IS NULL THEN 'NO_TARGET_ELEMENT'
            WHEN f.EXPECTED_PROP IS NULL THEN 'TARGET_CANDIDATE_ONLY_PATH_NOT_VERIFIED'
            WHEN t.PROP_NAME=f.EXPECTED_PROP THEN 'PROPERTY_FOUND_CHECK_TRANSFORM_AND_LINEAGE'
            ELSE 'PROPERTY_NOT_SHOWN_ON_THIS_ELEMENT'
       END AS QA_STATUS
FROM raw r JOIN field_matrix f ON f.LVL=r.LVL
LEFT JOIN properties t
  ON t.MODEL=f.MODEL AND t.RAW_TABLE=r.RAW_TABLE AND t.CID=r.CID
 AND (f.EXPECTED_PROP IS NULL OR t.PROP_NAME=f.EXPECTED_PROP)
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY r.LVL, f.MODEL, f.ARCHER_FIELD
  ORDER BY IFF(t.PROP_NAME=f.EXPECTED_PROP,0,1), r.CID, t.ELEMENT_TYPE
) <= 15
ORDER BY r.LVL, f.MODEL, f.ARCHER_FIELD, r.CID
LIMIT 200;

-- ================================================================
-- 04 CONTROL STANDARD / PROCEDURES / MASTER CONTROL SOURCE OWNERS
-- ================================================================
-- Important: the older Oct 16 review had unresolved/deferred native Catalog
-- controls and related-reference mapping decisions. An unchanged target name
-- or nearby control payload cannot establish these field mappings.
-- This returns the exact Archer fields and source-level identity; it does NOT
-- falsely claim native controls/links were emitted or accepted in newer runs.
WITH raw AS (
  SELECT 'SOURCE' LVL, CONTENT_ID::VARCHAR CID,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON) P
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
  UNION ALL
  SELECT 'TOPIC', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
  UNION ALL
  SELECT 'SECTION', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
  UNION ALL
  SELECT 'SUB_SECTION', CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR',TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)),CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
fields AS (
  SELECT COLUMN1 LVL, COLUMN2 FIELD_NAME, COLUMN3 MAPPING_REVIEW_CONTEXT
  FROM VALUES
    ('SOURCE','CONTROL_STANDARDS','Catalog native controls: earlier owner deferred'),
    ('SOURCE','RELATED_CONTROL_PROCEDURES','Catalog control links: review pending'),
    ('SOURCE','MASTER_CONTROLS_AUTHORITATIVE_SOURCES','Catalog master links: review pending'),
    ('SOURCE','CONTROL_PROCEDURES','Catalog vs Component Definition ambiguous'),
    ('TOPIC','CONTROL_STANDARDS','Catalog native controls: earlier owner deferred'),
    ('TOPIC','RELATED_CONTROL_PROCEDURES','Catalog control links: review pending'),
    ('TOPIC','MASTER_CONTROLS_AUTHORITATIVE_SOURCES','Catalog master links: review pending'),
    ('SECTION','CONTROL_STANDARDS','Catalog native controls: earlier owner deferred'),
    ('SECTION','RELATED_CONTROL_PROCEDURES','Catalog control links: review pending'),
    ('SECTION','MASTER_CONTROLS_AUTHORITATIVE_SOURCES','Catalog master links: review pending'),
    ('SUB_SECTION','CONTROL_STANDARDS','Catalog native controls: earlier owner deferred'),
    ('SUB_SECTION','CONTROL_STANDARDS_ATCS_CONTROLS','Catalog ATCS control links: review pending'),
    ('SUB_SECTION','RELATED_CONTROL_PROCEDURES','Catalog control links: review pending'),
    ('SUB_SECTION','CONTROL_PROCEDURES_AUTHORITATIVE_SOURCES','Component Definition reference review')
)
SELECT r.LVL AS SOURCE_LEVEL, r.CID AS ARCHER_CONTENT_ID,
       f.FIELD_NAME AS ARCHER_FIELD,
       TYPEOF(GET(r.P,f.FIELD_NAME)) AS ARCHER_TYPE,
       GET(r.P,f.FIELD_NAME) AS ARCHER_PAYLOAD,
       f.MAPPING_REVIEW_CONTEXT,
       'SOURCE_ONLY_NOT_A_TARGET_FIELD_QA_PASS' AS QA_STATUS
FROM raw r JOIN fields f ON f.LVL=r.LVL
WHERE GET(r.P,f.FIELD_NAME) IS NOT NULL
  AND NOT COALESCE(IS_NULL_VALUE(GET(r.P,f.FIELD_NAME)), FALSE)
QUALIFY ROW_NUMBER() OVER (PARTITION BY r.LVL, f.FIELD_NAME ORDER BY r.CID) <= 8
ORDER BY r.LVL, f.FIELD_NAME, r.CID
LIMIT 200;

-- ================================================================
-- 05 LIVE REGISTRY / TARGET SHAPE CHECK (READ-ONLY)
-- ================================================================
-- Confirm active hierarchy and identity before applying query 01's hash proof.
SELECT OSCAL_MODEL_KEY, NODE_PATH, ELEMENT_TYPE,
       PARENT_NODE_PATH, INSTANCE_KEY_RULE, OPERATOR,
       IS_COLLECTION, IS_ACTIVE
FROM RTX_RAW_DEV.ES_ESC_GRC.OSCAL_ELEMENT_REGISTRY
WHERE UPPER(OSCAL_MODEL_KEY) IN
      ('COMPONENT_DEFINITION','CATALOG','ASSESSMENT_RESULTS','SECURITY_ASSESSMENT_PLAN')
  AND (NODE_PATH ILIKE '%props%' OR NODE_PATH ILIKE '%components%'
       OR NODE_PATH ILIKE '%groups%' OR NODE_PATH ILIKE '%tasks%')
ORDER BY OSCAL_MODEL_KEY, NODE_PATH;