-- 2026-10-29 | Source Two | READ-ONLY Archer reference-field inventory
-- Scope: all four Source Two authoritative-source levels. Not yet all Archer apps.
-- OBJECT reference inventory; numeric-only arrays require separate field metadata.
WITH roots AS (
 SELECT 'SOURCE' AS LVL, CONTENT_ID::VARCHAR AS CID, CURATED_JSON AS J
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
 UNION ALL
 SELECT 'TOPIC',CONTENT_ID::VARCHAR,CURATED_JSON
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
 UNION ALL
 SELECT 'SECTION',CONTENT_ID::VARCHAR,CURATED_JSON
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
 UNION ALL
 SELECT 'SUB_SECTION',CONTENT_ID::VARCHAR,CURATED_JSON
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
),
refs AS (
 SELECT r.LVL,r.CID,SPLIT_PART(SPLIT_PART(f.PATH,'[',1),'.',1) AS SOURCE_FIELD,
        f.VALUE:ContentId::VARCHAR AS CONTENT_ID,
        f.VALUE:LevelId::VARCHAR AS LEVEL_ID
 FROM roots r,LATERAL FLATTEN(INPUT=>r.J,RECURSIVE=>TRUE) f
 WHERE TYPEOF(f.VALUE)='OBJECT'
   AND f.VALUE:ContentId IS NOT NULL AND f.VALUE:LevelId IS NOT NULL
)
SELECT r.LVL,r.SOURCE_FIELD,r.LEVEL_ID,m.LEVEL_NAME,m.MODULE_NAME,
       COUNT(*) AS REF_OCCURRENCES,
       COUNT(DISTINCT r.CID) AS OWNERS,
       COUNT(DISTINCT r.CONTENT_ID) AS DISTINCT_REFERENCED_IDS
FROM refs r
LEFT JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_META_LEVEL m
 ON m.LEVEL_ID::VARCHAR=r.LEVEL_ID
GROUP BY 1,2,3,4,5
ORDER BY REF_OCCURRENCES DESC,LVL,SOURCE_FIELD;

-- Query 02: positive numeric array members, CANDIDATES ONLY.
-- These can be select-value IDs or other numbers, not necessarily ContentIds.
-- No automatic LevelId or target app assignment. Do not hydrate yet.
WITH roots AS (
 SELECT 'SOURCE' AS LVL, CONTENT_ID::VARCHAR AS CID,CURATED_JSON AS J
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
 UNION ALL
 SELECT 'TOPIC',CONTENT_ID::VARCHAR,CURATED_JSON
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
 UNION ALL
 SELECT 'SECTION',CONTENT_ID::VARCHAR,CURATED_JSON
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
 UNION ALL
 SELECT 'SUB_SECTION',CONTENT_ID::VARCHAR,CURATED_JSON
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
)
SELECT r.LVL, f.KEY::VARCHAR AS SOURCE_FIELD,
       TYPEOF(x.VALUE) AS MEMBER_TYPE,
       COUNT(*) AS CANDIDATE_OCCURRENCES,
       COUNT(DISTINCT r.CID) AS OWNER_RECORDS,
       COUNT(DISTINCT x.VALUE::VARCHAR) AS DISTINCT_NUMERIC_VALUES,
       'REQUIRES_ARCHER_FIELD_RELATIONSHIP_AND_TARGET_RAW_VERIFICATION'
          AS DISPOSITION
FROM roots r,LATERAL FLATTEN(INPUT=>r.J) f,
     LATERAL FLATTEN(INPUT=>f.VALUE) x
WHERE IS_ARRAY(f.VALUE)
  AND TYPEOF(x.VALUE) IN ('INTEGER','DECIMAL','VARCHAR')
  AND REGEXP_LIKE(x.VALUE::VARCHAR,'^[1-9][0-9]*$')
GROUP BY r.LVL, f.KEY::VARCHAR,TYPEOF(x.VALUE)
ORDER BY CANDIDATE_OCCURRENCES DESC,LVL,SOURCE_FIELD;
