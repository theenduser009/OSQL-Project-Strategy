-- Source Two QA 11: same property name, different Source/Topic fields.
-- Read-only Snowflake DEV; one SELECT, seven output columns.
-- A node is attributed ONLY by its full field-and-value-derived DIM hash.
-- Based on mapper v17 Source Two Component Definition registry:
-- component-definition.components[].props[], identity SOURCE_FIELD_NAME+VALUE.
-- Validate deployed registry/code before interpreting a hash miss as failure.
-- Source and Topic Component Definition were owner-reported COMMITTED_AND_VERIFIED on 2026-10-28.
-- Do not assume Section or Sub-Section Component Definition was committed.
WITH raw AS (
  SELECT 'SOURCE' AS LVL, 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW' AS RAW_TABLE,
         CONTENT_ID::VARCHAR AS CID,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR', TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)), CURATED_JSON) AS J
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
  UNION ALL
  SELECT 'TOPIC', 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW',
         CONTENT_ID::VARCHAR,
         IFF(TYPEOF(CURATED_JSON)='VARCHAR', TRY_PARSE_JSON(AS_VARCHAR(CURATED_JSON)), CURATED_JSON)
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
), fields AS (
  SELECT COLUMN1 AS LVL, COLUMN2 AS ARCHER_FIELD
  FROM VALUES
    ('SOURCE','POLICY_LEVEL_3'),
    ('SOURCE','POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS'),
    ('TOPIC','POLICY_LEVEL_3'),
    ('TOPIC','POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS')
)
SELECT
  r.RAW_TABLE AS ARCHER_TABLE_NAME,
  r.CID AS CONTENT_ID,
  f.ARCHER_FIELD AS ARCHER_FIELD_NAME,
  GET(r.J,f.ARCHER_FIELD) AS ARCHER_VALUE,
  d.METADATA_JSON:name::VARCHAR AS OSCAL_PROPERTY_NAME,
  d.ELEMENT_TYPE AS OSCAL_ELEMENT_TYPE,
  d.METADATA_JSON:value AS OSCAL_VALUE
FROM raw r
JOIN fields f ON f.LVL=r.LVL
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_COMPONENT_ELEMENT d
  ON d.SOURCE_TABLE_NAME=r.RAW_TABLE
 AND d.SOURCE_RECORD_ID=r.CID
 AND d.ELEMENT_TYPE='props'
 AND d.METADATA_JSON:name::VARCHAR='policy-level'
 AND d.PK_DIM_OSCAL_COMPONENT_ELEMENT_HASH=MD5_BINARY(
      'v1_registry_path_instance|ARCHER|' || r.RAW_TABLE || '|' || r.CID ||
      '|COMPONENT_DEFINITION|component-definition.components[].props[]|' ||
      f.ARCHER_FIELD || ':' ||
      MD5('source-field-value-v1|' || f.ARCHER_FIELD || '|' ||
          IFF(COALESCE(IS_NULL_VALUE(d.METADATA_JSON:value),FALSE),
              'None',d.METADATA_JSON:value::VARCHAR))
    )
QUALIFY ROW_NUMBER() OVER (PARTITION BY r.RAW_TABLE,f.ARCHER_FIELD ORDER BY r.CID) <= 8
ORDER BY ARCHER_TABLE_NAME,ARCHER_FIELD_NAME,CONTENT_ID;
