-- PREASSESSMENT_REVIEW_COMMENTS is a native task remarks member,
-- NOT a separate "remarks" DIM element or a task props name/value child.
-- Source One mapping: APPROVED, text, NULL_POLICY=preserve,
-- assessment-plan.tasks[].remarks (source-field lineage is separate).
-- Compare the exact original source text (without trimming) to persisted
-- task METADATA_JSON:"remarks" with root->task FACT ownership.
WITH source_data AS (
    SELECT
        s.CONTENT_ID::STRING AS ARCHER_CONTENT_ID,
        s.CURATED_JSON:"PREASSESSMENT_REVIEW_COMMENTS" AS SOURCE_VALUE,
        COUNT(*) OVER (PARTITION BY s.CONTENT_ID::STRING) AS SOURCE_SNAPSHOTS,
        CASE
            WHEN s.CURATED_JSON:"PREASSESSMENT_REVIEW_COMMENTS" IS NULL
                THEN 'SOURCE_KEY_ABSENT'
            WHEN IS_NULL_VALUE(s.CURATED_JSON:"PREASSESSMENT_REVIEW_COMMENTS")
                THEN 'EXPLICIT_JSON_NULL'
            WHEN TYPEOF(s.CURATED_JSON:"PREASSESSMENT_REVIEW_COMMENTS") = 'VARCHAR'
             AND LENGTH(TRIM(s.CURATED_JSON:"PREASSESSMENT_REVIEW_COMMENTS"::STRING)) = 0
                THEN 'SOURCE_EMPTY'
            WHEN TYPEOF(s.CURATED_JSON:"PREASSESSMENT_REVIEW_COMMENTS") <> 'VARCHAR'
                THEN 'SOURCE_UNSUPPORTED_SHAPE'
            ELSE 'SOURCE_POPULATED'
        END AS SOURCE_STATE,
        IFF(TYPEOF(s.CURATED_JSON:"PREASSESSMENT_REVIEW_COMMENTS") = 'VARCHAR',
            s.CURATED_JSON:"PREASSESSMENT_REVIEW_COMMENTS"::STRING, NULL)
            AS EXPECTED_COMMENTS
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW s
),
task_data AS (
    SELECT
        task.SOURCE_RECORD_ID AS ARCHER_CONTENT_ID,
        HEX_ENCODE(task.PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH) AS TASK_DIM_HASH,
        task.METADATA_JSON:"title"::STRING AS TASK_TITLE,
        GET(task.METADATA_JSON, 'remarks') AS TARGET_REMARKS,
        task.METADATA_JSON AS TASK_JSON
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT root
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_PLAN_DEPENDENCY link
      ON link.FK_SOURCE_ELEMENT_HASH = root.PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH
     AND link.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT task
      ON task.PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH = link.FK_TARGET_ELEMENT_HASH
    WHERE root.ELEMENT_TYPE = 'assessment-plan'
      AND task.ELEMENT_TYPE = 'tasks'
      AND root.SOURCE_SYSTEM_NAME = 'ARCHER'
      AND root.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND task.SOURCE_SYSTEM_NAME = root.SOURCE_SYSTEM_NAME
      AND task.SOURCE_TABLE_NAME = root.SOURCE_TABLE_NAME
      AND task.SOURCE_RECORD_ID = root.SOURCE_RECORD_ID
),
qa AS (
    SELECT
        src.*, t.TASK_DIM_HASH, t.TASK_TITLE, t.TARGET_REMARKS,
        COUNT(t.TASK_DIM_HASH) OVER (PARTITION BY src.ARCHER_CONTENT_ID) AS TASK_MATCHES,
        CASE
            WHEN src.SOURCE_SNAPSHOTS > 1 THEN 'SOURCE_SNAPSHOT_AMBIGUOUS'
            WHEN t.TASK_DIM_HASH IS NULL THEN 'TASK_MISSING_IN_TARGET'
            WHEN src.SOURCE_STATE = 'SOURCE_KEY_ABSENT'
                THEN IFF(t.TARGET_REMARKS IS NULL,
                         'SOURCE_KEY_ABSENT', 'UNEXPECTED_REMARKS_FOR_ABSENT_SOURCE')
            WHEN src.SOURCE_STATE = 'SOURCE_EMPTY'
                THEN 'SOURCE_EMPTY_REVIEW'
            WHEN src.SOURCE_STATE = 'SOURCE_UNSUPPORTED_SHAPE'
                THEN 'SOURCE_UNSUPPORTED_SHAPE'
            WHEN src.SOURCE_STATE = 'EXPLICIT_JSON_NULL'
             AND IS_NULL_VALUE(t.TARGET_REMARKS)
                THEN 'EXPLICIT_NULL_PRESERVED'
            WHEN src.SOURCE_STATE = 'EXPLICIT_JSON_NULL'
                THEN 'NULL_SOURCE_TARGET_MISMATCH'
            WHEN t.TARGET_REMARKS IS NULL OR IS_NULL_VALUE(t.TARGET_REMARKS)
                THEN 'POPULATED_SOURCE_TARGET_MISSING'
            WHEN t.TARGET_REMARKS::STRING = src.EXPECTED_COMMENTS
                THEN 'VALUE_MATCH'
            ELSE 'VALUE_MISMATCH'
        END AS QA_STATUS
    FROM source_data src
    LEFT JOIN task_data t ON t.ARCHER_CONTENT_ID = src.ARCHER_CONTENT_ID
)
SELECT
    ARCHER_CONTENT_ID, SOURCE_STATE, SOURCE_VALUE,
    EXPECTED_COMMENTS, TASK_TITLE, TARGET_REMARKS,
    TASK_DIM_HASH, TASK_MATCHES, QA_STATUS,
    COUNT(*) OVER (PARTITION BY QA_STATUS) AS QA_STATUS_ROWS_ALL
FROM qa
ORDER BY ARCHER_CONTENT_ID, QA_STATUS
LIMIT 100;
