-- ADJUSTED_AVERAGE_RISK_SCORE | Source One Assessment Results | READ ONLY | 2026-10-13
-- Archer name recovered from OSCAL property-name convention + approved CSV mapping.
-- This is mapped-field traceability, not a separately stored "source-field" prop.
SELECT
    d.SOURCE_RECORD_ID AS ARCHER_CONTENT_ID,
    UPPER(REPLACE(d.METADATA_JSON:props[0]:name::STRING, '-', '_')) AS ARCHER_FIELD_NAME,
    GET(a.CURATED_JSON, UPPER(REPLACE(d.METADATA_JSON:props[0]:name::STRING, '-', '_'))) AS ARCHER_PAYLOAD,
    d.METADATA_JSON:props[0]:value AS OSCAL_VALUE,
    d.ELEMENT_TYPE AS OSCAL_ELEMENT_TYPE,
    d.METADATA_JSON AS OSCAL_PAYLOAD
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT d
LEFT JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
    ON a.CONTENT_ID::STRING = d.SOURCE_RECORD_ID
WHERE d.SOURCE_SYSTEM_NAME = 'ARCHER'
  AND d.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
  AND d.ELEMENT_TYPE = 'observations'
  AND d.METADATA_JSON:props[0]:name::STRING = 'adjusted-average-risk-score'
ORDER BY d.SOURCE_RECORD_ID
LIMIT 20;
