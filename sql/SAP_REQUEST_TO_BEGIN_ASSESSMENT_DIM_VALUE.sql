-- Locate the exact persisted Assessment Plan DIM property for
-- Archer REQUEST_TO_BEGIN_ASSESSMENT (resolved select label).
-- Property: assessment-plan.tasks[].props[].name = request-to-begin-assessment
SELECT
    SOURCE_RECORD_ID AS ARCHER_CONTENT_ID,
    HEX_ENCODE(PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH) AS DIM_ELEMENT_HASH,
    ELEMENT_TYPE,
    METADATA_JSON:"name"::STRING AS ARCHER_FIELD_PROPERTY,
    METADATA_JSON:"value"::STRING AS RESOLVED_VALUE,
    METADATA_JSON AS FULL_OSCAL_JSON
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT
WHERE ELEMENT_TYPE = 'props'
  AND SOURCE_SYSTEM_NAME = 'ARCHER'
  AND SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
  AND METADATA_JSON:"name"::STRING = 'request-to-begin-assessment'
ORDER BY SOURCE_RECORD_ID
LIMIT 100;
