-- SSP CIA Archer source-to-target lineage | READ ONLY | DEV
-- Shows all eleven approved fields, including JSON nulls.
-- SOURCE_FILE_NAME is optional; no filename is inferred where absent.
WITH mapped_fields (ARCHER_FIELD, OSCAL_MEMBER) AS (
 SELECT column1,column2 FROM VALUES
 ('RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY','security-objective-confidentiality'),
 ('CONFIDENTIALITY_CONTROL_CATEGORY_OVERRIDE','security-objective-confidentiality'),
 ('CNSS_CONFIDENTIALITY_RATING','security-objective-confidentiality'),
 ('RECOMMENDED_INTEGRITY_CONTROL_CATEGORY','security-objective-integrity'),
 ('INTEGRITY_CONTROL_CATEGORY_OVERRIDE','security-objective-integrity'),
 ('PROGRAMSITE_INTEGRITY_CONTROL_CATEGORY','security-objective-integrity'),
 ('CNSS_INTEGRITY_RATING','security-objective-integrity'),
 ('RECOMMENDED_AVAILABILITY_CONTROL_CATEGORY','security-objective-availability'),
 ('AVAILABILITY_CONTROL_CATEGORY_OVERRIDE','security-objective-availability'),
 ('PROGRAMSITE_AVAILABILITY_CONTROL_CATEGORY','security-objective-availability'),
 ('CNSS_AVAILABILITY_RATING','security-objective-availability')
),
archer AS (
 SELECT a.CONTENT_ID::STRING AS CONTENT_ID, a.CURATED_JSON,
  COALESCE(
   GET_IGNORE_CASE(OBJECT_CONSTRUCT_KEEP_NULL(a.*),'SOURCE_FILE_NAME')::STRING,
   GET_IGNORE_CASE(OBJECT_CONSTRUCT_KEEP_NULL(a.*),'FILE_NAME')::STRING
  ) AS SOURCE_FILE_NAME
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
),
oscal AS (
 SELECT SOURCE_RECORD_ID, METADATA_JSON
 FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
 WHERE ELEMENT_TYPE='security-impact-level'
),
lineage AS (
 SELECT SOURCE_RECORD_ID, METADATA_JSON:"value"::STRING AS SOURCE_FIELD
 FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
 WHERE ELEMENT_TYPE='props'
   AND METADATA_JSON:"name"::STRING='source-field'
)
SELECT
 a.CONTENT_ID AS ARCHER_CONTENT_ID,
 a.SOURCE_FILE_NAME AS ARCHER_ARCHIVE_FILE_NAME,
 f.ARCHER_FIELD,
 GET(a.CURATED_JSON,f.ARCHER_FIELD) AS ARCHER_FIELD_PAYLOAD,
 GET(a.CURATED_JSON,f.ARCHER_FIELD):ValuesListIds AS ARCHER_VALUE_IDS,
 GET(a.CURATED_JSON,f.ARCHER_FIELD):ResolvedValues AS ARCHER_RESOLVED_VALUES,
 'system-security-plan.system-characteristics.security-impact-level.' ||
    f.OSCAL_MEMBER AS OSCAL_PATH,
 GET(o.METADATA_JSON,f.OSCAL_MEMBER)::STRING AS OSCAL_VALUE,
 o.METADATA_JSON AS OSCAL_PAYLOAD,
 l.SOURCE_FIELD AS SOURCE_FIELD_LINEAGE
FROM archer a CROSS JOIN mapped_fields f
LEFT JOIN oscal o ON o.SOURCE_RECORD_ID=a.CONTENT_ID
LEFT JOIN lineage l ON l.SOURCE_RECORD_ID=a.CONTENT_ID
 AND l.SOURCE_FIELD=f.ARCHER_FIELD
ORDER BY a.CONTENT_ID,f.ARCHER_FIELD;
