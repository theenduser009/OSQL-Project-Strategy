-- FINDINGS | Assessment Results | READ ONLY | 2026-10-13
-- FINDINGS is stored as a result-level prop, not a native findings[] object.
SELECT
    d.SOURCE_RECORD_ID AS ARCHER_CONTENT_ID,
    UPPER(REPLACE(d.METADATA_JSON:name::STRING, '-', '_')) AS ARCHER_FIELD_NAME,
    GET(a.CURATED_JSON, UPPER(REPLACE(d.METADATA_JSON:name::STRING, '-', '_'))) AS ARCHER_PAYLOAD,
    TYPEOF(GET(a.CURATED_JSON, 'FINDINGS')) AS ARCHER_VALUE_TYPE,
    d.METADATA_JSON:value AS OSCAL_VALUE,
    d.ELEMENT_TYPE AS OSCAL_ELEMENT_TYPE,
    d.METADATA_JSON AS OSCAL_PAYLOAD
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT d
LEFT JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
    ON a.CONTENT_ID::STRING = d.SOURCE_RECORD_ID
WHERE d.SOURCE_SYSTEM_NAME = 'ARCHER'
  AND d.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
  AND d.ELEMENT_TYPE = 'props'
  AND d.METADATA_JSON:name::STRING = 'findings'
ORDER BY d.SOURCE_RECORD_ID
LIMIT 20;
