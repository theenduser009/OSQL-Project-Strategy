-- FINDINGS: Assessment Results DIM-only field lookup; no RAW join.
-- Stored as result-level props; current mapped source values may be JSON null.
SELECT
    SOURCE_RECORD_ID AS ARCHER_CONTENT_ID,
    UPPER(REPLACE(METADATA_JSON:name::STRING, '-', '_')) AS ARCHER_FIELD_NAME,
    METADATA_JSON:value AS OSCAL_VALUE,
    TYPEOF(METADATA_JSON:value) AS OSCAL_VALUE_TYPE,
    ELEMENT_TYPE,
    METADATA_JSON AS OSCAL_PAYLOAD
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT
WHERE SOURCE_SYSTEM_NAME = 'ARCHER'
  AND SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
  AND ELEMENT_TYPE = 'props'
  AND METADATA_JSON:name::STRING = 'findings'
LIMIT 20;
