-- PATCH_SCORE: Assessment Results DIM-only field lookup; no RAW join.
SELECT
    SOURCE_RECORD_ID AS ARCHER_CONTENT_ID,
    UPPER(REPLACE(METADATA_JSON:props[0]:name::STRING, '-', '_')) AS ARCHER_FIELD_NAME,
    METADATA_JSON:props[0]:value AS OSCAL_VALUE,
    ELEMENT_TYPE,
    METADATA_JSON AS OSCAL_PAYLOAD
FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT
WHERE SOURCE_SYSTEM_NAME = 'ARCHER'
  AND SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
  AND ELEMENT_TYPE = 'observations'
  AND METADATA_JSON:props[0]:name::STRING = 'patch-score'
LIMIT 20;
