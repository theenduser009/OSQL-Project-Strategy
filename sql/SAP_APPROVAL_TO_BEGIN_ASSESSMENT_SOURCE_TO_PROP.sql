-- Archer APPROVAL_TO_BEGIN_ASSESSMENT -> assessment-plan.tasks[].props[]
-- APPROVED, archer-select, NULL_POLICY=preserve.
-- Compares source's single resolved label to a persisted task child prop.
-- The two FACT CONTAINS joins enforce assessment-plan -> task -> prop.
-- Source duplicates are reported as ambiguous, not silently resolved.
WITH source_data AS (
    SELECT
        s.CONTENT_ID::STRING AS ARCHER_CONTENT_ID,
        s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT" AS SOURCE_VALUE,
        COUNT(*) OVER (PARTITION BY s.CONTENT_ID::STRING) AS SOURCE_SNAPSHOTS,
        CASE
            WHEN s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT" IS NULL
                THEN 'SOURCE_KEY_ABSENT'
            WHEN IS_NULL_VALUE(s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT")
                THEN 'EXPLICIT_JSON_NULL'
            WHEN IS_ARRAY(s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ResolvedValues")
             AND ARRAY_SIZE(s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ResolvedValues") = 0
                THEN 'SOURCE_EMPTY'
            ELSE 'SOURCE_PRESENT'
        END AS SOURCE_STATE,
        CASE
            WHEN IS_ARRAY(s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ResolvedValues")
             AND ARRAY_SIZE(s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ResolvedValues") = 1
             AND IS_ARRAY(s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ValuesListIds")
             AND ARRAY_SIZE(s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ValuesListIds") = 1
             AND s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ResolvedValues"[0]:"LookupStatus"::STRING = 'MATCHED'
             AND s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ResolvedValues"[0]:"ValueId"::STRING
                 = s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ValuesListIds"[0]::STRING
                THEN s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT":"ResolvedValues"[0]:"ValueName"::STRING
            WHEN TYPEOF(s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT")
                 IN ('VARCHAR','INTEGER','DECIMAL','DOUBLE','BOOLEAN')
                THEN s.CURATED_JSON:"APPROVAL_TO_BEGIN_ASSESSMENT"::STRING
            ELSE NULL
        END AS EXPECTED_RESOLVED_VALUE
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW s
),
task_props AS (
    SELECT
        prop.SOURCE_RECORD_ID AS ARCHER_CONTENT_ID,
        task.METADATA_JSON:"title"::STRING AS TASK_TITLE,
        prop.METADATA_JSON:"name"::STRING AS PROPERTY_NAME,
        prop.METADATA_JSON:"value" AS TARGET_VALUE,
        HEX_ENCODE(prop.PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH) AS PROPERTY_DIM_HASH,
        COUNT(*) OVER (PARTITION BY prop.SOURCE_RECORD_ID) AS TARGET_PROPERTY_COUNT
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT root
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_PLAN_DEPENDENCY task_link
      ON task_link.FK_SOURCE_ELEMENT_HASH = root.PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH
     AND task_link.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT task
      ON task.PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH = task_link.FK_TARGET_ELEMENT_HASH
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_PLAN_DEPENDENCY prop_link
      ON prop_link.FK_SOURCE_ELEMENT_HASH = task.PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH
     AND prop_link.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT prop
      ON prop.PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH = prop_link.FK_TARGET_ELEMENT_HASH
    WHERE root.ELEMENT_TYPE = 'assessment-plan'
      AND task.ELEMENT_TYPE = 'tasks'
      AND prop.ELEMENT_TYPE = 'props'
      AND root.SOURCE_SYSTEM_NAME = 'ARCHER'
      AND root.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND task.SOURCE_SYSTEM_NAME = root.SOURCE_SYSTEM_NAME
      AND prop.SOURCE_SYSTEM_NAME = root.SOURCE_SYSTEM_NAME
      AND task.SOURCE_TABLE_NAME = root.SOURCE_TABLE_NAME
      AND prop.SOURCE_TABLE_NAME = root.SOURCE_TABLE_NAME
      AND task.SOURCE_RECORD_ID = root.SOURCE_RECORD_ID
      AND prop.SOURCE_RECORD_ID = root.SOURCE_RECORD_ID
      AND prop.METADATA_JSON:"name"::STRING = 'approval-to-begin-assessment'
),
qa AS (
    SELECT
        src.*, target.TASK_TITLE, target.PROPERTY_NAME,
        target.TARGET_VALUE, target.PROPERTY_DIM_HASH,
        target.TARGET_PROPERTY_COUNT,
        CASE
            WHEN src.SOURCE_SNAPSHOTS > 1 THEN 'SOURCE_SNAPSHOT_AMBIGUOUS'
            WHEN src.SOURCE_STATE = 'SOURCE_KEY_ABSENT'
                THEN IFF(target.PROPERTY_DIM_HASH IS NULL,
                         'SOURCE_KEY_ABSENT', 'UNEXPECTED_TARGET_FOR_ABSENT_SOURCE')
            WHEN src.SOURCE_STATE = 'SOURCE_EMPTY' THEN 'SOURCE_EMPTY_REVIEW'
            WHEN src.SOURCE_STATE = 'EXPLICIT_JSON_NULL'
             AND target.PROPERTY_DIM_HASH IS NOT NULL
             AND IS_NULL_VALUE(target.TARGET_VALUE) THEN 'EXPLICIT_NULL_PRESERVED'
            WHEN src.SOURCE_STATE = 'EXPLICIT_JSON_NULL'
             AND target.PROPERTY_DIM_HASH IS NULL THEN 'NULL_SOURCE_TARGET_MISSING'
            WHEN target.PROPERTY_DIM_HASH IS NULL THEN 'POPULATED_SOURCE_TARGET_MISSING'
            WHEN target.TARGET_PROPERTY_COUNT > 1
                THEN 'DUPLICATE_TARGET_PROPERTY'
            WHEN src.EXPECTED_RESOLVED_VALUE IS NULL
                THEN 'SOURCE_MULTI_OR_UNRESOLVED_REVIEW'
            WHEN target.TARGET_VALUE IS NULL OR IS_NULL_VALUE(target.TARGET_VALUE)
                THEN 'TARGET_NULL_OR_MISSING_VALUE'
            WHEN target.TARGET_VALUE::STRING = src.EXPECTED_RESOLVED_VALUE
                THEN 'VALUE_MATCH'
            ELSE 'VALUE_MISMATCH'
        END AS QA_STATUS
    FROM source_data src
    LEFT JOIN task_props target
      ON target.ARCHER_CONTENT_ID = src.ARCHER_CONTENT_ID
)
SELECT ARCHER_CONTENT_ID, SOURCE_STATE, SOURCE_VALUE,
       EXPECTED_RESOLVED_VALUE, TASK_TITLE, PROPERTY_NAME,
       TARGET_VALUE, PROPERTY_DIM_HASH, TARGET_PROPERTY_COUNT, QA_STATUS,
       COUNT(*) OVER (PARTITION BY QA_STATUS) AS QA_STATUS_ROWS_ALL
FROM qa
ORDER BY ARCHER_CONTENT_ID, QA_STATUS
LIMIT 100;
