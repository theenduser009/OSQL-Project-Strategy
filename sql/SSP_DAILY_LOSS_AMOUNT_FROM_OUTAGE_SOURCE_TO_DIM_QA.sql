-- OSCAL Source One field QA: DAILY_LOSS_AMOUNT_FROM_OUTAGE
-- 2026-10-23 | Read-only Snowflake DEV SELECT | No DML, no notebook variables
-- Mapping: APPROVED / direct / system-security-plan.system-characteristics.props[]
-- NULL_POLICY=preserve; exact property name = daily-loss-amount-from-outage.
-- Source table, DIM, FACT names verified from current GitHub code.
-- The query checks a stored props DIM child connected to its
-- system-characteristics parent through FACT CONTAINS.
-- No new PREVIEW, COMMIT or live acceptance is implied.
-- RAW may have multiple snapshots per CONTENT_ID; this does not replay the
-- notebook's latest-record selection. Single-label/scalar value checks only;
-- complex and multiselection inputs are classified as REVIEW, never PASS.
WITH source_data AS (
    SELECT
        s.CONTENT_ID::STRING AS CONTENT_ID,
        s.CURATED_JSON:"DAILY_LOSS_AMOUNT_FROM_OUTAGE" AS SOURCE_VALUE,
        CASE
          WHEN s.CURATED_JSON:"DAILY_LOSS_AMOUNT_FROM_OUTAGE" IS NULL THEN 'SOURCE_KEY_ABSENT'
          WHEN IS_NULL_VALUE(s.CURATED_JSON:"DAILY_LOSS_AMOUNT_FROM_OUTAGE") THEN 'EXPLICIT_JSON_NULL'
          WHEN TYPEOF(s.CURATED_JSON:"DAILY_LOSS_AMOUNT_FROM_OUTAGE") = 'VARCHAR'
               AND LENGTH(TRIM(s.CURATED_JSON:"DAILY_LOSS_AMOUNT_FROM_OUTAGE"::STRING)) = 0
               THEN 'SOURCE_EMPTY'
          WHEN IS_ARRAY(s.CURATED_JSON:"DAILY_LOSS_AMOUNT_FROM_OUTAGE")
               AND ARRAY_SIZE(s.CURATED_JSON:"DAILY_LOSS_AMOUNT_FROM_OUTAGE") = 0
               THEN 'SOURCE_EMPTY'
          ELSE 'SOURCE_PRESENT'
        END AS SOURCE_STATE,
        CASE
          WHEN TYPEOF(s.CURATED_JSON:"DAILY_LOSS_AMOUNT_FROM_OUTAGE") IN
               ('VARCHAR','INTEGER','DECIMAL','DOUBLE','BOOLEAN')
          THEN s.CURATED_JSON:"DAILY_LOSS_AMOUNT_FROM_OUTAGE"::STRING
          ELSE NULL
        END AS EXPECTED_VALUE
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW s
),
target_data AS (
    SELECT
        child.SOURCE_RECORD_ID AS CONTENT_ID,
        child.PK_OSCAL_SSP_ELEMENT_HASH AS PROPERTY_HASH,
        child.METADATA_JSON:"name"::STRING AS PROPERTY_NAME,
        child.METADATA_JSON:"value" AS STORED_VALUE,
        child.METADATA_JSON AS FULL_OSCAL_JSON
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT parent
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY link
      ON link.FK_SOURCE_ELEMENT_HASH = parent.PK_OSCAL_SSP_ELEMENT_HASH
     AND link.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT child
      ON child.PK_OSCAL_SSP_ELEMENT_HASH = link.FK_TARGET_ELEMENT_HASH
    WHERE parent.ELEMENT_TYPE = 'system-characteristics'
      AND child.ELEMENT_TYPE = 'props'
      AND parent.SOURCE_SYSTEM_NAME = 'ARCHER'
      AND parent.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND child.SOURCE_SYSTEM_NAME = parent.SOURCE_SYSTEM_NAME
      AND child.SOURCE_TABLE_NAME = parent.SOURCE_TABLE_NAME
      AND child.SOURCE_RECORD_ID = parent.SOURCE_RECORD_ID
      AND child.METADATA_JSON:"name"::STRING = 'daily-loss-amount-from-outage'
),
qa AS (
    SELECT
        s.*, t.PROPERTY_HASH, t.PROPERTY_NAME, t.STORED_VALUE,
        t.FULL_OSCAL_JSON,
        CASE
          WHEN s.SOURCE_STATE = 'SOURCE_KEY_ABSENT'
            THEN IFF(t.PROPERTY_HASH IS NULL,
                     'SOURCE_KEY_ABSENT', 'UNEXPECTED_TARGET_FOR_ABSENT_SOURCE')
          WHEN s.SOURCE_STATE = 'SOURCE_EMPTY'
            THEN IFF(t.PROPERTY_HASH IS NULL,
                     'SOURCE_EMPTY', 'TARGET_PRESENT_SOURCE_EMPTY_REVIEW')
          WHEN s.SOURCE_STATE = 'EXPLICIT_JSON_NULL' THEN
            CASE
              WHEN t.PROPERTY_HASH IS NULL
                THEN 'NULL_SOURCE_TARGET_MISSING'
              WHEN IS_NULL_VALUE(t.STORED_VALUE)
                THEN 'EXPLICIT_NULL_PRESERVED'
              ELSE 'SOURCE_NULL_TARGET_NOT_NULL'
            END
          WHEN t.PROPERTY_HASH IS NULL
            THEN 'POPULATED_SOURCE_TARGET_MISSING'
          WHEN t.STORED_VALUE IS NULL OR IS_NULL_VALUE(t.STORED_VALUE)
            THEN 'TARGET_VALUE_MISSING_OR_NULL'
          WHEN s.EXPECTED_VALUE IS NOT NULL AND (
                 t.STORED_VALUE::STRING = s.EXPECTED_VALUE
                 OR (
                   TRY_TO_DECIMAL(t.STORED_VALUE::STRING, 38, 12) IS NOT NULL
                   AND TRY_TO_DECIMAL(s.EXPECTED_VALUE, 38, 12) IS NOT NULL
                   AND TRY_TO_DECIMAL(t.STORED_VALUE::STRING, 38, 12) =
                       TRY_TO_DECIMAL(s.EXPECTED_VALUE, 38, 12)
                 )
              )
            THEN 'VALUE_MATCH'
          WHEN s.EXPECTED_VALUE IS NOT NULL
            THEN 'VALUE_MISMATCH'
          ELSE 'TARGET_PRESENT_REVIEW_SOURCE_SHAPE'
        END AS QA_STATUS
    FROM source_data s
    LEFT JOIN target_data t ON t.CONTENT_ID = s.CONTENT_ID
)
SELECT
    CONTENT_ID AS ARCHER_CONTENT_ID,
    SOURCE_STATE,
    SOURCE_VALUE,
    EXPECTED_VALUE,
    PROPERTY_NAME AS OSCAL_PROPERTY_NAME,
    STORED_VALUE AS RESOLVED_OR_STORED_VALUE,
    HEX_ENCODE(PROPERTY_HASH) AS DIM_ELEMENT_HASH,
    FULL_OSCAL_JSON,
    QA_STATUS,
    COUNT(*) OVER (PARTITION BY QA_STATUS) AS STATUS_ROWS_ALL,
    COUNT(*) OVER () AS QA_ROWS_ALL
FROM qa
ORDER BY ARCHER_CONTENT_ID, QA_STATUS
LIMIT 100;
