-- READ ONLY: all visible Archer *_RAW structured-reference audit.
-- DEV namespace is explicit. No data/metadata writes, temp tables or procedures.
-- Run this ENTIRE block once in a Snowflake SQL worksheet.
-- SUMMARY is the default. Change v_report_mode to DETAIL for occurrence-level IDs/paths.
-- Raw data values/business payloads are not returned. Keep results private.
-- Reads all matching visible RAW tables; compare the inventory with your 44-table loader.
-- No Snowflake compilation or execution has been performed by the assistant.
EXECUTE IMMEDIATE $$
DECLARE
  v_union VARCHAR DEFAULT '';
  v_sql VARCHAR;
  v_piece VARCHAR;
  v_label VARCHAR;
  v_table_fqn VARCHAR;
  v_table_count INTEGER DEFAULT 0;
  v_report_mode VARCHAR DEFAULT 'SUMMARY';
  v_result RESULTSET;
  c_tables CURSOR FOR
    SELECT TABLE_CATALOG,TABLE_SCHEMA,TABLE_NAME,
           MAX(IFF(UPPER(COLUMN_NAME)='CONTENT_ID',COLUMN_NAME,NULL)) AS CID_COLUMN,
           MAX(IFF(UPPER(COLUMN_NAME)='RAW_DATA',COLUMN_NAME,NULL)) AS RAW_COLUMN,
           MAX(IFF(UPPER(COLUMN_NAME)='CURATED_JSON',COLUMN_NAME,NULL)) AS JSON_COLUMN
    FROM RTX_RAW_DEV.INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA='ES_ESC_GRC'
      AND STARTSWITH(UPPER(TABLE_NAME),'ARCHER_CONTENT_')
      AND ENDSWITH(UPPER(TABLE_NAME),'_RAW')
    GROUP BY TABLE_CATALOG,TABLE_SCHEMA,TABLE_NAME
    HAVING SUM(IFF(UPPER(COLUMN_NAME)='CONTENT_ID',1,0))=1
       AND SUM(IFF(UPPER(COLUMN_NAME)='RAW_DATA',1,0))=1
       AND SUM(IFF(UPPER(COLUMN_NAME)='CURATED_JSON',1,0))=1
    ORDER BY TABLE_NAME;
BEGIN
  FOR r IN c_tables DO
    v_label := r.TABLE_CATALOG||'.'||r.TABLE_SCHEMA||'.'||r.TABLE_NAME;
    v_table_fqn := '"'||REPLACE(r.TABLE_CATALOG,'"','""')||'"."'||
                         REPLACE(r.TABLE_SCHEMA,'"','""')||'"."'||
                         REPLACE(r.TABLE_NAME,'"','""')||'"';
    v_piece := 'SELECT '||CHR(39)||REPLACE(v_label,CHR(39),CHR(39)||CHR(39))||
      CHR(39)||' AS SOURCE_TABLE, "'||REPLACE(r.CID_COLUMN,'"','""')||
      '"::VARCHAR AS STORED_CONTENT_ID, "'||REPLACE(r.RAW_COLUMN,'"','""')||
      '"::VARIANT AS RAW_DATA, "'||REPLACE(r.JSON_COLUMN,'"','""')||
      '"::VARIANT AS CURATED_JSON FROM '||v_table_fqn;
    IF (v_table_count>0) THEN
      v_union := v_union||' UNION ALL ';
    END IF;
    v_union := v_union||v_piece;
    v_table_count := v_table_count+1;
  END FOR;
  IF (v_table_count=0) THEN
    v_result := (SELECT 'NO_VISIBLE_RAW_TABLES_WITH_UNIQUE_REQUIRED_COLUMNS' AS AUDIT_STATUS);
    RETURN TABLE(v_result);
  END IF;
  v_sql := 'WITH inventory_counts AS (
SELECT TABLE_CATALOG,TABLE_SCHEMA,TABLE_NAME,
       SUM(IFF(UPPER(COLUMN_NAME)=''RAW_DATA'',1,0)) AS RAW_DATA_COLUMNS,
       SUM(IFF(UPPER(COLUMN_NAME)=''CONTENT_ID'',1,0)) AS CONTENT_ID_COLUMNS,
       SUM(IFF(UPPER(COLUMN_NAME)=''CURATED_JSON'',1,0)) AS CURATED_JSON_COLUMNS
FROM RTX_RAW_DEV.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA=''ES_ESC_GRC''
  AND STARTSWITH(UPPER(TABLE_NAME),''ARCHER_CONTENT_'')
  AND ENDSWITH(UPPER(TABLE_NAME),''_RAW'')
GROUP BY TABLE_CATALOG,TABLE_SCHEMA,TABLE_NAME
), inventory AS (
 SELECT TABLE_CATALOG||''.''||TABLE_SCHEMA||''.''||TABLE_NAME AS SOURCE_TABLE,
        RAW_DATA_COLUMNS,CONTENT_ID_COLUMNS,CURATED_JSON_COLUMNS,
        (RAW_DATA_COLUMNS=1 AND CONTENT_ID_COLUMNS=1 AND CURATED_JSON_COLUMNS=1) AS ELIGIBLE
 FROM inventory_counts
), all_raw AS (
'||v_union||'
), normalized AS (
 SELECT SOURCE_TABLE,STORED_CONTENT_ID,
        IFF(TYPEOF(RAW_DATA)=''VARCHAR'',TRY_PARSE_JSON(RAW_DATA::VARCHAR),RAW_DATA) AS R,
        IFF(TYPEOF(CURATED_JSON)=''VARCHAR'',TRY_PARSE_JSON(CURATED_JSON::VARCHAR),CURATED_JSON) AS J
 FROM all_raw
), source_rows AS (
 SELECT *,ROW_NUMBER() OVER (
   PARTITION BY SOURCE_TABLE
   ORDER BY STORED_CONTENT_ID,TO_JSON(R),TO_JSON(J)
 ) AS SOURCE_ROW_NO
 FROM normalized
), raw_envelopes AS (
 SELECT s.SOURCE_TABLE,s.SOURCE_ROW_NO,
        f.INDEX AS RAW_ENVELOPE_INDEX,
        f.VALUE:RequestedObject:Id::VARCHAR AS RAW_ARCHER_CONTENT_ID,
        f.VALUE:RequestedObject:LevelId::VARCHAR AS RAW_ARCHER_LEVEL_ID
 FROM source_rows s,LATERAL FLATTEN(INPUT=>
   CASE WHEN TYPEOF(s.R)=''ARRAY'' THEN s.R
        WHEN TYPEOF(s.R)=''OBJECT'' THEN ARRAY_CONSTRUCT(s.R)
        ELSE ARRAY_CONSTRUCT() END) f
), envelope_stats AS (
 SELECT SOURCE_TABLE,SOURCE_ROW_NO,COUNT(*) AS RAW_ENVELOPE_ROWS,
        SUM(IFF(
          REGEXP_LIKE(COALESCE(RAW_ARCHER_CONTENT_ID,''''),''^[1-9][0-9]*$'')
          AND REGEXP_LIKE(COALESCE(RAW_ARCHER_LEVEL_ID,''''),''^[1-9][0-9]*$''),1,0
        )) AS VALID_ENVELOPE_ROWS,
        MIN(RAW_ARCHER_CONTENT_ID) AS OWNER_ARCHER_CONTENT_ID,
        MIN(RAW_ARCHER_LEVEL_ID) AS OWNER_ARCHER_LEVEL_ID
 FROM raw_envelopes GROUP BY SOURCE_TABLE,SOURCE_ROW_NO
), source_with_identity AS (
 SELECT s.*,COALESCE(e.RAW_ENVELOPE_ROWS,0) AS RAW_ENVELOPE_ROWS,
        COALESCE(e.VALID_ENVELOPE_ROWS,0) AS VALID_ENVELOPE_ROWS,
        e.OWNER_ARCHER_CONTENT_ID,e.OWNER_ARCHER_LEVEL_ID,
        (COALESCE(e.RAW_ENVELOPE_ROWS,0)=1
         AND COALESCE(e.VALID_ENVELOPE_ROWS,0)=1) AS OWNER_IDENTITY_VERIFIED
 FROM source_rows s LEFT JOIN envelope_stats e
   ON e.SOURCE_TABLE=s.SOURCE_TABLE AND e.SOURCE_ROW_NO=s.SOURCE_ROW_NO
), owners AS (
 SELECT s.*,SUM(IFF(OWNER_IDENTITY_VERIFIED,1,0)) OVER (
    PARTITION BY SOURCE_TABLE,OWNER_ARCHER_LEVEL_ID,OWNER_ARCHER_CONTENT_ID
 ) AS OWNER_PAIR_ROWS
 FROM source_with_identity s
), candidate_target_ids AS (
 -- DISTINCT prevents duplicate envelopes in one SQL row from inventing extra
 -- physical target rows. Multi-envelope curated ownership is still UNVERIFIED.
 SELECT DISTINCT SOURCE_TABLE,SOURCE_ROW_NO,
        RAW_ARCHER_LEVEL_ID AS REF_LEVEL_ID,
        RAW_ARCHER_CONTENT_ID AS REF_CONTENT_ID
 FROM raw_envelopes
 WHERE REGEXP_LIKE(COALESCE(RAW_ARCHER_CONTENT_ID,''''),''^[1-9][0-9]*$'')
   AND REGEXP_LIKE(COALESCE(RAW_ARCHER_LEVEL_ID,''''),''^[1-9][0-9]*$'')
), targets AS (
 SELECT c.REF_LEVEL_ID,c.REF_CONTENT_ID,COUNT(*) AS TARGET_PHYSICAL_ROWS,
        COUNT(DISTINCT c.SOURCE_TABLE) AS TARGET_TABLES,
        MIN(c.SOURCE_TABLE) AS TARGET_RAW_TABLE,
        SUM(IFF(s.OWNER_IDENTITY_VERIFIED,1,0)) AS TARGET_VERIFIED_IDENTITY_ROWS,
        SUM(IFF(TYPEOF(s.J)=''OBJECT'',1,0)) AS TARGET_OBJECT_JSON_ROWS
 FROM candidate_target_ids c JOIN owners s
   ON s.SOURCE_TABLE=c.SOURCE_TABLE AND s.SOURCE_ROW_NO=c.SOURCE_ROW_NO
 GROUP BY c.REF_LEVEL_ID,c.REF_CONTENT_ID
), level_metadata AS (
 SELECT LEVEL_ID::VARCHAR AS REF_LEVEL_ID,COUNT(*) AS META_LEVEL_ROWS,
        MAX(LEVEL_NAME::VARCHAR) AS LEVEL_NAME,
        MAX(MODULE_NAME::VARCHAR) AS MODULE_NAME
 FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_META_LEVEL
 GROUP BY LEVEL_ID::VARCHAR
), clean_owners AS (
 SELECT o.*,CASE WHEN TYPEOF(J)=''OBJECT''
   THEN OBJECT_DELETE(AS_OBJECT(J),''_OSCAL_RESOLVED_RECORD_REFERENCES'')
   ELSE OBJECT_CONSTRUCT() END AS ORIGINAL_FIELDS
 FROM owners o
), field_values AS (
 SELECT o.SOURCE_TABLE,o.SOURCE_ROW_NO,f.KEY::VARCHAR AS FIELD_NAME,
        f.PATH::VARCHAR AS FIELD_PATH,f.VALUE AS FIELD_VALUE
 FROM clean_owners o,LATERAL FLATTEN(INPUT=>o.ORIGINAL_FIELDS) f
), object_values AS (
 SELECT SOURCE_TABLE,SOURCE_ROW_NO,FIELD_NAME,FIELD_PATH AS JSON_PATH,
        NULL::NUMBER AS ARRAY_INDEX,FIELD_VALUE AS REF_OBJECT
 FROM field_values WHERE TYPEOF(FIELD_VALUE)=''OBJECT''
 UNION ALL
 SELECT p.SOURCE_TABLE,p.SOURCE_ROW_NO,p.FIELD_NAME,
        p.FIELD_PATH||IFF(LEFT(f.PATH::VARCHAR,1)=''['','''',''.'')||f.PATH::VARCHAR AS JSON_PATH,
        f.INDEX AS ARRAY_INDEX,f.VALUE AS REF_OBJECT
 FROM field_values p,LATERAL FLATTEN(INPUT=>
      IFF(TYPEOF(p.FIELD_VALUE) IN (''ARRAY'',''OBJECT''),p.FIELD_VALUE,NULL),
      RECURSIVE=>TRUE) f
 WHERE TYPEOF(f.VALUE)=''OBJECT''
 UNION ALL
 SELECT SOURCE_TABLE,SOURCE_ROW_NO,''[ROOT]'',''$'',NULL::NUMBER,ORIGINAL_FIELDS
 FROM clean_owners
), possible_references AS (
 SELECT o.*,
        ARRAY_CONTAINS(TO_VARIANT(''ContentId''),OBJECT_KEYS(AS_OBJECT(REF_OBJECT))) AS HAS_CONTENT_KEY,
        ARRAY_CONTAINS(TO_VARIANT(''LevelId''),OBJECT_KEYS(AS_OBJECT(REF_OBJECT))) AS HAS_LEVEL_KEY,
        GET(REF_OBJECT,''ContentId'')::VARCHAR AS REF_CONTENT_ID,
        GET(REF_OBJECT,''LevelId'')::VARCHAR AS REF_LEVEL_ID
 FROM object_values o
), references_found AS (
 -- Key presence keeps JSON-null and incomplete objects visible for diagnosis.
 SELECT * FROM possible_references
 WHERE COALESCE(HAS_CONTENT_KEY,FALSE) OR COALESCE(HAS_LEVEL_KEY,FALSE)
), resolved AS (
 SELECT r.SOURCE_TABLE,r.SOURCE_ROW_NO,r.FIELD_NAME,r.JSON_PATH,r.ARRAY_INDEX,
        s.STORED_CONTENT_ID,s.OWNER_ARCHER_CONTENT_ID,s.OWNER_ARCHER_LEVEL_ID,
        r.REF_CONTENT_ID,r.REF_LEVEL_ID,m.LEVEL_NAME,m.MODULE_NAME,
        t.TARGET_RAW_TABLE AS REPRESENTATIVE_TARGET_RAW_TABLE,COALESCE(t.TARGET_PHYSICAL_ROWS,0) AS TARGET_PHYSICAL_ROWS,
        COALESCE(t.TARGET_TABLES,0) AS TARGET_TABLES,
        CASE
          WHEN NOT COALESCE(r.HAS_CONTENT_KEY,FALSE)
            OR NOT COALESCE(r.HAS_LEVEL_KEY,FALSE) THEN ''INCOMPLETE_REFERENCE_OBJECT''
          WHEN NOT REGEXP_LIKE(COALESCE(r.REF_CONTENT_ID,''''),''^[1-9][0-9]*$'')
            OR NOT REGEXP_LIKE(COALESCE(r.REF_LEVEL_ID,''''),''^[1-9][0-9]*$'')
            THEN ''INVALID_REFERENCE_ID_OR_LEVEL''
          WHEN NOT s.OWNER_IDENTITY_VERIFIED THEN ''SOURCE_RAW_IDENTITY_UNVERIFIED''
          WHEN s.OWNER_PAIR_ROWS<>1 THEN ''DUPLICATE_SOURCE_ARCHER_ID''
          WHEN m.REF_LEVEL_ID IS NULL THEN ''LEVEL_NOT_IN_META_LEVEL''
          WHEN m.META_LEVEL_ROWS<>1 THEN ''AMBIGUOUS_META_LEVEL''
          WHEN t.REF_CONTENT_ID IS NULL THEN ''TARGET_NOT_FOUND_IN_VISIBLE_RAW''
          WHEN t.TARGET_PHYSICAL_ROWS<>1 OR t.TARGET_TABLES<>1 THEN ''AMBIGUOUS_TARGET''
          WHEN t.TARGET_VERIFIED_IDENTITY_ROWS<>1 THEN ''TARGET_RAW_IDENTITY_UNVERIFIED''
          WHEN t.TARGET_OBJECT_JSON_ROWS<>1 THEN ''TARGET_CURATED_JSON_NOT_OBJECT''
          ELSE ''UNIQUE_CURATED_TARGET_FOUND''
        END AS REFERENCE_STATUS,
        CASE
          WHEN GET(s.J,''_OSCAL_RESOLVED_RECORD_REFERENCES'') IS NULL THEN ''SIDECAR_ABSENT''
          WHEN TYPEOF(GET(s.J,''_OSCAL_RESOLVED_RECORD_REFERENCES''))<>''OBJECT''
            THEN ''SIDECAR_NOT_OBJECT''
          WHEN GET(GET(s.J,''_OSCAL_RESOLVED_RECORD_REFERENCES''),r.FIELD_NAME) IS NULL
            THEN ''SIDECAR_FIELD_ABSENT''
          ELSE ''SIDECAR_FIELD_PRESENT_NOT_VALIDATED''
        END AS ENRICHMENT_STATUS
 FROM references_found r JOIN owners s
   ON s.SOURCE_TABLE=r.SOURCE_TABLE AND s.SOURCE_ROW_NO=r.SOURCE_ROW_NO
 LEFT JOIN targets t ON t.REF_LEVEL_ID=r.REF_LEVEL_ID AND t.REF_CONTENT_ID=r.REF_CONTENT_ID
 LEFT JOIN level_metadata m ON m.REF_LEVEL_ID=r.REF_LEVEL_ID
), source_stats AS (
 SELECT SOURCE_TABLE,COUNT(*) AS SOURCE_PHYSICAL_ROWS,
        SUM(IFF(TYPEOF(J)=''OBJECT'',1,0)) AS CURATED_OBJECT_ROWS,
        SUM(IFF(COALESCE(TYPEOF(J),''SQL_NULL'')<>''OBJECT'',1,0)) AS UNUSABLE_CURATED_ROWS,
        SUM(IFF(OWNER_IDENTITY_VERIFIED,0,1)) AS UNVERIFIED_RAW_IDENTITY_ROWS,
        SUM(IFF(OWNER_IDENTITY_VERIFIED AND OWNER_PAIR_ROWS<>1,1,0)) AS DUPLICATE_SOURCE_ID_ROWS,
        SUM(IFF(OWNER_IDENTITY_VERIFIED
                AND STORED_CONTENT_ID IS DISTINCT FROM OWNER_ARCHER_CONTENT_ID,1,0))
           AS STORED_ID_DIFFERS_FROM_ARCHER_ID_ROWS
 FROM owners GROUP BY SOURCE_TABLE
)
';
  IF (UPPER(v_report_mode)='DETAIL') THEN
    v_sql := v_sql||'SELECT * FROM resolved
ORDER BY SOURCE_TABLE,SOURCE_ROW_NO,FIELD_NAME,JSON_PATH';
  ELSEIF (UPPER(v_report_mode)='SUMMARY') THEN
    v_sql := v_sql||'SELECT i.SOURCE_TABLE,
       COUNT(*) OVER () AS REPORT_ROWS,
       i.RAW_DATA_COLUMNS,i.CONTENT_ID_COLUMNS,i.CURATED_JSON_COLUMNS,
       s.SOURCE_PHYSICAL_ROWS,s.CURATED_OBJECT_ROWS,s.UNUSABLE_CURATED_ROWS,
       s.UNVERIFIED_RAW_IDENTITY_ROWS,s.DUPLICATE_SOURCE_ID_ROWS,
       s.STORED_ID_DIFFERS_FROM_ARCHER_ID_ROWS,
       CASE WHEN NOT i.ELIGIBLE THEN ''NOT_AUDITED_MISSING_OR_AMBIGUOUS_COLUMNS''
            WHEN COALESCE(s.UNUSABLE_CURATED_ROWS,0)>0
              OR COALESCE(s.UNVERIFIED_RAW_IDENTITY_ROWS,0)>0
              OR COALESCE(s.DUPLICATE_SOURCE_ID_ROWS,0)>0
              THEN ''SOURCE_ROWS_NOT_FULLY_AUDITABLE''
            ELSE ''SOURCE_ROWS_AUDITABLE'' END AS SOURCE_AUDIT_STATUS,
       r.FIELD_NAME,COALESCE(r.REFERENCE_STATUS,
          IFF(i.ELIGIBLE,''NO_STRUCTURED_REFERENCE_CANDIDATES'',''NOT_AUDITED'')) AS REFERENCE_STATUS,
       r.ENRICHMENT_STATUS,COUNT(r.SOURCE_ROW_NO) AS REFERENCE_OCCURRENCES,
       COUNT(DISTINCT r.SOURCE_ROW_NO) AS SOURCE_ROWS_WITH_THIS_STATUS,
       LISTAGG(DISTINCT r.REPRESENTATIVE_TARGET_RAW_TABLE,'' | '')
          WITHIN GROUP (ORDER BY r.REPRESENTATIVE_TARGET_RAW_TABLE) AS REPRESENTATIVE_TARGET_TABLES
FROM inventory i
LEFT JOIN source_stats s ON s.SOURCE_TABLE=i.SOURCE_TABLE
LEFT JOIN resolved r ON r.SOURCE_TABLE=i.SOURCE_TABLE
GROUP BY i.SOURCE_TABLE,i.RAW_DATA_COLUMNS,i.CONTENT_ID_COLUMNS,i.CURATED_JSON_COLUMNS,
         i.ELIGIBLE,s.SOURCE_PHYSICAL_ROWS,s.CURATED_OBJECT_ROWS,s.UNUSABLE_CURATED_ROWS,
         s.UNVERIFIED_RAW_IDENTITY_ROWS,s.DUPLICATE_SOURCE_ID_ROWS,
         s.STORED_ID_DIFFERS_FROM_ARCHER_ID_ROWS,r.FIELD_NAME,r.REFERENCE_STATUS,r.ENRICHMENT_STATUS
ORDER BY i.SOURCE_TABLE,r.FIELD_NAME,REFERENCE_STATUS,ENRICHMENT_STATUS';
  ELSE
    v_result := (SELECT 'SET_v_report_mode_TO_SUMMARY_OR_DETAIL' AS AUDIT_STATUS);
    RETURN TABLE(v_result);
  END IF;
  v_result := (EXECUTE IMMEDIATE :v_sql);
  RETURN TABLE(v_result);
END;
$$;
