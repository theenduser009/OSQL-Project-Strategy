-- READ ONLY. Discover actual visible RAW tables before the full audit.
-- Missing or duplicate canonical columns are reported, not silently guessed.
WITH inventory AS (
SELECT TABLE_CATALOG,TABLE_SCHEMA,TABLE_NAME,
       SUM(IFF(UPPER(COLUMN_NAME)='RAW_DATA',1,0)) AS RAW_DATA_COLUMNS,
       SUM(IFF(UPPER(COLUMN_NAME)='CONTENT_ID',1,0)) AS CONTENT_ID_COLUMNS,
       SUM(IFF(UPPER(COLUMN_NAME)='CURATED_JSON',1,0)) AS CURATED_JSON_COLUMNS
FROM RTX_RAW_DEV.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA='ES_ESC_GRC'
  AND STARTSWITH(UPPER(TABLE_NAME),'ARCHER_CONTENT_')
  AND ENDSWITH(UPPER(TABLE_NAME),'_RAW')
GROUP BY TABLE_CATALOG,TABLE_SCHEMA,TABLE_NAME
)
SELECT *,
 COUNT(*) OVER () AS DISCOVERED_RAW_TABLES,
 SUM(IFF(RAW_DATA_COLUMNS=1 AND CONTENT_ID_COLUMNS=1 AND CURATED_JSON_COLUMNS=1,1,0))
   OVER () AS ELIGIBLE_RAW_TABLES,
 IFF(RAW_DATA_COLUMNS=1 AND CONTENT_ID_COLUMNS=1 AND CURATED_JSON_COLUMNS=1,
     'ELIGIBLE_FOR_READ_ONLY_AUDIT','MISSING_OR_AMBIGUOUS_REQUIRED_COLUMNS') AS TABLE_STATUS
FROM inventory ORDER BY TABLE_NAME;
