-- SSP CIA direct-native change impact and source-value conflicts
-- Read-only Snowflake DEV | 2026-10-12
-- Exact database/schema/table identifiers. No target writes or sample IDs.
-- Run both SELECT statements before any mapper PREVIEW or migration.

-- 1) Classify each Archer record by non-null CIA objectives, compare
--    current native nodes and old fallback-property nodes.
WITH cia_fields AS (
  SELECT
      a.CONTENT_ID::STRING AS SOURCE_RECORD_ID,
      f.KEY::STRING AS ARCHER_FIELD,
      IFF(f.VALUE IS NOT NULL AND NOT COALESCE(IS_NULL_VALUE(f.VALUE), FALSE), 1, 0)
          AS HAS_VALUE
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a,
       LATERAL FLATTEN(INPUT => a.CURATED_JSON) f
  WHERE f.KEY::STRING IN (
      'RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY',
      'CONFIDENTIALITY_CONTROL_CATEGORY_OVERRIDE',
      'CNSS_CONFIDENTIALITY_RATING',
      'RECOMMENDED_INTEGRITY_CONTROL_CATEGORY',
      'INTEGRITY_CONTROL_CATEGORY_OVERRIDE',
      'PROGRAMSITE_INTEGRITY_CONTROL_CATEGORY',
      'CNSS_INTEGRITY_RATING',
      'RECOMMENDED_AVAILABILITY_CONTROL_CATEGORY',
      'AVAILABILITY_CONTROL_CATEGORY_OVERRIDE',
      'PROGRAMSITE_AVAILABILITY_CONTROL_CATEGORY',
      'CNSS_AVAILABILITY_RATING'
  )
),
by_record AS (
  SELECT SOURCE_RECORD_ID,
      MAX(IFF(ARCHER_FIELD IN (
          'RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY',
          'CONFIDENTIALITY_CONTROL_CATEGORY_OVERRIDE',
          'CNSS_CONFIDENTIALITY_RATING'
      ), HAS_VALUE, 0)) AS HAS_CONFIDENTIALITY,
      MAX(IFF(ARCHER_FIELD IN (
          'RECOMMENDED_INTEGRITY_CONTROL_CATEGORY',
          'INTEGRITY_CONTROL_CATEGORY_OVERRIDE',
          'PROGRAMSITE_INTEGRITY_CONTROL_CATEGORY',
          'CNSS_INTEGRITY_RATING'
      ), HAS_VALUE, 0)) AS HAS_INTEGRITY,
      MAX(IFF(ARCHER_FIELD IN (
          'RECOMMENDED_AVAILABILITY_CONTROL_CATEGORY',
          'AVAILABILITY_CONTROL_CATEGORY_OVERRIDE',
          'PROGRAMSITE_AVAILABILITY_CONTROL_CATEGORY',
          'CNSS_AVAILABILITY_RATING'
      ), HAS_VALUE, 0)) AS HAS_AVAILABILITY
  FROM cia_fields
  GROUP BY SOURCE_RECORD_ID
),
classified AS (
  SELECT SOURCE_RECORD_ID,
      CASE
          WHEN HAS_CONFIDENTIALITY = 1
           AND HAS_INTEGRITY = 1
           AND HAS_AVAILABILITY = 1 THEN 'COMPLETE_CIA'
          WHEN HAS_CONFIDENTIALITY + HAS_INTEGRITY + HAS_AVAILABILITY > 0
              THEN 'PARTIAL_CIA'
          ELSE 'ALL_CIA_NULL'
      END AS SOURCE_CIA_CLASS
  FROM by_record
),
stored AS (
  SELECT
      SOURCE_RECORD_ID,
      SUM(IFF(LOWER(ELEMENT_TYPE) = 'security-impact-level', 1, 0))
          AS NATIVE_IMPACT_NODES,
      SUM(IFF(LOWER(ELEMENT_TYPE) = 'props' AND
          METADATA_JSON:"name"::STRING IN (
              'recommended-confidentiality-control-category',
              'confidentiality-control-category-override',
              'cnss-confidentiality-rating',
              'recommended-integrity-control-category',
              'integrity-control-category-override',
              'programsite-integrity-control-category',
              'cnss-integrity-rating',
              'recommended-availability-control-category',
              'availability-control-category-override',
              'programsite-availability-control-category',
              'cnss-availability-rating'
          ), 1, 0)) AS FALLBACK_PROP_NODES
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
  GROUP BY SOURCE_RECORD_ID
)
SELECT
    c.SOURCE_CIA_CLASS,
    COUNT(*) AS SOURCE_RECORDS,
    SUM(COALESCE(s.NATIVE_IMPACT_NODES, 0)) AS STORED_NATIVE_NODES,
    SUM(COALESCE(s.FALLBACK_PROP_NODES, 0)) AS STORED_FALLBACK_NODES
FROM classified c
LEFT JOIN stored s ON s.SOURCE_RECORD_ID = c.SOURCE_RECORD_ID
GROUP BY c.SOURCE_CIA_CLASS
ORDER BY c.SOURCE_CIA_CLASS;

-- 2) Find any objective receiving contradictory non-null Archer labels
--    or populated but unresolved select labels. Zero rows is the target.
WITH mapped_fields (ARCHER_FIELD, OBJECTIVE) AS (
  SELECT COLUMN1, COLUMN2 FROM VALUES
      ('RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY', 'CONFIDENTIALITY'),
      ('CONFIDENTIALITY_CONTROL_CATEGORY_OVERRIDE', 'CONFIDENTIALITY'),
      ('CNSS_CONFIDENTIALITY_RATING', 'CONFIDENTIALITY'),
      ('RECOMMENDED_INTEGRITY_CONTROL_CATEGORY', 'INTEGRITY'),
      ('INTEGRITY_CONTROL_CATEGORY_OVERRIDE', 'INTEGRITY'),
      ('PROGRAMSITE_INTEGRITY_CONTROL_CATEGORY', 'INTEGRITY'),
      ('CNSS_INTEGRITY_RATING', 'INTEGRITY'),
      ('RECOMMENDED_AVAILABILITY_CONTROL_CATEGORY', 'AVAILABILITY'),
      ('AVAILABILITY_CONTROL_CATEGORY_OVERRIDE', 'AVAILABILITY'),
      ('PROGRAMSITE_AVAILABILITY_CONTROL_CATEGORY', 'AVAILABILITY'),
      ('CNSS_AVAILABILITY_RATING', 'AVAILABILITY')
),
populated AS (
  SELECT a.CONTENT_ID::STRING AS SOURCE_RECORD_ID,
      m.OBJECTIVE,
      CASE
          WHEN IS_OBJECT(f.VALUE)
           AND ARRAY_SIZE(f.VALUE:ResolvedValues) = 1
           AND f.VALUE:ResolvedValues[0]:LookupStatus::STRING = 'MATCHED'
              THEN TRIM(f.VALUE:ResolvedValues[0]:ValueName::STRING)
          WHEN TYPEOF(f.VALUE) = 'VARCHAR' THEN TRIM(f.VALUE::STRING)
          ELSE NULL
      END AS SOURCE_LABEL
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a,
       LATERAL FLATTEN(INPUT => a.CURATED_JSON) f,
       mapped_fields m
  WHERE f.KEY::STRING = m.ARCHER_FIELD
    AND f.VALUE IS NOT NULL
    AND NOT COALESCE(IS_NULL_VALUE(f.VALUE), FALSE)
),
canonical AS (
  SELECT SOURCE_RECORD_ID, OBJECTIVE,
      CASE WHEN LOWER(SOURCE_LABEL) IN ('low', 'moderate', 'high')
           THEN LOWER(SOURCE_LABEL) ELSE SOURCE_LABEL END AS LABEL
  FROM populated
)
SELECT SOURCE_RECORD_ID, OBJECTIVE,
    COUNT(DISTINCT LABEL) AS DISTINCT_NON_NULL_LABELS,
    SUM(IFF(LABEL IS NULL, 1, 0)) AS UNRESOLVED_VALUES
FROM canonical
GROUP BY SOURCE_RECORD_ID, OBJECTIVE
HAVING COUNT(DISTINCT LABEL) > 1 OR SUM(IFF(LABEL IS NULL, 1, 0)) > 0
ORDER BY SOURCE_RECORD_ID, OBJECTIVE;
