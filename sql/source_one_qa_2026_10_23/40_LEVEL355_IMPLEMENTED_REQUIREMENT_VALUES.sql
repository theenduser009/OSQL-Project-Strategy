-- Source One SSP Control Implementation: exact joined Level-355 field QA.
-- 2026-10-23 | READ ONLY | Snowflake DEV | no DML.
-- CONTROL_NUMBER -> implemented-requirements[].control-id
-- IMPLEMENTATION_DETAILS -> implemented-requirements[].remarks
-- The mapper selects Authorization Package reference [0] as parent and
-- ALLOCATED_CONTROL_ID as implemented requirement instance identity.
-- This checks the expected v1 keyed child under root->control-implementation
-- via two FACT links. A mismatch of deployed identity version, raw snapshot
-- ordering, or live registry is a separate investigation, not an automatic fix.
WITH package_records AS (
  SELECT DISTINCT CONTENT_ID::STRING AS CONTENT_ID
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
joined_raw AS (
  SELECT
    CONTENT_ID::STRING AS CHILD_CONTENT_ID,
    COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS CHILD_SNAPSHOTS,
    CURATED_JSON:"AUTHORIZATION_PACKAGE"[0]::STRING AS PARENT_CONTENT_ID,
    CURATED_JSON:"ALLOCATED_CONTROL_ID"::STRING AS ALLOCATED_CONTROL_ID,
    CURATED_JSON:"CONTROL_NUMBER" AS CONTROL_NUMBER,
    CURATED_JSON:"IMPLEMENTATION_DETAILS" AS IMPLEMENTATION_DETAILS
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_ALLOCATED_CONTROLS_CONTROL_RAW
),
field_contract AS (
  SELECT column1::STRING AS FIELD_NAME, column2::STRING AS TARGET_MEMBER
  FROM VALUES
    ('CONTROL_NUMBER', 'control-id'),
    ('IMPLEMENTATION_DETAILS', 'remarks')
),
expectations AS (
  SELECT
    j.CHILD_CONTENT_ID, j.CHILD_SNAPSHOTS,
    j.PARENT_CONTENT_ID, j.ALLOCATED_CONTROL_ID,
    f.FIELD_NAME, f.TARGET_MEMBER,
    IFF(f.FIELD_NAME='CONTROL_NUMBER',
        j.CONTROL_NUMBER, j.IMPLEMENTATION_DETAILS) AS SOURCE_VALUE,
    MD5_BINARY(CONCAT_WS('|',
      'v1_registry_path_instance',
      'ARCHER', 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW',
      j.PARENT_CONTENT_ID, 'SSP',
      'system-security-plan.control-implementation.implemented-requirements[]',
      j.ALLOCATED_CONTROL_ID)) AS EXPECTED_NODE_HASH
  FROM joined_raw j CROSS JOIN field_contract f
),
owned_requirements AS (
  SELECT req.SOURCE_RECORD_ID AS PARENT_CONTENT_ID,
         req.PK_OSCAL_SSP_ELEMENT_HASH AS NODE_HASH,
         req.METADATA_JSON:"control-id" AS TARGET_CONTROL_NUMBER,
         req.METADATA_JSON:"remarks" AS TARGET_IMPLEMENTATION_DETAILS
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT root
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY first_link
    ON first_link.FK_SOURCE_ELEMENT_HASH=root.PK_OSCAL_SSP_ELEMENT_HASH
   AND first_link.DEPENDENCY_TYPE='CONTAINS'
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT controls
    ON controls.PK_OSCAL_SSP_ELEMENT_HASH=first_link.FK_TARGET_ELEMENT_HASH
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY req_link
    ON req_link.FK_SOURCE_ELEMENT_HASH=controls.PK_OSCAL_SSP_ELEMENT_HASH
   AND req_link.DEPENDENCY_TYPE='CONTAINS'
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT req
    ON req.PK_OSCAL_SSP_ELEMENT_HASH=req_link.FK_TARGET_ELEMENT_HASH
  WHERE root.ELEMENT_TYPE='system-security-plan'
    AND controls.ELEMENT_TYPE='control-implementation'
    AND req.ELEMENT_TYPE='implemented-requirements'
    AND root.SOURCE_SYSTEM_NAME='ARCHER'
    AND root.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND controls.SOURCE_SYSTEM_NAME=root.SOURCE_SYSTEM_NAME
    AND req.SOURCE_SYSTEM_NAME=root.SOURCE_SYSTEM_NAME
    AND controls.SOURCE_TABLE_NAME=root.SOURCE_TABLE_NAME
    AND req.SOURCE_TABLE_NAME=root.SOURCE_TABLE_NAME
    AND controls.SOURCE_RECORD_ID=root.SOURCE_RECORD_ID
    AND req.SOURCE_RECORD_ID=root.SOURCE_RECORD_ID
),
checks AS (
  SELECT e.CHILD_CONTENT_ID, e.CHILD_SNAPSHOTS,
         e.PARENT_CONTENT_ID, e.ALLOCATED_CONTROL_ID,
         e.FIELD_NAME, e.TARGET_MEMBER, e.SOURCE_VALUE,
         parent.CONTENT_ID AS MATCHED_PACKAGE_ID,
         req.NODE_HASH,
         IFF(e.FIELD_NAME='CONTROL_NUMBER',
             req.TARGET_CONTROL_NUMBER,
             req.TARGET_IMPLEMENTATION_DETAILS) AS TARGET_VALUE,
         CASE
           WHEN e.CHILD_SNAPSHOTS>1 THEN 'JOINED_CHILD_SNAPSHOT_AMBIGUOUS'
           WHEN e.PARENT_CONTENT_ID IS NULL
                OR LENGTH(TRIM(e.PARENT_CONTENT_ID))=0
             THEN 'SOURCE_PARENT_ID_INVALID'
           WHEN parent.CONTENT_ID IS NULL
             THEN 'SOURCE_PARENT_NOT_FOUND'
           WHEN e.ALLOCATED_CONTROL_ID IS NULL
                OR LENGTH(TRIM(e.ALLOCATED_CONTROL_ID))=0
             THEN 'JOINED_INSTANCE_KEY_MISSING'
           WHEN e.SOURCE_VALUE IS NOT NULL
                AND NOT IS_NULL_VALUE(e.SOURCE_VALUE)
                AND TYPEOF(e.SOURCE_VALUE)<>'VARCHAR'
             THEN 'SOURCE_TEXT_SHAPE_REVIEW'
           WHEN req.NODE_HASH IS NULL
             THEN 'IMPLEMENTED_REQUIREMENT_MISSING_OR_VERSION_MISMATCH'
           WHEN e.SOURCE_VALUE IS NULL AND TARGET_VALUE IS NULL
             THEN 'SOURCE_FIELD_ABSENT'
           WHEN e.SOURCE_VALUE IS NULL
             THEN 'UNEXPECTED_TARGET_FIELD_FOR_ABSENT_SOURCE'
           WHEN IS_NULL_VALUE(e.SOURCE_VALUE)
                AND (TARGET_VALUE IS NULL OR IS_NULL_VALUE(TARGET_VALUE))
             THEN 'SOURCE_JSON_NULL_TARGET_OMITTED'
           WHEN IS_NULL_VALUE(e.SOURCE_VALUE)
             THEN 'SOURCE_NULL_TARGET_CONFLICT'
           WHEN LENGTH(TRIM(e.SOURCE_VALUE::STRING))=0
             THEN 'SOURCE_EMPTY_REVIEW'
           WHEN TARGET_VALUE IS NULL OR IS_NULL_VALUE(TARGET_VALUE)
             THEN 'POPULATED_SOURCE_TARGET_MEMBER_MISSING'
           WHEN e.SOURCE_VALUE::STRING=TARGET_VALUE::STRING THEN 'VALUE_MATCH'
           ELSE 'VALUE_MISMATCH'
         END AS QA_STATUS
  FROM expectations e
  LEFT JOIN package_records parent
    ON parent.CONTENT_ID=e.PARENT_CONTENT_ID
  LEFT JOIN owned_requirements req
    ON req.PARENT_CONTENT_ID=e.PARENT_CONTENT_ID
   AND req.NODE_HASH=e.EXPECTED_NODE_HASH
)
SELECT FIELD_NAME AS ARCHER_FIELD_NAME, TARGET_MEMBER, QA_STATUS,
       COUNT(*) AS JOINED_CHILD_FIELD_ROWS,
       COUNT(DISTINCT CHILD_CONTENT_ID) AS DISTINCT_CHILD_CONTENT_IDS,
       COUNT(DISTINCT PARENT_CONTENT_ID) AS DISTINCT_PARENT_PACKAGES,
       MIN(CHILD_CONTENT_ID) AS EXAMPLE_CHILD_CONTENT_ID
FROM checks
GROUP BY FIELD_NAME, TARGET_MEMBER, QA_STATUS
ORDER BY ARCHER_FIELD_NAME, QA_STATUS;
