-- Exact Source One fields requiring business mapping decisions:
-- RECOMMENDED_SECURITY_CATEGORY: BLOCKED_IF_POPULATED (reject-populated).
-- PORTS_PROTOCOLS_AND_SERVICES_MANAGEMENT_PPSM: not in runtime mapping CSV.
-- Source-only profiling. No field/value mapping or target PASS is implied.
-- Example source values stay in Snowflake; do not commit query results.
WITH requested AS (
  SELECT COLUMN1::STRING AS ARCHER_FIELD_NAME,
         COLUMN2::STRING AS CURRENT_MAPPING_STATUS
  FROM VALUES
    ('RECOMMENDED_SECURITY_CATEGORY','BLOCKED_IF_POPULATED'),
    ('PORTS_PROTOCOLS_AND_SERVICES_MANAGEMENT_PPSM','NOT_IN_RUNTIME_CSV')
),
raw AS (
  SELECT CONTENT_ID::STRING AS CONTENT_ID,
         CURATED_JSON,
         COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS RAW_SNAPSHOTS
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
field_values AS (
  SELECT k.ARCHER_FIELD_NAME,k.CURRENT_MAPPING_STATUS,
         s.CONTENT_ID,s.RAW_SNAPSHOTS,
         GET(s.CURATED_JSON,k.ARCHER_FIELD_NAME) AS SOURCE_VALUE
  FROM raw s CROSS JOIN requested k
),
classified AS (
  SELECT *,
    COALESCE(TYPEOF(SOURCE_VALUE),'SQL_NULL') AS SOURCE_JSON_TYPE,
    CASE
      WHEN SOURCE_VALUE IS NULL THEN 'SOURCE_KEY_ABSENT'
      WHEN IS_NULL_VALUE(SOURCE_VALUE) THEN 'EXPLICIT_JSON_NULL'
      WHEN TYPEOF(SOURCE_VALUE)='VARCHAR'
           AND LENGTH(TRIM(SOURCE_VALUE::STRING))=0 THEN 'SOURCE_EMPTY'
      WHEN IS_ARRAY(SOURCE_VALUE) AND ARRAY_SIZE(SOURCE_VALUE)=0
           THEN 'SOURCE_EMPTY'
      WHEN IS_OBJECT(SOURCE_VALUE)
           AND ARRAY_SIZE(OBJECT_KEYS(SOURCE_VALUE))=0 THEN 'SOURCE_EMPTY'
      ELSE 'SOURCE_POPULATED'
    END AS SOURCE_STATE
  FROM field_values
),
counts AS (
  SELECT ARCHER_FIELD_NAME,CURRENT_MAPPING_STATUS,
         SOURCE_STATE,SOURCE_JSON_TYPE,
         COUNT(*) AS SOURCE_ROWS,
         COUNT(DISTINCT CONTENT_ID) AS DISTINCT_CONTENT_IDS,
         COUNT_IF(RAW_SNAPSHOTS>1) AS AMBIGUOUS_RAW_SNAPSHOT_ROWS
  FROM classified
  GROUP BY ARCHER_FIELD_NAME,CURRENT_MAPPING_STATUS,
           SOURCE_STATE,SOURCE_JSON_TYPE
),
examples AS (
  SELECT ARCHER_FIELD_NAME,SOURCE_STATE,SOURCE_JSON_TYPE,
         CONTENT_ID AS EXAMPLE_CONTENT_ID,
         SOURCE_VALUE AS EXAMPLE_SOURCE_JSON,
         IFF(IS_ARRAY(SOURCE_VALUE),ARRAY_SIZE(SOURCE_VALUE),NULL)
           AS EXAMPLE_ARRAY_SIZE,
         IFF(IS_ARRAY(SOURCE_VALUE:"ResolvedValues"),
             ARRAY_SIZE(SOURCE_VALUE:"ResolvedValues"),NULL)
           AS EXAMPLE_RESOLVED_SELECT_COUNT
  FROM classified
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ARCHER_FIELD_NAME,SOURCE_STATE,SOURCE_JSON_TYPE
    ORDER BY CONTENT_ID
  )=1
)
SELECT c.ARCHER_FIELD_NAME,c.CURRENT_MAPPING_STATUS,
       c.SOURCE_STATE,c.SOURCE_JSON_TYPE,
       c.SOURCE_ROWS,c.DISTINCT_CONTENT_IDS,
       c.AMBIGUOUS_RAW_SNAPSHOT_ROWS,
       e.EXAMPLE_CONTENT_ID,e.EXAMPLE_SOURCE_JSON,
       e.EXAMPLE_ARRAY_SIZE,e.EXAMPLE_RESOLVED_SELECT_COUNT,
       CASE
         WHEN c.SOURCE_STATE='SOURCE_POPULATED'
           THEN 'POPULATED_NEEDS_REVIEW_AND_OWNER_APPROVAL'
         ELSE 'NO_POPULATED_VALUE_PROVEN'
       END AS QA_DISPOSITION
FROM counts c
LEFT JOIN examples e
  ON e.ARCHER_FIELD_NAME=c.ARCHER_FIELD_NAME
 AND e.SOURCE_STATE=c.SOURCE_STATE
 AND e.SOURCE_JSON_TYPE=c.SOURCE_JSON_TYPE
ORDER BY c.ARCHER_FIELD_NAME,c.SOURCE_STATE,c.SOURCE_JSON_TYPE;
