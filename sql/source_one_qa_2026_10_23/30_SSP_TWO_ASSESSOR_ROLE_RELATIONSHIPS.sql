-- Source One SSP two assessor fields: party/assignment graph QA.
-- 2026-10-23 | READ ONLY | Snowflake DEV.
-- Roles are NOT system-characteristics props. They are metadata assignments
-- (responsible-parties) referencing parties by UUID. Check FACT ownership,
-- cardinality and orphan party UUIDs. Exact UUIDv5 identity from source user
-- IDs is not computed here: an intact count/graph is PARTIAL, not full PASS.
WITH field_contract AS (
  SELECT column1::STRING AS FIELD_NAME, column2::STRING AS ROLE_ID
  FROM VALUES
     ('SECURITY_CONTROL_ASSESSOR_SCA', 'security-control-assessor'),
     ('ALTERNATE_SECURITY_CONTROL_ASSESSOR_SCA',
      'alternate-security-control-assessor')
),
raw AS (
  SELECT CONTENT_ID::STRING AS CONTENT_ID, CURATED_JSON,
         COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS SNAPSHOT_COUNT
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
sources AS (
  SELECT r.CONTENT_ID, r.SNAPSHOT_COUNT,
         f.FIELD_NAME, f.ROLE_ID,
         GET(r.CURATED_JSON, f.FIELD_NAME) AS SOURCE_VALUE
  FROM raw r CROSS JOIN field_contract f
),
source_states AS (
  SELECT *,
         CASE
           WHEN SOURCE_VALUE IS NULL THEN 'SOURCE_KEY_ABSENT'
           WHEN IS_NULL_VALUE(SOURCE_VALUE) THEN 'SOURCE_NULL'
           WHEN IS_ARRAY(SOURCE_VALUE) AND ARRAY_SIZE(SOURCE_VALUE)=0
               THEN 'SOURCE_EMPTY'
           WHEN IS_OBJECT(SOURCE_VALUE)
                AND IS_ARRAY(SOURCE_VALUE:"UserList")
                AND ARRAY_SIZE(SOURCE_VALUE:"UserList")=0
                AND COALESCE(ARRAY_SIZE(SOURCE_VALUE:"GroupList"),0)=0
               THEN 'SOURCE_EMPTY'
           WHEN IS_OBJECT(SOURCE_VALUE)
                AND COALESCE(ARRAY_SIZE(SOURCE_VALUE:"UserList"),0)=0
                AND COALESCE(ARRAY_SIZE(SOURCE_VALUE:"GroupList"),0)>0
               THEN 'SOURCE_GROUP_ONLY_REVIEW'
           ELSE 'SOURCE_PRESENT'
         END AS SOURCE_STATE,
         CASE
           WHEN IS_ARRAY(SOURCE_VALUE:"UserList")
               THEN SOURCE_VALUE:"UserList"
           WHEN IS_ARRAY(SOURCE_VALUE) THEN SOURCE_VALUE
           WHEN IS_OBJECT(SOURCE_VALUE)
               AND (SOURCE_VALUE:"Id" IS NOT NULL
                    OR SOURCE_VALUE:"UserId" IS NOT NULL
                    OR SOURCE_VALUE:"ContentId" IS NOT NULL)
               THEN ARRAY_CONSTRUCT(SOURCE_VALUE)
           ELSE ARRAY_CONSTRUCT()
         END AS USER_MEMBERS
  FROM sources
),
source_ids AS (
  SELECT s.CONTENT_ID, s.FIELD_NAME, s.ROLE_ID,
         COALESCE(f.VALUE:"Id"::STRING,
                  f.VALUE:"UserId"::STRING,
                  f.VALUE:"ContentId"::STRING,
                  IFF(NOT IS_OBJECT(f.VALUE), f.VALUE::STRING, NULL))
           AS SOURCE_USER_ID
  FROM source_states s,
       LATERAL FLATTEN(INPUT=>s.USER_MEMBERS) f
),
source_counts AS (
  SELECT CONTENT_ID, FIELD_NAME,
         COUNT(DISTINCT SOURCE_USER_ID) AS SOURCE_UNIQUE_USER_IDS,
         COUNT_IF(SOURCE_USER_ID IS NULL OR
                  LENGTH(TRIM(SOURCE_USER_ID))=0) AS INVALID_SOURCE_REFS
  FROM source_ids
  GROUP BY CONTENT_ID, FIELD_NAME
),
assignments AS (
  SELECT child.SOURCE_RECORD_ID AS CONTENT_ID,
         child.METADATA_JSON:"role-id"::STRING AS ROLE_ID,
         child.METADATA_JSON:"party-uuids" AS PARTY_UUIDS,
         child.METADATA_JSON:"props" AS ASSIGNMENT_PROPS,
         HEX_ENCODE(child.PK_OSCAL_SSP_ELEMENT_HASH) AS ASSIGNMENT_HASH
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT parent
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY edge
    ON edge.FK_SOURCE_ELEMENT_HASH=parent.PK_OSCAL_SSP_ELEMENT_HASH
   AND edge.DEPENDENCY_TYPE='CONTAINS'
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT child
    ON child.PK_OSCAL_SSP_ELEMENT_HASH=edge.FK_TARGET_ELEMENT_HASH
  WHERE parent.ELEMENT_TYPE='metadata'
    AND child.ELEMENT_TYPE='responsible-parties'
    AND parent.SOURCE_SYSTEM_NAME='ARCHER'
    AND parent.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND child.SOURCE_SYSTEM_NAME=parent.SOURCE_SYSTEM_NAME
    AND child.SOURCE_TABLE_NAME=parent.SOURCE_TABLE_NAME
    AND child.SOURCE_RECORD_ID=parent.SOURCE_RECORD_ID
),
party_nodes AS (
  SELECT p.SOURCE_RECORD_ID AS CONTENT_ID,
         p.METADATA_JSON:"uuid"::STRING AS PARTY_UUID
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT p
  WHERE p.ELEMENT_TYPE='parties'
    AND p.SOURCE_SYSTEM_NAME='ARCHER'
    AND p.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
),
assignment_uuids AS (
  SELECT a.CONTENT_ID, a.ROLE_ID,
         f.VALUE::STRING AS PARTY_UUID
  FROM assignments a,
       LATERAL FLATTEN(INPUT=>a.PARTY_UUIDS) f
),
assignment_uuid_counts AS (
  SELECT u.CONTENT_ID, u.ROLE_ID,
         COUNT(DISTINCT u.PARTY_UUID) AS ASSIGNED_UUIDS,
         COALESCE(COUNT_IF(p.PARTY_UUID IS NULL),0) AS ORPHAN_UUID_REFS
  FROM assignment_uuids u
  LEFT JOIN party_nodes p
    ON p.CONTENT_ID=u.CONTENT_ID AND p.PARTY_UUID=u.PARTY_UUID
  GROUP BY u.CONTENT_ID, u.ROLE_ID
),
qa AS (
  SELECT s.CONTENT_ID, s.FIELD_NAME, s.ROLE_ID,
         s.SOURCE_STATE, s.SNAPSHOT_COUNT,
         COALESCE(src.SOURCE_UNIQUE_USER_IDS,0) AS SOURCE_USERS,
         COALESCE(src.INVALID_SOURCE_REFS,0) AS INVALID_SOURCE_REFS,
         COUNT(a.ASSIGNMENT_HASH) AS ASSIGNMENT_ROWS,
         COALESCE(MAX(au.ASSIGNED_UUIDS),0) AS ASSIGNED_UUIDS,
         COALESCE(MAX(au.ORPHAN_UUID_REFS),0) AS ORPHAN_UUID_REFS,
         CASE
           WHEN s.SNAPSHOT_COUNT>1 THEN 'SOURCE_SNAPSHOT_AMBIGUOUS'
           WHEN s.SOURCE_STATE IN ('SOURCE_KEY_ABSENT','SOURCE_NULL',
                                   'SOURCE_EMPTY')
             THEN IFF(COUNT(a.ASSIGNMENT_HASH)=0, s.SOURCE_STATE,
                      'UNEXPECTED_ROLE_ASSIGNMENT')
           WHEN s.SOURCE_STATE='SOURCE_GROUP_ONLY_REVIEW'
             THEN 'SOURCE_GROUP_ONLY_REVIEW'
           WHEN COALESCE(src.INVALID_SOURCE_REFS,0)>0 OR
                COALESCE(src.SOURCE_UNIQUE_USER_IDS,0)=0
             THEN 'SOURCE_USER_REFERENCE_SHAPE_REVIEW'
           WHEN COUNT(a.ASSIGNMENT_HASH)=0
             THEN 'POPULATED_SOURCE_ROLE_MISSING'
           WHEN COUNT(a.ASSIGNMENT_HASH)>1
             THEN 'DUPLICATE_ROLE_ASSIGNMENTS'
           WHEN COALESCE(MAX(au.ORPHAN_UUID_REFS),0)>0
             THEN 'ORPHAN_PARTY_UUID'
           WHEN COALESCE(src.SOURCE_UNIQUE_USER_IDS,0)
                <>COALESCE(MAX(au.ASSIGNED_UUIDS),0)
             THEN 'SOURCE_TARGET_PARTY_COUNT_MISMATCH'
           ELSE 'ROLE_GRAPH_AND_COUNT_MATCH_UUID_IDENTITY_REVIEW'
         END AS QA_STATUS
  FROM source_states s
  LEFT JOIN source_counts src
    ON src.CONTENT_ID=s.CONTENT_ID AND src.FIELD_NAME=s.FIELD_NAME
  LEFT JOIN assignments a
    ON a.CONTENT_ID=s.CONTENT_ID AND a.ROLE_ID=s.ROLE_ID
  LEFT JOIN assignment_uuid_counts au
    ON au.CONTENT_ID=a.CONTENT_ID AND au.ROLE_ID=a.ROLE_ID
  GROUP BY s.CONTENT_ID, s.FIELD_NAME, s.ROLE_ID,
           s.SOURCE_STATE, s.SNAPSHOT_COUNT, src.SOURCE_UNIQUE_USER_IDS,
           src.INVALID_SOURCE_REFS
)
SELECT FIELD_NAME AS ARCHER_FIELD_NAME, ROLE_ID, QA_STATUS,
       COUNT(*) AS RECORDS, COUNT(DISTINCT CONTENT_ID) AS DISTINCT_CONTENT_IDS,
       SUM(SOURCE_USERS) AS SOURCE_USER_IDS,
       SUM(ASSIGNED_UUIDS) AS TARGET_PARTY_UUIDS,
       SUM(ORPHAN_UUID_REFS) AS ORPHAN_UUID_REFS,
       MIN(CONTENT_ID) AS EXAMPLE_CONTENT_ID
FROM qa
GROUP BY FIELD_NAME, ROLE_ID, QA_STATUS
ORDER BY ARCHER_FIELD_NAME, QA_STATUS;
