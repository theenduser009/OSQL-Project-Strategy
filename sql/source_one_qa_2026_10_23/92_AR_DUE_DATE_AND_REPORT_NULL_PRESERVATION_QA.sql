-- 2026-10-23 | Read-only Snowflake DEV QA for the AR null-policy candidate.
-- DUE_DATE and RISK_ASSESSMENT_REPORT are existing APPROVED results.props[]
-- mappings. Feature PR #17 proposes NULL_POLICY=preserve for both.
-- This tests actual persisted value (incl JSON null), not approval/preview alone.
-- Run AFTER a matching release and owner-approved COMMIT to evaluate target
-- persistence. Before that, TARGET_MISSING is expected and NOT a defect verdict.
-- The literal worksheet DUE-DATE is NOT an alternate Archer source key.
-- NULL component/references stay omitted because a null ContentId is invalid.
WITH contract AS (
    SELECT column1::STRING AS FIELD_NAME,
           column2::STRING AS TRANSFORM_ID,
           column3::STRING AS PROPERTY_NAME
    FROM VALUES
      ('DUE_DATE', 'date', 'due-date'),
      ('RISK_ASSESSMENT_REPORT', 'json-text', 'risk-assessment-report')
),
raw AS (
    SELECT CONTENT_ID::STRING AS CID,
           CURATED_JSON,
           COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS SNAPSHOTS
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
source_field AS (
    SELECT r.CID, r.SNAPSHOTS, c.FIELD_NAME,
           c.TRANSFORM_ID, c.PROPERTY_NAME,
           GET(r.CURATED_JSON,c.FIELD_NAME) AS SOURCE_VALUE
    FROM raw r CROSS JOIN contract c
),
target_properties AS (
    SELECT prop.SOURCE_RECORD_ID AS CID,
           prop.METADATA_JSON:"name"::STRING AS PROPERTY_NAME,
           prop.METADATA_JSON:"value" AS TARGET_VALUE,
           prop.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH AS TARGET_HASH
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT root
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_RESULTS_DEPENDENCY e1
      ON e1.FK_SOURCE_ELEMENT_HASH=root.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH
     AND e1.DEPENDENCY_TYPE='CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT results
      ON results.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=e1.FK_TARGET_ELEMENT_HASH
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_RESULTS_DEPENDENCY e2
      ON e2.FK_SOURCE_ELEMENT_HASH=results.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH
     AND e2.DEPENDENCY_TYPE='CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT prop
      ON prop.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=e2.FK_TARGET_ELEMENT_HASH
    WHERE root.ELEMENT_TYPE='assessment-results'
      AND results.ELEMENT_TYPE='results'
      AND prop.ELEMENT_TYPE='props'
      AND root.SOURCE_SYSTEM_NAME='ARCHER'
      AND root.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND results.SOURCE_SYSTEM_NAME=root.SOURCE_SYSTEM_NAME
      AND results.SOURCE_TABLE_NAME=root.SOURCE_TABLE_NAME
      AND prop.SOURCE_SYSTEM_NAME=root.SOURCE_SYSTEM_NAME
      AND prop.SOURCE_TABLE_NAME=root.SOURCE_TABLE_NAME
      AND results.SOURCE_RECORD_ID=root.SOURCE_RECORD_ID
      AND prop.SOURCE_RECORD_ID=root.SOURCE_RECORD_ID
      AND prop.METADATA_JSON:"name"::STRING IN ('due-date','risk-assessment-report')
),
joined AS (
    SELECT s.*, t.TARGET_HASH, t.TARGET_VALUE,
           COUNT(t.TARGET_HASH) OVER (
               PARTITION BY s.CID,s.FIELD_NAME
           ) AS TARGET_PROPERTY_ROWS
    FROM source_field s
    LEFT JOIN target_properties t
      ON t.CID=s.CID AND t.PROPERTY_NAME=s.PROPERTY_NAME
),
qa AS (
    SELECT CID,FIELD_NAME,SNAPSHOTS,SOURCE_VALUE,TARGET_VALUE,
           TARGET_PROPERTY_ROWS,
           CASE
             WHEN SNAPSHOTS>1 THEN 'SOURCE_SNAPSHOT_AMBIGUOUS'
             WHEN SOURCE_VALUE IS NULL AND TARGET_HASH IS NULL
                  THEN 'SOURCE_KEY_ABSENT'
             WHEN SOURCE_VALUE IS NULL THEN 'UNEXPECTED_TARGET_FOR_ABSENT_SOURCE'
             WHEN IS_NULL_VALUE(SOURCE_VALUE) AND TARGET_HASH IS NULL
                  THEN 'EXPLICIT_NULL_TARGET_MISSING_NEEDS_COMMIT_REVIEW'
             WHEN IS_NULL_VALUE(SOURCE_VALUE) AND
                  TARGET_PROPERTY_ROWS=1 AND IS_NULL_VALUE(TARGET_VALUE)
                  THEN 'EXPLICIT_NULL_PRESERVED'
             WHEN IS_NULL_VALUE(SOURCE_VALUE)
                  THEN 'EXPLICIT_NULL_TARGET_CONFLICT'
             WHEN TYPEOF(SOURCE_VALUE)='VARCHAR' AND
                  LENGTH(TRIM(SOURCE_VALUE::STRING))=0
                  THEN 'SOURCE_EMPTY_REVIEW'
             WHEN TARGET_HASH IS NULL THEN 'POPULATED_SOURCE_TARGET_MISSING'
             WHEN TARGET_PROPERTY_ROWS>1 THEN 'DUPLICATE_TARGET_PROPERTIES'
             WHEN TRANSFORM_ID='date'
                  AND NOT REGEXP_LIKE(
                    SOURCE_VALUE::STRING,
                    '[0-9]{4}-[0-9]{2}-[0-9]{2}([Tt ].*)?')
                  THEN 'DATE_SOURCE_SHAPE_REVIEW'
             WHEN TRANSFORM_ID='date'
                  AND TRY_TO_DATE(LEFT(SOURCE_VALUE::STRING,10)) IS NULL
                  THEN 'DATE_SOURCE_INVALID'
             WHEN TRANSFORM_ID='date'
                  AND TARGET_VALUE::STRING=LEFT(SOURCE_VALUE::STRING,10)
                  THEN 'VALUE_MATCH'
             WHEN TRANSFORM_ID='json-text'
                  AND TRY_PARSE_JSON(TARGET_VALUE::STRING)=SOURCE_VALUE
                  THEN 'VALUE_MATCH'
             WHEN TRANSFORM_ID='json-text'
                  AND (IS_ARRAY(SOURCE_VALUE) OR IS_OBJECT(SOURCE_VALUE))
                  AND TARGET_VALUE IS NOT NULL
                  THEN 'VALUE_MISMATCH_OR_SHAPE_REVIEW'
             ELSE 'VALUE_MISMATCH'
           END AS QA_STATUS
    FROM joined
)
SELECT FIELD_NAME AS ARCHER_FIELD_NAME,
       QA_STATUS,
       COUNT(*) AS SOURCE_ROWS,
       COUNT(DISTINCT CID) AS DISTINCT_CONTENT_IDS,
       COUNT_IF(TARGET_VALUE IS NOT NULL) AS TARGET_VALUE_ROWS,
       MIN(CID) AS EXAMPLE_CONTENT_ID
FROM qa
GROUP BY FIELD_NAME,QA_STATUS
ORDER BY ARCHER_FIELD_NAME,QA_STATUS;
