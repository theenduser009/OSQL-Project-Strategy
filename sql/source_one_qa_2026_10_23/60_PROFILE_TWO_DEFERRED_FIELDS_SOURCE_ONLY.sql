-- Source One Profile candidates: source-only QA for two DEFERRED mappings.
-- 2026-10-23 | READ ONLY | Snowflake DEV.
-- ADD_OVERLAY and BASELINE_RECOMMENDATION are DEFERRED in current CSV.
-- Do not infer a missing target, registered Profile path, or mapped PASS;
-- no Profile runtime storage contract has been approved in Source One Cell 1.
WITH fields AS (
  SELECT column1::STRING AS ARCHER_FIELD_NAME,
         column2::STRING AS PROPOSED_PATH
  FROM VALUES
    ('ADD_OVERLAY', 'Multiple - see owner notes'),
    ('BASELINE_RECOMMENDATION', 'profile.imports[] (deferred)')
),
raw AS (
  SELECT CONTENT_ID::STRING AS CONTENT_ID, CURATED_JSON,
         COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS RAW_SNAPSHOTS
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
field_values AS (
  SELECT f.ARCHER_FIELD_NAME, f.PROPOSED_PATH,
         r.CONTENT_ID, r.RAW_SNAPSHOTS,
         GET(r.CURATED_JSON,f.ARCHER_FIELD_NAME) AS SOURCE_VALUE
  FROM raw r CROSS JOIN fields f
),
classified AS (
  SELECT *,
         TYPEOF(SOURCE_VALUE) AS SOURCE_JSON_TYPE,
         IFF(IS_ARRAY(SOURCE_VALUE),ARRAY_SIZE(SOURCE_VALUE),NULL)
             AS SOURCE_ARRAY_LENGTH,
         CASE
           WHEN SOURCE_VALUE IS NULL THEN 'SOURCE_KEY_ABSENT'
           WHEN IS_NULL_VALUE(SOURCE_VALUE) THEN 'EXPLICIT_JSON_NULL'
           WHEN TYPEOF(SOURCE_VALUE)='VARCHAR'
                AND LENGTH(TRIM(SOURCE_VALUE::STRING))=0 THEN 'SOURCE_EMPTY'
           WHEN IS_ARRAY(SOURCE_VALUE) AND ARRAY_SIZE(SOURCE_VALUE)=0
                THEN 'SOURCE_EMPTY'
           WHEN IS_OBJECT(SOURCE_VALUE)
                AND ARRAY_SIZE(OBJECT_KEYS(SOURCE_VALUE))=0
                THEN 'SOURCE_EMPTY'
           ELSE 'SOURCE_PRESENT_DEFERRED_OWNER_MAPPING_REVIEW'
         END AS QA_STATUS
  FROM field_values
)
SELECT ARCHER_FIELD_NAME, 'DEFERRED' AS MAPPING_STATUS,
       PROPOSED_PATH, QA_STATUS, SOURCE_JSON_TYPE,
       COUNT(*) AS SOURCE_ROWS,
       COUNT(DISTINCT CONTENT_ID) AS DISTINCT_CONTENT_IDS,
       COUNT_IF(RAW_SNAPSHOTS>1) AS DUPLICATE_RAW_SNAPSHOT_ROWS,
       MAX(SOURCE_ARRAY_LENGTH) AS MAX_SOURCE_ARRAY_LENGTH,
       MIN(CONTENT_ID) AS EXAMPLE_CONTENT_ID
FROM classified
GROUP BY ARCHER_FIELD_NAME, PROPOSED_PATH, QA_STATUS, SOURCE_JSON_TYPE
ORDER BY ARCHER_FIELD_NAME, QA_STATUS, SOURCE_JSON_TYPE;
