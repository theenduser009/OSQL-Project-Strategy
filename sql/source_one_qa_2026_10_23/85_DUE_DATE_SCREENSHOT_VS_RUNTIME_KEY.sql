-- Screenshot row 24 literally says DUE-DATE (hyphen).
-- Current approved runtime CSV key is DUE_DATE (underscore), not the same key.
-- 2026-10-23 | READ ONLY | Snowflake DEV; no implicit aliasing.
-- This is a source-key/name QA, NOT a target-value PASS.
WITH candidate_keys AS (
    SELECT column1::STRING AS FIELD_KEY,
           column2::STRING AS CONTEXT
    FROM VALUES
      ('DUE-DATE','OWNER_SCREENSHOT_EXACT'),
      ('DUE_DATE','CURRENT_RUNTIME_CSV_APPROVED')
),
raw AS (
    SELECT CONTENT_ID::STRING AS CID, CURATED_JSON,
           COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS SNAPSHOTS
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
candidates AS (
    SELECT k.FIELD_KEY,k.CONTEXT,r.CID,r.SNAPSHOTS,
           GET(r.CURATED_JSON,k.FIELD_KEY) AS SOURCE_VALUE
    FROM raw r CROSS JOIN candidate_keys k
),
classified AS (
    SELECT *,
        TYPEOF(SOURCE_VALUE) AS SOURCE_JSON_TYPE,
        CASE
          WHEN SOURCE_VALUE IS NULL THEN 'SOURCE_KEY_ABSENT'
          WHEN IS_NULL_VALUE(SOURCE_VALUE) THEN 'EXPLICIT_JSON_NULL'
          WHEN TYPEOF(SOURCE_VALUE)='VARCHAR'
               AND LENGTH(TRIM(SOURCE_VALUE::STRING))=0 THEN 'SOURCE_EMPTY'
          WHEN IS_ARRAY(SOURCE_VALUE) AND ARRAY_SIZE(SOURCE_VALUE)=0
               THEN 'SOURCE_EMPTY'
          ELSE 'SOURCE_PRESENT'
        END AS SOURCE_STATE
    FROM candidates
)
SELECT FIELD_KEY, CONTEXT, SOURCE_STATE, SOURCE_JSON_TYPE,
       COUNT(*) AS RAW_ROWS,
       COUNT(DISTINCT CID) AS DISTINCT_CONTENT_IDS,
       COUNT_IF(SNAPSHOTS>1) AS SOURCE_SNAPSHOT_AMBIGUOUS_ROWS,
       MIN(CID) AS EXAMPLE_CONTENT_ID,
       'NO_ALIAS_WITHOUT_OWNER_APPROVAL' AS MAPPING_DECISION
FROM classified
GROUP BY FIELD_KEY, CONTEXT, SOURCE_STATE, SOURCE_JSON_TYPE
ORDER BY FIELD_KEY, SOURCE_STATE;
