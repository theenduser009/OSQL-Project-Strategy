-- Screenshot row 27: POAMS -> POAM poam-items[] references.
-- 2026-10-23 | READ ONLY | Snowflake DEV, no DML.
-- Source: ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW.CURATED_JSON:"POAMS".
-- Mapping APPROVED, reference operator; POAM model is NOT SSP props.
-- Expect a POAM root->poam-items FACT CONTAINS relationship and child identity
-- scoped to Archer package Content ID + referenced poam ContentId.
-- POAM has historically accepted PREVIEW evidence; no current COMMIT assumed.
WITH raw AS (
    SELECT CONTENT_ID::STRING AS CID,
           CURATED_JSON:"POAMS" AS REF_VALUE,
           COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS RAW_SNAPSHOTS
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
source_state AS (
    SELECT *,
      CASE
        WHEN REF_VALUE IS NULL THEN 'SOURCE_KEY_ABSENT'
        WHEN IS_NULL_VALUE(REF_VALUE) THEN 'SOURCE_JSON_NULL'
        WHEN IS_ARRAY(REF_VALUE) AND ARRAY_SIZE(REF_VALUE)=0
          THEN 'SOURCE_EMPTY'
        ELSE 'SOURCE_PRESENT'
      END AS SOURCE_STATE
    FROM raw
),
ref_members AS (
    SELECT s.CID,
           IFF(IS_OBJECT(f.VALUE), f.VALUE:"ContentId"::STRING,
               f.VALUE::STRING) AS POAM_REFERENCE_CONTENT_ID
    FROM source_state s,
         LATERAL FLATTEN(
           INPUT => CASE
                      WHEN IS_ARRAY(s.REF_VALUE) THEN s.REF_VALUE
                      WHEN s.SOURCE_STATE='SOURCE_PRESENT'
                        THEN ARRAY_CONSTRUCT(s.REF_VALUE)
                      ELSE ARRAY_CONSTRUCT()
                    END
         ) f
    WHERE s.SOURCE_STATE='SOURCE_PRESENT'
),
source_refs AS (
    SELECT DISTINCT CID, POAM_REFERENCE_CONTENT_ID
    FROM ref_members
),
target_items AS (
    SELECT parent.SOURCE_RECORD_ID AS CID,
           child.PK_DIM_OSCAL_POAM_ELEMENT_HASH AS CHILD_HASH,
           child.OSCAL_UUID,
           child.METADATA_JSON
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT parent
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_POAM_DEPENDENCY edge
      ON edge.FK_SOURCE_ELEMENT_HASH=parent.PK_DIM_OSCAL_POAM_ELEMENT_HASH
     AND edge.DEPENDENCY_TYPE='CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT child
      ON child.PK_DIM_OSCAL_POAM_ELEMENT_HASH=edge.FK_TARGET_ELEMENT_HASH
    WHERE parent.ELEMENT_TYPE='plan-of-action-and-milestones'
      AND child.ELEMENT_TYPE='poam-items'
      AND parent.SOURCE_SYSTEM_NAME='ARCHER'
      AND parent.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND child.SOURCE_SYSTEM_NAME=parent.SOURCE_SYSTEM_NAME
      AND child.SOURCE_TABLE_NAME=parent.SOURCE_TABLE_NAME
      AND child.SOURCE_RECORD_ID=parent.SOURCE_RECORD_ID
),
source_counts AS (
    SELECT CID,
           COUNT(*) AS DISTINCT_SOURCE_REFERENCES,
           COALESCE(COUNT_IF(POAM_REFERENCE_CONTENT_ID IS NULL
               OR LENGTH(TRIM(POAM_REFERENCE_CONTENT_ID))=0),0)
             AS INVALID_REFERENCE_IDS
    FROM source_refs
    GROUP BY CID
),
matched_refs AS (
    SELECT r.CID,
           COUNT(*) AS SOURCE_REF_ROWS,
           COALESCE(COUNT_IF(t.CHILD_HASH IS NOT NULL),0) AS MATCHED_REF_ROWS
    FROM source_refs r
    LEFT JOIN target_items t
      ON t.CID=r.CID AND
         t.CHILD_HASH=MD5_BINARY(CONCAT_WS('|',
           'v1_registry_path_instance',
           'ARCHER','ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW',
           r.CID,'POAM','plan-of-action-and-milestones.poam-items[]',
           r.POAM_REFERENCE_CONTENT_ID))
    GROUP BY r.CID
),
target_counts AS (
    SELECT CID, COUNT(*) AS TARGET_ITEM_ROWS
    FROM target_items GROUP BY CID
),
qa AS (
    SELECT s.CID, s.SOURCE_STATE, s.RAW_SNAPSHOTS,
           COALESCE(sc.DISTINCT_SOURCE_REFERENCES,0) AS SOURCE_REFERENCES,
           COALESCE(sc.INVALID_REFERENCE_IDS,0) AS INVALID_REFERENCE_IDS,
           COALESCE(m.MATCHED_REF_ROWS,0) AS MATCHED_REFERENCES,
           COALESCE(tc.TARGET_ITEM_ROWS,0) AS TARGET_ITEMS,
           CASE
             WHEN s.RAW_SNAPSHOTS>1 THEN 'SOURCE_SNAPSHOT_AMBIGUOUS'
             WHEN s.SOURCE_STATE='SOURCE_KEY_ABSENT' AND
                  COALESCE(tc.TARGET_ITEM_ROWS,0)=0 THEN 'SOURCE_KEY_ABSENT'
             WHEN s.SOURCE_STATE='SOURCE_JSON_NULL' AND
                  COALESCE(tc.TARGET_ITEM_ROWS,0)=0 THEN 'SOURCE_NULL_NO_ITEM_EXPECTED'
             WHEN s.SOURCE_STATE='SOURCE_EMPTY' AND
                  COALESCE(tc.TARGET_ITEM_ROWS,0)=0 THEN 'SOURCE_EMPTY_NO_ITEM_EXPECTED'
             WHEN s.SOURCE_STATE<>'SOURCE_PRESENT'
                THEN 'UNEXPECTED_POAM_ITEMS_FOR_EMPTY_SOURCE'
             WHEN COALESCE(sc.INVALID_REFERENCE_IDS,0)>0
                THEN 'INVALID_SOURCE_REFERENCE_ID'
             WHEN COALESCE(sc.DISTINCT_SOURCE_REFERENCES,0)=0
                THEN 'SOURCE_REFERENCE_SHAPE_REVIEW'
             WHEN COALESCE(m.MATCHED_REF_ROWS,0)<
                  sc.DISTINCT_SOURCE_REFERENCES
                THEN 'POAM_TARGET_REFERENCE_MISSING_OR_NOT_COMMITTED'
             WHEN COALESCE(tc.TARGET_ITEM_ROWS,0)>
                  sc.DISTINCT_SOURCE_REFERENCES
                THEN 'EXTRA_POAM_TARGET_ITEM_REVIEW'
             ELSE 'POAM_REFERENCE_GRAPH_MATCH'
           END AS QA_STATUS
    FROM source_state s
    LEFT JOIN source_counts sc ON sc.CID=s.CID
    LEFT JOIN matched_refs m ON m.CID=s.CID
    LEFT JOIN target_counts tc ON tc.CID=s.CID
)
SELECT 'POAMS' AS ARCHER_FIELD_NAME,
       'plan-of-action-and-milestones.poam-items[]' AS TARGET_PATH,
       QA_STATUS, COUNT(*) AS RAW_ROWS,
       COUNT(DISTINCT CID) AS DISTINCT_CONTENT_IDS,
       SUM(SOURCE_REFERENCES) AS SOURCE_REFERENCES,
       SUM(MATCHED_REFERENCES) AS MATCHED_TARGET_REFERENCES,
       SUM(TARGET_ITEMS) AS TOTAL_TARGET_ITEM_LINKS,
       MIN(CID) AS EXAMPLE_CONTENT_ID
FROM qa GROUP BY QA_STATUS
ORDER BY QA_STATUS;
