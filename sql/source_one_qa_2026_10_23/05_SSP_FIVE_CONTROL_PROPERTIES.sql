-- Screenshot-only QA: the FIVE Control Implementation fields targeting SSP
-- System Characteristics props[] (excludes all other SSP source fields).
-- 2026-10-23 | READ ONLY | Snowflake DEV. No DML / registry updates.
-- Each approved property is compared to the exact Archer CURATED_JSON key.
-- A source key absent in every record is NOT a populated mapping failure.
-- Direct structured values need shape review; canonical json-text compares
-- parsed source and parsed stored JSON (object key order is irrelevant).
WITH field_contract AS (
  SELECT column1::STRING AS SOURCE_FIELD,
         column2::STRING AS TRANSFORM_ID,
         column3::STRING AS PROPERTY_NAME
  FROM VALUES
    ('PCT_CURRENT_CONTROL_RISK_THRESHOLD', 'direct',
     'pct-current-control-risk-threshold'),
    ('PCT_OF_SATISFIED_CONTROLS', 'direct',
     'pct-of-satisfied-controls'),
    ('LINK_CNSS_CONTROLS_BY_AVAILABILITY_RATING', 'direct',
     'link-cnss-controls-by-availability-rating'),
    ('EXPORT_CONTROLLED_DATA_ITARAR_IF_APPLICABLE', 'direct',
     'export-controlled-data-itarar-if-applicable'),
    ('HELPER_ALLOCATED_CONTROLS', 'json-text',
     'helper-allocated-controls')
),
raw AS (
  SELECT CONTENT_ID::STRING AS CID, CURATED_JSON,
         COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS SNAPSHOTS
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
source_fields AS (
  SELECT r.CID, r.SNAPSHOTS,
         m.SOURCE_FIELD, m.TRANSFORM_ID, m.PROPERTY_NAME,
         GET(r.CURATED_JSON, m.SOURCE_FIELD) AS SOURCE_VALUE
  FROM raw r CROSS JOIN field_contract m
),
prepared AS (
  SELECT *,
    CASE
      WHEN SOURCE_VALUE IS NULL THEN 'SOURCE_KEY_ABSENT'
      WHEN IS_NULL_VALUE(SOURCE_VALUE) THEN 'EXPLICIT_JSON_NULL'
      WHEN TYPEOF(SOURCE_VALUE)='VARCHAR'
           AND LENGTH(TRIM(SOURCE_VALUE::STRING))=0 THEN 'SOURCE_EMPTY'
      WHEN IS_ARRAY(SOURCE_VALUE) AND ARRAY_SIZE(SOURCE_VALUE)=0
           THEN 'SOURCE_EMPTY'
      WHEN IS_OBJECT(SOURCE_VALUE) AND ARRAY_SIZE(OBJECT_KEYS(SOURCE_VALUE))=0
           THEN 'SOURCE_EMPTY'
      ELSE 'SOURCE_PRESENT'
    END AS SOURCE_STATE,
    CASE
      WHEN TRANSFORM_ID='json-text' THEN 'JSON_TEXT'
      WHEN TYPEOF(SOURCE_VALUE) IN ('VARCHAR','INTEGER','DECIMAL',
                                     'DOUBLE','BOOLEAN') THEN 'DIRECT_SCALAR'
      ELSE 'SHAPE_REVIEW'
    END AS VALUE_SHAPE
  FROM source_fields
),
target_props AS (
  SELECT child.SOURCE_RECORD_ID AS CID,
         child.METADATA_JSON:"name"::STRING AS PROPERTY_NAME,
         child.METADATA_JSON:"value" AS TARGET_VALUE,
         child.PK_OSCAL_SSP_ELEMENT_HASH AS TARGET_HASH
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT parent
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY e
    ON e.FK_SOURCE_ELEMENT_HASH=parent.PK_OSCAL_SSP_ELEMENT_HASH
   AND e.DEPENDENCY_TYPE='CONTAINS'
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT child
    ON child.PK_OSCAL_SSP_ELEMENT_HASH=e.FK_TARGET_ELEMENT_HASH
  WHERE parent.ELEMENT_TYPE='system-characteristics'
    AND child.ELEMENT_TYPE='props'
    AND parent.SOURCE_SYSTEM_NAME='ARCHER'
    AND parent.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND child.SOURCE_SYSTEM_NAME=parent.SOURCE_SYSTEM_NAME
    AND child.SOURCE_TABLE_NAME=parent.SOURCE_TABLE_NAME
    AND child.SOURCE_RECORD_ID=parent.SOURCE_RECORD_ID
),
matched_counts AS (
  SELECT s.CID, s.SOURCE_FIELD, s.TRANSFORM_ID, s.SNAPSHOTS,
         s.SOURCE_STATE, s.VALUE_SHAPE, s.SOURCE_VALUE,
         COUNT(t.TARGET_HASH) AS TARGET_ROWS,
         COALESCE(COUNT_IF(IS_NULL_VALUE(t.TARGET_VALUE)),0) AS TARGET_JSON_NULLS,
         COALESCE(COUNT_IF(
           CASE
             WHEN s.VALUE_SHAPE='JSON_TEXT'
               THEN TRY_PARSE_JSON(t.TARGET_VALUE::STRING)=s.SOURCE_VALUE
             WHEN s.VALUE_SHAPE='DIRECT_SCALAR'
               THEN t.TARGET_VALUE::STRING=TRIM(s.SOURCE_VALUE::STRING)
             ELSE FALSE
           END
         ),0) AS MATCHED_TARGET_ROWS
  FROM prepared s
  LEFT JOIN target_props t
    ON t.CID=s.CID AND t.PROPERTY_NAME=s.PROPERTY_NAME
  GROUP BY ALL
),
qa AS (
  SELECT *,
    CASE
      WHEN SNAPSHOTS>1 THEN 'SOURCE_SNAPSHOT_AMBIGUOUS'
      WHEN SOURCE_STATE='SOURCE_KEY_ABSENT' AND TARGET_ROWS>0
        THEN 'UNEXPECTED_TARGET_ABSENT_SOURCE'
      WHEN SOURCE_STATE='SOURCE_KEY_ABSENT' THEN 'SOURCE_KEY_ABSENT'
      WHEN SOURCE_STATE='SOURCE_EMPTY' AND TARGET_ROWS>0
        THEN 'TARGET_PRESENT_EMPTY_SOURCE_REVIEW'
      WHEN SOURCE_STATE='SOURCE_EMPTY' THEN 'SOURCE_EMPTY'
      WHEN SOURCE_STATE='EXPLICIT_JSON_NULL' AND
           TARGET_ROWS=1 AND TARGET_JSON_NULLS=1
        THEN 'EXPLICIT_NULL_PRESERVED'
      WHEN SOURCE_STATE='EXPLICIT_JSON_NULL' AND TARGET_ROWS=0
        THEN 'PRESERVED_NULL_TARGET_MISSING'
      WHEN SOURCE_STATE='EXPLICIT_JSON_NULL'
        THEN 'NULL_SOURCE_TARGET_CONFLICT'
      WHEN TARGET_ROWS=0 THEN 'POPULATED_SOURCE_TARGET_MISSING'
      WHEN TARGET_ROWS>1 THEN 'MULTIPLE_TARGET_PROPERTIES_REVIEW'
      WHEN VALUE_SHAPE='SHAPE_REVIEW' THEN 'DIRECT_VALUE_SHAPE_REVIEW'
      WHEN MATCHED_TARGET_ROWS=1 THEN 'VALUE_MATCH'
      ELSE 'VALUE_MISMATCH'
    END AS QA_STATUS
  FROM matched_counts
)
SELECT SOURCE_FIELD AS ARCHER_FIELD_NAME,
       TRANSFORM_ID, QA_STATUS,
       COUNT(*) AS SOURCE_ROWS,
       COUNT(DISTINCT CID) AS DISTINCT_CONTENT_IDS,
       SUM(TARGET_ROWS) AS TARGET_ROWS,
       SUM(MATCHED_TARGET_ROWS) AS MATCHED_TARGET_ROWS,
       MIN(CID) AS EXAMPLE_CONTENT_ID
FROM qa
GROUP BY SOURCE_FIELD, TRANSFORM_ID, QA_STATUS
ORDER BY ARCHER_FIELD_NAME, QA_STATUS;
