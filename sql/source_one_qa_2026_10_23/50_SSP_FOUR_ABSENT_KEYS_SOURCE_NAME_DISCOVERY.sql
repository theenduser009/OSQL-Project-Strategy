-- Source One: four approved SSP property keys reported absent by 2026-10-23 QA.
-- READ-ONLY SNOWFLAKE DEV. This is a name/shape investigation,
-- not an approval to alias other fields or reinterpret business meaning.
-- The _CURRENT_CONTROL_RISK_THRESHOLD and _OF_SATISFIED_CONTROLS keys
-- are separate and must not be used as silent replacements.
WITH expected AS (
  SELECT column1::STRING AS EXPECTED_ARCHER_FIELD,
         column2::STRING AS CANDIDATE_PATTERN
  FROM VALUES
    ('PCT_CURRENT_CONTROL_RISK_THRESHOLD', '%CONTROL%RISK%THRESHOLD%'),
    ('PCT_OF_SATISFIED_CONTROLS', '%SATISFIED%CONTROL%'),
    ('LINK_CNSS_CONTROLS_BY_AVAILABILITY_RATING', '%AVAILABILITY%'),
    ('EXPORT_CONTROLLED_DATA_ITARAR_IF_APPLICABLE', '%EXPORT%CONTROL%')
),
raw AS (
  SELECT CONTENT_ID::STRING AS CONTENT_ID, CURATED_JSON
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
all_keys AS (
  SELECT r.CONTENT_ID, UPPER(k.VALUE::STRING) AS SOURCE_JSON_KEY,
         k.VALUE::STRING AS SOURCE_JSON_KEY_EXACT,
         GET(r.CURATED_JSON, k.VALUE::STRING) AS SOURCE_VALUE
  FROM raw r,
       LATERAL FLATTEN(INPUT=>OBJECT_KEYS(r.CURATED_JSON)) k
),
candidates AS (
  SELECT e.EXPECTED_ARCHER_FIELD, k.SOURCE_JSON_KEY_EXACT,
         IFF(k.SOURCE_JSON_KEY_EXACT=e.EXPECTED_ARCHER_FIELD,
             'EXACT_KEY','SIMILAR_NAME_ONLY_OWNER_REVIEW') AS KEY_CLASS,
         k.CONTENT_ID,
         CASE
           WHEN k.SOURCE_VALUE IS NULL THEN 'SOURCE_KEY_ABSENT'
           WHEN IS_NULL_VALUE(k.SOURCE_VALUE) THEN 'JSON_NULL'
           WHEN TYPEOF(k.SOURCE_VALUE)='VARCHAR'
                AND LENGTH(TRIM(k.SOURCE_VALUE::STRING))=0 THEN 'EMPTY_STRING'
           ELSE 'PRESENT_NON_NULL'
         END AS SOURCE_STATE,
         TYPEOF(k.SOURCE_VALUE) AS SOURCE_JSON_TYPE
  FROM expected e JOIN all_keys k
    ON k.SOURCE_JSON_KEY LIKE e.CANDIDATE_PATTERN
),
matched AS (
  SELECT EXPECTED_ARCHER_FIELD, SOURCE_JSON_KEY_EXACT,
         KEY_CLASS, SOURCE_STATE, SOURCE_JSON_TYPE,
         COUNT(*) AS RAW_ROWS,
         COUNT(DISTINCT CONTENT_ID) AS DISTINCT_CONTENT_IDS
  FROM candidates
  GROUP BY EXPECTED_ARCHER_FIELD, SOURCE_JSON_KEY_EXACT,
           KEY_CLASS, SOURCE_STATE, SOURCE_JSON_TYPE
)
SELECT e.EXPECTED_ARCHER_FIELD,
       COALESCE(m.SOURCE_JSON_KEY_EXACT, '[NO SIMILAR KEY FOUND]')
          AS OBSERVED_SOURCE_KEY,
       COALESCE(m.KEY_CLASS,'NO_CANDIDATE_KEY_FOUND') AS KEY_CLASS,
       m.SOURCE_STATE, m.SOURCE_JSON_TYPE,
       COALESCE(m.RAW_ROWS,0) AS RAW_ROWS,
       COALESCE(m.DISTINCT_CONTENT_IDS,0) AS DISTINCT_CONTENT_IDS
FROM expected e
LEFT JOIN matched m ON m.EXPECTED_ARCHER_FIELD=e.EXPECTED_ARCHER_FIELD
ORDER BY e.EXPECTED_ARCHER_FIELD, KEY_CLASS, OBSERVED_SOURCE_KEY;
