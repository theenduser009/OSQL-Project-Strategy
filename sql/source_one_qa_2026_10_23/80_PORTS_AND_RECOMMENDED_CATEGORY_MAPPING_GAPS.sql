-- Screenshot rows 28-29: fields requiring mapping-owner action, not
-- "target matched" assertions. READ ONLY — Snowflake DEV (2026-10-23).
--
-- PORTS_PROTOCOLS_AND_SERVICES_MANAGEMENT_PPSM: exact field is pictured in
-- owner's workbook but is ABSENT from current Source One runtime mapping CSV.
-- RECOMMENDED_SECURITY_CATEGORY: present in runtime CSV, but has status
-- BLOCKED_IF_POPULATED with reject-populated transformation; a populated
-- source requires review, NOT automatic mapping to impact level.
-- Screenshot row 18 has no reliable Archer field name, so cannot be queried.
WITH contracts AS (
    SELECT column1::STRING AS ARCHER_FIELD_NAME,
           column2::STRING AS CURRENT_MAPPING_STATUS
    FROM VALUES
      ('PORTS_PROTOCOLS_AND_SERVICES_MANAGEMENT_PPSM',
       'NOT_IN_EXECUTABLE_MAPPING_CSV'),
      ('RECOMMENDED_SECURITY_CATEGORY','BLOCKED_IF_POPULATED')
),
raw AS (
    SELECT CONTENT_ID::STRING AS CID, CURATED_JSON,
           COUNT(*) OVER (PARTITION BY CONTENT_ID::STRING) AS SOURCE_SNAPSHOTS
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
fields AS (
    SELECT c.ARCHER_FIELD_NAME,c.CURRENT_MAPPING_STATUS,r.CID,
           r.SOURCE_SNAPSHOTS,
           GET(r.CURATED_JSON,c.ARCHER_FIELD_NAME) AS SOURCE_VALUE
    FROM raw r CROSS JOIN contracts c
),
classified AS (
    SELECT *,
        TYPEOF(SOURCE_VALUE) AS SOURCE_JSON_TYPE,
        CASE
          WHEN SOURCE_VALUE IS NULL THEN 'SOURCE_KEY_ABSENT'
          WHEN IS_NULL_VALUE(SOURCE_VALUE) THEN 'EXPLICIT_JSON_NULL'
          WHEN TYPEOF(SOURCE_VALUE)='VARCHAR'
               AND LENGTH(TRIM(SOURCE_VALUE::STRING))=0 THEN 'SOURCE_EMPTY'
          WHEN IS_ARRAY(SOURCE_VALUE) AND ARRAY_SIZE(SOURCE_VALUE)=0
               THEN 'SOURCE_EMPTY'
          WHEN IS_OBJECT(SOURCE_VALUE)
               AND ARRAY_SIZE(OBJECT_KEYS(SOURCE_VALUE))=0
               THEN 'SOURCE_EMPTY'
          ELSE 'SOURCE_POPULATED'
        END AS SOURCE_STATE
    FROM fields
)
SELECT ARCHER_FIELD_NAME,CURRENT_MAPPING_STATUS,SOURCE_STATE,
       SOURCE_JSON_TYPE,
       CASE
         WHEN CURRENT_MAPPING_STATUS='NOT_IN_EXECUTABLE_MAPPING_CSV'
          AND SOURCE_STATE='SOURCE_POPULATED'
           THEN 'POPULATED_SOURCE_NEEDS_OWNER_MAPPING_DECISION'
         WHEN CURRENT_MAPPING_STATUS='BLOCKED_IF_POPULATED'
          AND SOURCE_STATE='SOURCE_POPULATED'
           THEN 'BLOCKED_POPULATED_SOURCE_NEEDS_OWNER_DECISION'
         ELSE 'NOT_POPULATED_NO_TARGET_PASS_POSSIBLE'
       END AS QA_DISPOSITION,
       COUNT(*) AS RAW_ROWS,
       COUNT(DISTINCT CID) AS DISTINCT_CONTENT_IDS,
       COUNT_IF(SOURCE_SNAPSHOTS>1) AS AMBIGUOUS_SOURCE_SNAPSHOT_ROWS,
       MIN(CID) AS EXAMPLE_CONTENT_ID
FROM classified
GROUP BY ARCHER_FIELD_NAME,CURRENT_MAPPING_STATUS,SOURCE_STATE,SOURCE_JSON_TYPE
ORDER BY ARCHER_FIELD_NAME,SOURCE_STATE;
