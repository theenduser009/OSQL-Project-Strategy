-- SSP / System Characteristics | FIPS 199 | READ ONLY
-- Native confidentiality can originate from another approved Archer field
-- when RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY is NULL.
SELECT
    a.CONTENT_ID AS ARCHER_RECORD_NUMBER,
    'SSP - System Characteristics' AS OSCAL_MODEL,
    'FIPS 199' AS STANDARD_REFERENCE,
    a.CURATED_JSON:RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY AS ARCHER_PAYLOAD,
    d.METADATA_JSON:"security-objective-confidentiality" AS OSCAL_VALUE,
    d.METADATA_JSON AS OSCAL_PAYLOAD,
    p.METADATA_JSON:"value"::STRING AS ARCHER_FIELD_LINEAGE
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT d
    ON d.SOURCE_RECORD_ID = a.CONTENT_ID::STRING
   AND d.ELEMENT_TYPE = 'security-impact-level'
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT p
    ON p.SOURCE_RECORD_ID = a.CONTENT_ID::STRING
   AND p.ELEMENT_TYPE = 'props'
   AND p.METADATA_JSON:"name"::STRING = 'source-field'
   AND p.METADATA_JSON:"value"::STRING = 'RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY'
ORDER BY a.CONTENT_ID
LIMIT 20;
