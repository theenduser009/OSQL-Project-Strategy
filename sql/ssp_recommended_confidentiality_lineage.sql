-- SSP CIA lineage (READ ONLY). Change ARCHER_FIELD once below.
-- Approved field-to-OSCAL path is shown even if the source value is JSON null.
-- Persisted "source-field" props exist only for contributing populated fields.
WITH field AS (
    SELECT 'RECOMMENDED_CONFIDENTIALITY_CONTROL_CATEGORY' AS ARCHER_FIELD
), target AS (
    SELECT ARCHER_FIELD,
        CASE
            WHEN ARCHER_FIELD ILIKE '%CONFIDENTIALITY%' THEN 'security-objective-confidentiality'
            WHEN ARCHER_FIELD ILIKE '%INTEGRITY%' THEN 'security-objective-integrity'
            WHEN ARCHER_FIELD ILIKE '%AVAILABILITY%' THEN 'security-objective-availability'
        END AS OSCAL_MEMBER
    FROM field
)
SELECT
    a.CONTENT_ID AS ARCHER_CONTENT_ID,
    t.ARCHER_FIELD,
    GET(a.CURATED_JSON, t.ARCHER_FIELD) AS ARCHER_PAYLOAD,
    CASE
        WHEN GET(a.CURATED_JSON, t.ARCHER_FIELD) IS NULL THEN 'MISSING_KEY'
        WHEN IS_NULL_VALUE(GET(a.CURATED_JSON, t.ARCHER_FIELD)) THEN 'JSON_NULL'
        ELSE 'POPULATED'
    END AS ARCHER_STATUS,
    'SSP - System Characteristics' AS OSCAL_MODEL,
    'system-security-plan.system-characteristics.security-impact-level.' || t.OSCAL_MEMBER AS APPROVED_OSCAL_PATH,
    d.ELEMENT_TYPE AS STORED_ELEMENT_TYPE,
    GET(d.METADATA_JSON, t.OSCAL_MEMBER) AS OSCAL_VALUE,
    d.METADATA_JSON AS OSCAL_PAYLOAD,
    p.METADATA_JSON:"value"::STRING AS STORED_SOURCE_FIELD_PROP
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW a
CROSS JOIN target t
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT d
    ON d.SOURCE_RECORD_ID = a.CONTENT_ID::STRING AND d.ELEMENT_TYPE = 'security-impact-level'
LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT p
    ON p.SOURCE_RECORD_ID = a.CONTENT_ID::STRING AND p.ELEMENT_TYPE = 'props'
   AND p.METADATA_JSON:"name"::STRING = 'source-field'
   AND p.METADATA_JSON:"value"::STRING = t.ARCHER_FIELD
WHERE t.OSCAL_MEMBER IS NOT NULL
ORDER BY a.CONTENT_ID
LIMIT 30;
